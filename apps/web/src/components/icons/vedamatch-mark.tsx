import Image from "next/image";

/**
 * Знак VedaMatch: земной шар над «M» из двух горных шевронов.
 *
 * Это сам фирменный рисунок, а не его векторное приближение: глобус в нём
 * фотографический, и повторить его контурами не выходило — прежняя версия
 * рисовала «намёк на материки», и знак в шапке заметно отличался от того,
 * что на иконке приложения и на превью ссылки.
 *
 * Тёмная тема закрыта вторым файлом, а не фильтром: «M» в растре запечена
 * тёмно-синим и на подложке #0A0614 тонет. `scripts/generate-icons.mjs`
 * собирает обе версии из одного исходника, перекрашивая только букву —
 * глобус в обеих одинаковый.
 *
 * Оба файла в разметке всегда, переключает их `dark:`: вариант следует за
 * выбранной темой, а не за системной, и переживает смену темы без запроса
 * к серверу. Скрытая версия к моменту переключения уже в кеше браузера.
 *
 * `loading="eager"` — знак стоит в шапке, то есть выше сгиба на каждой
 * странице: с отложенной загрузкой он проявляется уже после отрисовки, и
 * шапка на глазах дёргается. `priority` при этом не ставится — он добавил
 * бы в <head> preload обеих версий, включая заведомо скрытую.
 */
export function VedaMatchMark({
  className = "h-8 w-8",
  title = "VedaMatch",
}: {
  className?: string;
  title?: string;
}) {
  // 144 — самый крупный показ знака (48 CSS-пикселей в шапке лендинга) при
  // тройной плотности пикселей.
  const sizes = "144px";

  return (
    <span className={`relative inline-block shrink-0 ${className}`}>
      <Image
        src="/brand/mark.png"
        alt={title}
        fill
        sizes={sizes}
        loading="eager"
        className="object-contain dark:hidden"
      />
      {/* Подпись только у одной из копий: для чтения с экрана знак один. */}
      <Image
        src="/brand/mark-dark.png"
        alt=""
        aria-hidden
        fill
        sizes={sizes}
        loading="eager"
        className="hidden object-contain dark:block"
      />
    </span>
  );
}
