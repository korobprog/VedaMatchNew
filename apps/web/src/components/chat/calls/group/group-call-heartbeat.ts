/**
 * «Я ещё здесь» глазами клиента.
 *
 * Сервер убирает участника, от которого не было подтверждения дольше
 * `GROUP_CALL_TTL_MS` (`apps/api/.../group/group-call-room.ts`), — у
 * остальных он просто исчезает из списка. Обратная сторона того же
 * правила нужна и здесь: если подтверждения не уходят (вкладка в
 * офлайне, портал недоступен), то нас в комнате уже нет, сколько бы
 * соединений ни оставалось открытыми. Показывать в этот момент
 * «разговор» — врать: остальные нас не слышат и не видят.
 *
 * Числа не независимые: тайм-аут — это ровно три пропущенных
 * подтверждения, и держать их согласованными — задача этого модуля, а не
 * двух случайных констант в разных файлах.
 */

/** Как часто подтверждаем присутствие. */
export const GROUP_CALL_HEARTBEAT_MS = 15_000;

/** Сколько сервер ждёт подтверждения, прежде чем убрать участника. */
export const GROUP_CALL_TTL_MS = 45_000;

/**
 * Сколько подряд неудачных подтверждений означают, что сервер нас уже
 * убрал. Короткая просадка сети (лифт, Wi-Fi → LTE) сюда не попадает: она
 * укладывается в один-два пропуска.
 */
export const HEARTBEAT_FAILURES_BEFORE_LOST = Math.ceil(
  GROUP_CALL_TTL_MS / GROUP_CALL_HEARTBEAT_MS,
);

export function heartbeatLost(consecutiveFailures: number): boolean {
  return consecutiveFailures >= HEARTBEAT_FAILURES_BEFORE_LOST;
}

/** Что показать, когда подтверждения перестали доходить. */
export const HEARTBEAT_LOST_MESSAGE =
  "Связь с порталом пропала — вас вывели из звонка";
