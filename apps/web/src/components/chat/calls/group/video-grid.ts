"use client";

/**
 * Раскладка плиток в групповом звонке (VED-293, этап 4).
 *
 * Порт одноимённого модуля приложения (`apps/mobile/src/lib/group-calls/`)
 * — по тому же правилу, по которому сюда уже перенесены `group-call-peers`
 * и `speaking-state`: раскладка обязана совпадать на телефоне и на сайте,
 * иначе разговор втроём выглядит у всех по-разному. Обоснование правила —
 * в шапке оригинала, здесь та же таблица случаев.
 *
 * Правило и обоснование:
 *
 * - **Двое, телефон вертикально — один столбец, две строки.** Плитки
 *   получаются широкими и низкими (примерно как кадр камеры, положенный
 *   набок), лицо занимает середину. Альтернатива — два узких столбца во всю
 *   высоту: на экране 360 точек это две полосы по 180, где от лица остаётся
 *   вертикальная щель. Вертикальный экран режут поперёк, а не вдоль.
 * - **Трое вертикально — один столбец, три строки.** По той же причине; да,
 *   плитки становятся приземистыми, но каждая остаётся во всю ширину. Сетка
 *   2×2 с пустым местом здесь хуже: пустая клетка читается как «кто-то
 *   отвалился».
 * - **Четверо — всегда 2×2.** Это единственный состав, где обе стороны
 *   делятся поровну, и он выглядит одинаково в любой ориентации.
 * - **Широкий экран (сайт, телефон боком) — наоборот, режем вдоль:**
 *   двое рядом, трое в ряд. Там лишняя ширина, а не высота.
 *
 * Все плитки равны по размеру. «Говорящего крупнее» здесь нет намеренно:
 * хозяин комнаты особых прав не имеет (`group-call-room.ts`), и делать
 * кого-то главным на экране значило бы завести эти права с чёрного хода.
 *
 * Исключение одно — показ экрана (VED-360), и оно не про человека, а про
 * содержимое: слайд или таблицу в плитке на четверть экрана не прочитать.
 * Тогда раскладка другая — «сцена»: экран крупно, остальные полосой
 * (`splitStage`, `stageStrip`).
 */

export interface GridLayout {
  columns: number;
  rows: number;
}

export function videoGridLayout(tileCount: number, wide: boolean): GridLayout {
  const count = Number.isFinite(tileCount)
    ? Math.max(Math.floor(tileCount), 0)
    : 0;
  if (count === 0) return { columns: 0, rows: 0 };
  if (count === 1) return { columns: 1, rows: 1 };
  if (count >= 4) return { columns: 2, rows: 2 };
  // Двое и трое: вдоль длинной стороны экрана.
  return wide ? { columns: count, rows: 1 } : { columns: 1, rows: count };
}

/**
 * Доля площади, которая достаётся одной плитке. Не украшение: по ней
 * экран считает высоту плитки, а число плиток в ряду задаёт `columns`.
 */
export function tileFraction(layout: GridLayout): {
  width: number;
  height: number;
} {
  if (layout.columns === 0 || layout.rows === 0)
    return { width: 0, height: 0 };
  return { width: 1 / layout.columns, height: 1 / layout.rows };
}

/**
 * Разделить плитки на «сцену» и полосу (VED-360).
 *
 * На сцену идёт ЧУЖОЙ экран. Свой — нет, он остаётся обычной плиткой в
 * сетке: свой экран у человека и так перед глазами, а крупная копия
 * показываемого экрана на том же экране даёт бесконечный коридор
 * отражений. `null` — сцены нет, раскладка обычная (`videoGridLayout`).
 *
 * Экран на сцене один: сервер не даёт показывать двоим. Если по старому
 * составу их всё же двое, берётся первый по порядку комнаты — второй
 * остаётся в полосе, а не пропадает.
 */
export function splitStage<
  T extends { userId: string; isSelf: boolean; screen: boolean },
>(tiles: readonly T[]): { stage: T | null; strip: T[] } {
  const stage = tiles.find((tile) => tile.screen && !tile.isSelf) ?? null;
  if (!stage) return { stage: null, strip: [...tiles] };
  return { stage, strip: tiles.filter((tile) => tile !== stage) };
}

/**
 * Где полоса остальных при сцене: сбоку на широком экране (ширины лишней,
 * а экран обычно шире, чем высок), снизу на вертикальном телефоне.
 * Пустая полоса не рисуется вовсе — в живой комнате её не бывает (своя
 * плитка всегда в полосе), но раскладка не должна на это полагаться.
 */
export function stageStrip(
  stripCount: number,
  wide: boolean,
): "side" | "bottom" | "none" {
  if (!Number.isFinite(stripCount) || stripCount <= 0) return "none";
  return wide ? "side" : "bottom";
}
