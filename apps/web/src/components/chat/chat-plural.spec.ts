import { describe, expect, it } from "vitest";
import { plural, withPlural } from "./chat-plural";

describe("plural", () => {
  it("берёт единственное для 1, 21, 101", () => {
    for (const n of [1, 21, 101, 131]) expect(plural(n, "канал", "канала", "каналов")).toBe("канал");
  });

  it("берёт форму «канала» для 2–4", () => {
    for (const n of [2, 3, 4, 22, 43])
      expect(plural(n, "канал", "канала", "каналов")).toBe("канала");
  });

  it("одиннадцать–четырнадцать — исключение", () => {
    for (const n of [11, 12, 13, 14, 111])
      expect(plural(n, "канал", "канала", "каналов")).toBe("каналов");
  });

  it("ноль и пять — множественное", () => {
    expect(plural(0, "канал", "канала", "каналов")).toBe("каналов");
    expect(plural(5, "канал", "канала", "каналов")).toBe("каналов");
  });

  it("не спотыкается о минус и дробь", () => {
    expect(plural(-1, "канал", "канала", "каналов")).toBe("канал");
    expect(plural(2.7, "канал", "канала", "каналов")).toBe("канала");
  });
});

describe("withPlural", () => {
  it("ставит число рядом со словом", () => {
    expect(withPlural(1, "участник", "участника", "участников")).toBe(
      "1 участник",
    );
    expect(withPlural(5, "участник", "участника", "участников")).toBe(
      "5 участников",
    );
  });
});
