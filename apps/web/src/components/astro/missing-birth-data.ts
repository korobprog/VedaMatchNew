/**
 * Совместимость упирается в незаполненные данные рождения чаще всего —
 * своих либо чужих. Сервер отвечает на это обычной ошибкой, и раньше она
 * выводилась голой красной строкой: человек, пришедший из Знакомств,
 * оказывался в тупике без подсказки, куда идти.
 *
 * Разбор вынесен отдельно от компонента: это чистая логика, и она
 * проверяется без DOM.
 */

/** Куда ведём заполнять: там же, где строится собственная карта. */
export const BIRTH_DATA_URL = "/astro/chart";

export function isMissingBirthDataError(message: string | null): boolean {
  if (!message) return false;
  return /данные рождения/i.test(message);
}

/**
 * Подсказка под ошибкой. Возвращает `null`, когда дело не в данных
 * рождения: выдумывать действие для чужой ошибки нельзя — ссылка «заполнить
 * данные» на сбое сети только собьёт с толку.
 */
export function birthDataHint(
  message: string | null,
): { text: string; href: string; action: string } | null {
  if (!isMissingBirthDataError(message)) return null;
  return {
    text: "Совместимость считается по двум картам рождения, поэтому без ваших данных её не посчитать.",
    href: BIRTH_DATA_URL,
    action: "Заполнить данные рождения",
  };
}
