import { describe, expect, it } from "vitest";
import {
  TITLE_SOFT_MAX,
  capsTitle,
  deriveTaskTitle,
  normalizeTaskTitle,
  taskFromDraft,
  titleToSave,
} from "./task-title";

describe("normalizeTaskTitle", () => {
  it("убирает пробелы по краям", () => {
    expect(normalizeTaskTitle("  Починить кнопку  ")).toBe("Починить кнопку");
  });

  it("схлопывает перевод строки в пробел", () => {
    expect(normalizeTaskTitle("Починить\nкнопку")).toBe("Починить кнопку");
  });

  it("схлопывает вставленный из письма текст с двойными пробелами", () => {
    expect(normalizeTaskTitle("Починить \n\n  кнопку")).toBe("Починить кнопку");
  });
});

describe("titleToSave", () => {
  it("без изменений сохранять нечего", () => {
    expect(titleToSave("Починить кнопку", "Починить кнопку")).toBeNull();
  });

  it("разница только в пробелах — тоже нечего", () => {
    expect(titleToSave("  Починить  кнопку ", "Починить кнопку")).toBeNull();
  });

  it("пустое название не сохраняется", () => {
    expect(titleToSave("   ", "Починить кнопку")).toBeNull();
    expect(titleToSave("\n", "Починить кнопку")).toBeNull();
  });

  it("новое название возвращается очищенным", () => {
    expect(titleToSave(" Починить\nкнопку ", "Старое")).toBe("Починить кнопку");
  });
});

describe("deriveTaskTitle — первое предложение (VED-647)", () => {
  it("берёт первое предложение, подробности остаются в описании", () => {
    expect(
      deriveTaskTitle(
        "Починить ссылки в письмах. Они ведут на старый домен, надо заменить.",
      ),
    ).toBe("Починить ссылки в письмах.");
  });

  it("перевод строки — готовая граница", () => {
    expect(deriveTaskTitle("Ссылки в письмах\nВедут на старый домен")).toBe(
      "Ссылки в письмах",
    );
  });

  it("выделение ЗАГЛАВНЫМИ заголовок больше не собирает", () => {
    expect(
      deriveTaskTitle(
        "ИЗМЕНИ ПРАВИЛА ДЛЯ СОЗДАНИЯ ЗАГОЛОВКА задачи. Пусть как раньше.",
      ),
    ).toBe("ИЗМЕНИ ПРАВИЛА ДЛЯ СОЗДАНИЯ ЗАГОЛОВКА задачи.");
  });

  it("короткий обрывок не заголовок — берётся следующая граница", () => {
    expect(
      deriveTaskTitle(
        "Не работает. Кнопка сохранить в карточке задачи молчит.",
      ),
    ).toBe("Не работает. Кнопка сохранить в карточке задачи молчит.");
  });

  it("без границ — по слову в пределах лимита, с многоточием", () => {
    const words = Array.from({ length: 30 }, () => "слово").join(" ");
    const title = deriveTaskTitle(words);
    expect(title.endsWith("…")).toBe(true);
    expect(title.length).toBeLessThanOrEqual(TITLE_SOFT_MAX + 1);
  });
});

describe("taskFromDraft", () => {
  it("описание уходит целиком, заголовок — первое предложение (VED-324)", () => {
    const text =
      "Кнопка сохранить в карточке не срабатывает. Повторяется на телефоне.";
    const fields = taskFromDraft(text);
    expect(fields.title).toBe("Кнопка сохранить в карточке не срабатывает.");
    expect(fields.description).toBe(text);
  });

  it("одно предложение — заголовок без дубля в описании", () => {
    expect(taskFromDraft("Обновить сертификат на проде")).toEqual({
      title: "Обновить сертификат на проде",
      description: "",
    });
  });

  it("короткая строка не дублируется в описании", () => {
    // Иначе значок «в карточке есть текст» врёт у каждой односложной задачи.
    const fields = taskFromDraft("Обновить сертификат", "Обновить сертификат");
    expect(fields.title).toBe("Обновить сертификат");
    expect(fields.description).toBe("");
  });

  it("свой заголовок побеждает выведенный, а описание остаётся", () => {
    const fields = taskFromDraft("Обновить сертификат", "Сертификат Caddy");
    expect(fields.title).toBe("Сертификат Caddy");
    expect(fields.description).toBe("Обновить сертификат");
  });

  it("пустой свой заголовок означает «собери сам»", () => {
    expect(taskFromDraft("Обновить сертификат", "   ").title).toBe(
      "Обновить сертификат",
    );
  });

  it("перевод строки в своём заголовке схлопывается", () => {
    expect(taskFromDraft("Текст задачи", "Строка\nвторая").title).toBe(
      "Строка вторая",
    );
  });

  it("пустое описание не даёт ни заголовка, ни описания", () => {
    expect(taskFromDraft("   ")).toEqual({ title: "", description: "" });
  });
});

describe("capsTitle — заголовок по словам ЗАГЛАВНЫМИ (VED-580)", () => {
  it("берёт выделенную серию и приводит её к виду заголовка", () => {
    expect(
      capsTitle(
        "Сделай кнопку ЧИТАТЬ ДАЛЕЕ для описания задач, чтобы можно было прочитать полностью.",
      ),
    ).toBe("Читать далее");
  });

  it("соединяет выделенное в разных частях описания по порядку", () => {
    expect(
      capsTitle(
        "Задачи со СКРИНШОТАМИ добавляются долго. Может, можно УСКОРИТЬ ЗАГРУЗКУ и уменьшать размер?",
      ),
    ).toBe("Скриншотами ускорить загрузку");
  });

  it("серии через разные предложения тоже соединяются", () => {
    expect(
      capsTitle(
        "На главной ОБРАЗОВАНИЯ беспорядок.\nСправа нужна НАДПИСЬ МАТЕРИАЛЫ и цифра.",
      ),
    ).toBe("Образования надпись материалы");
  });

  it("предлоги внутри выделения остаются в заголовке", () => {
    expect(capsTitle("Нужна КНОПКА НА ГЛАВНОЙ, чтобы попадать в ленту.")).toBe(
      "Кнопка на главной",
    );
  });

  it("сохраняет дефис и кавычки не тащит", () => {
    expect(capsTitle("Добавь «ЧАТ-БОТ ПОДДЕРЖКИ» в меню.")).toBe(
      "Чат-бот поддержки",
    );
  });

  it("латиница внутри выделения остаётся заглавной — это сокращение", () => {
    expect(capsTitle("Проверь, что УСТАНОВКА PWA работает на айфоне.")).toBe(
      "Установка PWA",
    );
  });

  it("одно кириллическое слово от четырёх букв — уже выделение (VED-637)", () => {
    expect(capsTitle("Перенеси задачу в РАЗНОЕ и закрой.")).toBe("Разное");
  });

  it("короткое кириллическое одиночкой — сокращение, а не выделение", () => {
    expect(capsTitle("Не приходят СМС при входе.")).toBeNull();
  });

  it("сокращения сами по себе не выделение", () => {
    expect(
      capsTitle("Обнови страницу ISKCON и проверь API на проде."),
    ).toBeNull();
    expect(capsTitle("Ответ ИИ в ЛК приходит пустым.")).toBeNull();
  });

  it("слова с цифрами — номера и ключи, а не выделение", () => {
    expect(
      capsTitle("Продолжение VED-578 и VED-580, см. комментарий."),
    ).toBeNull();
  });

  it("слово из двух букв веса не даёт", () => {
    expect(capsTitle("Кнопка ОК НА месте")).toBeNull();
  });

  it("одно кириллическое слово от четырёх букв засчитывается рядом с другим выделением", () => {
    expect(
      capsTitle("Сделай КНОПКУ для описания, текст должен раскрываться ДАЛЕЕ."),
    ).toBe("Кнопку далее");
  });

  it("одиночная латиница рядом с выделением не прилипает к заголовку", () => {
    expect(capsTitle("Сделай КНОПКУ ДАЛЕЕ в описании, как в Jira и API.")).toBe(
      "Кнопку далее",
    );
  });

  it("текст целиком заглавными — выделять нечем", () => {
    expect(capsTitle("ПОЧИНИТЬ КНОПКУ СОХРАНИТЬ")).toBeNull();
  });

  it("без заглавных — ничего", () => {
    expect(capsTitle("починить кнопку сохранить")).toBeNull();
    expect(capsTitle("")).toBeNull();
  });
});
