/**
 * Длинный пункт чек-листа (VED-375).
 *
 * Заказчик: «Увеличь лимит текста, чтобы не приходилось заводить следующую
 * запись и писать ПРОДОЛЖЕНИЕ. Если текст получается слишком длинный, просто
 * прячь его, чтобы можно было раскрыть кнопкой Далее». Лимит поднят до 2000
 * (`WORK_CHECKLIST_TEXT_MAX`), а длинный пункт в карточке свёрнут до трёх
 * строк.
 *
 * Длинным считаем по тексту, а не по замеру высоты: кнопка «Далее» должна
 * стоять уже на первом кадре, без прыжка после отрисовки, и одинаково на
 * сервере и в браузере. Порог — примерно три строки узкого окна на телефоне
 * (около 45 знаков в строке при 14px) или больше трёх абзацев.
 */
export const CHECKLIST_FOLD_CHARS = 140;
export const CHECKLIST_FOLD_LINES = 3;

export function isLongChecklistText(text: string): boolean {
  if (text.length > CHECKLIST_FOLD_CHARS) return true;
  return text.split("\n").length > CHECKLIST_FOLD_LINES;
}
