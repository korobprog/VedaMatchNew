/**
 * Доска сама догоняет чужие правки (VED-272).
 *
 * Заказчик попросил, чтобы на карточках планировщика было «всё то же самое»,
 * что в ленте уведомлений. В ленте пометка состояния меняется у всех сразу:
 * тестировщик перенёс карточку в «Выполнено» — и «Тестерование» у остальных
 * сменилось на «Выполнено». На доске ярлык тоже есть (VED-311), но доска
 * загружалась один раз: у второго администратора с открытой доской карточка
 * оставалась «Тестерованием» до перезагрузки страницы. То есть ярлык врал
 * ровно так, как врала лента до VED-320.
 *
 * Живого потока у «Работы» нет, поэтому доска перечитывает себя: когда
 * человек возвращается на вкладку и раз в минуту, пока вкладка на экране —
 * тот же ритм, что у колокольчика уведомлений, чтобы лента и доска не
 * расходились дольше, чем друг с другом.
 */

/** Как часто перечитывать открытую доску. Тот же минутный шаг, что у колокольчика. */
export const BOARD_REFRESH_MS = 60_000;

export interface BoardRefreshGate {
  /** Номер правки доски, с которым ушёл запрос. */
  startedAt: number;
  /** Номер правки сейчас: каждая своя правка доски его увеличивает. */
  current: number;
  /** Сколько своих переносов ещё летит на сервер. */
  pendingMoves: number;
  /** Человек тащит карточку. */
  dragging: boolean;
}

/**
 * Можно ли подставить перечитанную доску.
 *
 * Нельзя, если за время запроса человек сам что-то поменял: ответ сервера
 * старше его правки и вернул бы карточку на прежнее место — «прыгнула
 * обратно». Нельзя, пока летит перенос: сервер его ещё не записал. И нельзя
 * посреди перетаскивания: доска под пальцем не должна перестраиваться.
 * Пропущенное обновление не теряется — следующий тик принесёт свежее.
 */
export function shouldApplyBoardRefresh(gate: BoardRefreshGate): boolean {
  return (
    gate.startedAt === gate.current &&
    gate.pendingMoves === 0 &&
    !gate.dragging
  );
}
