/**
 * Подсказка после решения: «Взаимно! Чат открыт», «Суперлайк отправлен».
 *
 * Раньше она стояла строкой под колодой и раздвигала страницу — на телефоне
 * экран подпрыгивал ровно в тот момент, когда рука тянулась к следующей
 * анкете. Теперь это накладка по центру, а под ней — салют.
 */

/** Сколько подсказка держится на экране, мс. */
export const TOAST_MS = 2200;

export interface BurstRay {
  /** Смещение конца луча от центра, px. */
  dx: number;
  dy: number;
  /** Задержка перед вылетом, с: салют распускается, а не выстреливает разом. */
  delay: number;
}

/**
 * Лучи салюта: равномерно по кругу, с разной длиной и разной задержкой.
 *
 * Считается формулой, а не `Math.random()`: случайность на сервере и в
 * браузере разошлась бы при гидратации, а глазу разница не видна — важно
 * лишь, чтобы лучи не были одинаковыми.
 */
export function burstRays(count: number, radius: number): BurstRay[] {
  if (count <= 0 || radius <= 0) return [];
  return Array.from({ length: count }, (_, i) => {
    const angle = (2 * Math.PI * i) / count;
    // Шаг 5 по модулю 7 обходит все остатки, поэтому длины идут вразнобой,
    // а не волной от короткого к длинному. Верхняя доля — 0.96, а не 1:
    // радиус здесь габарит салюта, и самый длинный луч не должен его касаться.
    const spread = 0.6 + (0.36 * ((i * 5) % 7)) / 6;
    const length = radius * spread;
    return {
      // Не округляем: субпиксель CSS переварит, а округление к целому
      // вытолкнуло бы длинный луч за радиус.
      dx: Math.cos(angle) * length,
      dy: Math.sin(angle) * length,
      delay: Math.round(((i % 4) * 0.05 + Number.EPSILON) * 100) / 100,
    };
  });
}
