import { plural } from "@/lib/plural";

/**
 * Уборка пустых строк в тексте поста (VED-372).
 *
 * Заказчик: «Нужна в первую очередь функция — Убрать 1 и более (должно быть
 * настраиваемо) пустых строчек между частями текста. На скриншоте виден
 * разорванный текст, это некрасиво».
 *
 * Текст в ленту почти всегда приезжает вставкой из мессенджера, заметок или
 * PDF, и вместе с ним приезжают пустые строки между абзацами — иногда по
 * несколько. Сервер схлопывает только подряд идущие переводы строки
 * (`\n{3,}`), а вставленный текст чаще состоит из строк с пробелами и
 * табуляциями: для регулярного выражения это не пустая строка, для человека
 * — дыра в тексте. Поэтому здесь пустой считается строка без видимых
 * знаков.
 *
 * Инструмент ручной: кнопка в форме, результат виден сразу, отмена
 * возвращает прежний текст. Молча переписывать чужой текст при сохранении
 * нельзя — это его слова, а не наши.
 */

/** Сколько пустых строк оставлять между абзацами — выбор в форме. */
export const BLOG_BLANK_LINES_KEEP_CHOICES = [0, 1, 2] as const;

/** По умолчанию не оставляем ни одной: именно об этом просил заказчик. */
export const BLOG_BLANK_LINES_DEFAULT_KEEP = 0;

export interface BlogBlankLinesResult {
  /** Текст после уборки. */
  text: string;
  /** Сколько пустых строк убрано — это показывается человеку. */
  removed: number;
}

/**
 * Убрать лишние пустые строки, оставив между абзацами не больше `keep`.
 *
 * Строки с содержимым не меняются вовсе: уборка занимается пустотой, а не
 * словами. Оставленная пустая строка становится действительно пустой —
 * пробелы и табуляции в ней не видны, но мешают следующей уборке и
 * серверному схлопыванию.
 *
 * Пустые строки в начале и в конце убираются всегда: сверху и снизу
 * абзацев, между которыми надо оставить воздух, нет.
 *
 * `keep` больше фактического числа пустых строк ничего не добавляет: это
 * «убрать лишние», а не «расставить отступы».
 */
export function collapseBlankLines(
  value: string,
  keep: number = BLOG_BLANK_LINES_DEFAULT_KEEP,
): BlogBlankLinesResult {
  const limit = Number.isFinite(keep) ? Math.max(0, Math.trunc(keep)) : 0;
  const normalized = value.replace(/\r\n?/g, "\n");
  const lines = normalized.split("\n");

  const out: string[] = [];
  let pending = 0;
  let seenContent = false;

  for (const line of lines) {
    if (line.trim() === "") {
      pending += 1;
      continue;
    }
    if (seenContent) {
      // До первой строки с содержимым пустота не разделяет ничего, поэтому
      // оставлять её незачем — как и в самом конце текста.
      for (let index = 0; index < Math.min(pending, limit); index += 1) {
        out.push("");
      }
    }
    pending = 0;
    seenContent = true;
    out.push(line);
  }

  const text = out.join("\n");
  // Считаем по числу строк: убираем мы только строки, а оставленную пустую
  // всего лишь очищаем от пробелов — это не «убрано». Текст, который уборка
  // не изменила, не убрал ничего, и пустой текст в том числе.
  return { text, removed: text === normalized ? 0 : lines.length - out.length };
}

/**
 * Что сказать человеку после уборки. Отдельной функцией, потому что
 * склонения здесь три («убрана 1 пустая строка», «убрано 2 пустые строки»,
 * «убрано 5 пустых строк») и проверяются тестом, а не глазами в разметке.
 */
export function blogBlankLinesMessage(removed: number): string {
  if (removed <= 0) return "Пустых строк между абзацами не нашлось.";
  return `${plural(removed, "Убрана", "Убрано", "Убрано")} ${removed} ${plural(
    removed,
    "пустая строка",
    "пустые строки",
    "пустых строк",
  )}.`;
}
