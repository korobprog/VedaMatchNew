/**
 * Сколько эквалайзера помещается в ряд полосы на телефоне (VED-450, круг 5).
 *
 * Столбики стоят с постоянным шагом, а не растягиваются на всю ширину: в
 * широком ряду растянутая полоса расходилась редкими полосками («сделай его
 * как он выглядел раньше»). Поэтому ширина решает, сколько столбиков
 * нарисовать, а не насколько их раздвинуть.
 */

/** Ширина столбика и зазор между ними, в точках. */
export const EQ_BAR_WIDTH = 3;
export const EQ_BAR_GAP = 4;

/** Уже этого эквалайзер не рисуем: пять столбиков — уже не «играет», а шум. */
export const EQ_MIN_WIDTH = 40;

/** Столбиков в полосе шириной `width`; 0 — не рисовать вовсе. */
export function eqBarCount(width: number): number {
  if (!(width >= EQ_MIN_WIDTH)) return 0;
  return Math.floor((width + EQ_BAR_GAP) / (EQ_BAR_WIDTH + EQ_BAR_GAP));
}

/**
 * Встаёт ли эквалайзер между управлением и вынесенными кнопками.
 *
 * `rowWidth` — ширина всего ряда, `buttonsWidth` — сумма ширин вынесенных
 * кнопок, `margins` — поля эквалайзера до соседей. Решение по кнопкам, а не
 * по их числу: «15» у перемотки шире значка, а ширина экрана бывает от 320
 * до 430 точек, и счёт кнопок «две — ещё можно» ошибался в обе стороны.
 */
export function eqFits(
  rowWidth: number,
  buttonsWidth: number,
  margins: number,
): boolean {
  return rowWidth - buttonsWidth - margins >= EQ_MIN_WIDTH;
}

/**
 * Поле эквалайзера справа (VED-450, круг 7) — по тому, какая кнопка стоит
 * за ним. Слева до столбиков всегда одно и то же: поле ряда и кнопка
 * «Дальше», ~17 точек до её значка. Справа значок бывает у самого края
 * кнопки («↺ 15» перемотки — поле ~2 точки) или посередине (закладка,
 * история, кнопки полосы — ~12 точек), и одно поле на все случаи давало то
 * 17 и 21, то 17 и 29. Подобрано замером на 360, 393 и 412 точках.
 */
export function eqRightPadding(next: "seek" | "icon" | "strip"): number {
  if (next === "seek") return 13;
  if (next === "icon") return 4;
  return 6;
}
