/**
 * Та же ли это очередь.
 *
 * Кнопка запуска у текущей записи ставила паузу и на этом останавливалась —
 * очередь оставалась прежней. Из-за этого запись, включённая раньше из
 * каталога, а потом нажатая в плейлисте, продолжала играть со старой
 * очередью: «дальше» вело по каталогу, а в плейлисте не переключалось вовсе.
 *
 * Поэтому пауза — только когда очередь и правда та же. Иначе нажатие
 * означает «играй отсюда», и очередь надо подменить, даже если запись
 * совпала.
 */
export function isSameQueue(
  current: readonly string[],
  next: readonly string[] | undefined,
): boolean {
  // Кнопка без очереди ничего о ней не сообщает — считаем, что не меняет.
  if (!next || next.length === 0) return true;
  if (current.length !== next.length) return false;
  return current.every((id, at) => id === next[at]);
}
