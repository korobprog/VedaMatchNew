/**
 * Перемотка долгим нажатием на «предыдущая/следующая запись».
 *
 * В полосе плеера на телефоне помещается пять кнопок, и отдельные «−15 с» и
 * «+15 с» вытесняли переход по записям: сменить киртан можно было только
 * через список. Одна и та же кнопка несёт оба намерения — короткое нажатие
 * переключает, удержание мотает, — и это дешевле по месту, чем два ряда.
 *
 * Логика вынесена из компонента: разбор жеста — это арифметика по времени
 * удержания, и проверять её на настоящих указателях и таймерах дороже, чем
 * на числах.
 */

/**
 * Сколько держать, прежде чем нажатие перестанет быть переключением.
 *
 * Меньше — и обычное нажатие пальцем (около 100–200 мс) начинало бы мотать
 * вместо перехода. Больше — и удержание перестаёт читаться как жест: человек
 * успевает решить, что кнопка не сработала, и отпустить.
 */
export const HOLD_THRESHOLD_MS = 350;

/** Шаг тика перемотки. Реже — рывками, чаще — незачем: звук всё равно ждёт. */
export const HOLD_TICK_MS = 200;

/** Первый тик — маленький, чтобы точно попасть в пропущенную строку. */
const FIRST_STEP_SECONDS = 2;

/** Разгон: каждый следующий тик длиннее предыдущего на столько секунд. */
const STEP_GROWTH_SECONDS = 1.5;

/**
 * Потолок шага. Без него удержание на длинной лекции пролетает главу за
 * полсекунды, и попасть в нужное место становится невозможно.
 */
const MAX_STEP_SECONDS = 20;

/**
 * На сколько секунд двигать звук на `tick`-м тике удержания (с нуля).
 *
 * Разгон, а не постоянный шаг: в трёхминутном бхаджане нужна точность, в
 * двухчасовой лекции — скорость, и заранее неизвестно, что именно играет.
 */
export function holdSeekStep(tick: number): number {
  if (!Number.isFinite(tick) || tick < 0) return FIRST_STEP_SECONDS;
  return Math.min(
    FIRST_STEP_SECONDS + Math.floor(tick) * STEP_GROWTH_SECONDS,
    MAX_STEP_SECONDS,
  );
}

/**
 * Стало ли нажатие удержанием.
 *
 * Отдельной функцией, а не сравнением на месте: порог решает, переключит
 * кнопка запись или перемотает, и ошибиться в знаке сравнения здесь значит
 * сломать обычный переход.
 */
export function isHold(heldMs: number): boolean {
  return Number.isFinite(heldMs) && heldMs >= HOLD_THRESHOLD_MS;
}
