/**
 * Размер рамки обложки (VED-138, третий круг).
 *
 * Сначала обложку обрезали под 16:9, потом вписывали в ту же 16:9 целиком с
 * размытыми полями — заказчик назвал поля «дурацкими рамками». Теперь рамки
 * нет вовсе: рамка обложки принимает пропорции самой картинки и тянется на
 * всю ширину карточки. Широкий баннер — низкая полоса, квадрат — квадрат.
 *
 * Потолок по высоте нужен вертикальным: скриншот телефона во всю ширину
 * занял бы в ленте два экрана. Упёршись в потолок, рамка сужается по тем же
 * пропорциям и встаёт по центру — картинка по-прежнему целиком и без полей
 * вокруг себя, просто меньше.
 *
 * Ширина считается в CSS, а не в JS: `100cqw` — ширина контейнера обложки
 * (у него `container-type: inline-size`), и замерять её не нужно.
 */

/** Пропорции, пока картинка не загрузилась: место под обложку держим сразу. */
export const PLACEHOLDER_RATIO = 16 / 9;

/**
 * Пропорции картинки по её натуральному размеру. `null` — размер неизвестен:
 * картинка ещё не пришла или сломана.
 */
export function naturalRatio(width: number, height: number): number | null {
  if (!Number.isFinite(width) || !Number.isFinite(height)) return null;
  if (width <= 0 || height <= 0) return null;
  return width / height;
}

/**
 * Стиль рамки: пропорции картинки и ширина — вся доступная, но не больше
 * той, при которой высота упрётся в `maxHeight` (любая CSS-длина).
 */
export function coverFrameStyle(
  ratio: number | null,
  maxHeight: string,
): { aspectRatio: string; width: string } {
  const r = ratio ?? PLACEHOLDER_RATIO;
  // Четырёх знаков хватает с запасом: ошибка меньше пикселя на 10 000px.
  const rounded = Number(r.toFixed(4));
  return {
    aspectRatio: String(rounded),
    width: `min(100cqw, calc(${maxHeight} * ${rounded}))`,
  };
}
