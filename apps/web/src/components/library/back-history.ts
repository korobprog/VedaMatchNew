/**
 * Правила кнопки «Назад» Образования (VED-397): какие записи истории она
 * проходит насквозь.
 *
 * Форма добавления остаётся в истории и после публикации: выбор режима
 * `/library/add` стоит позади рубрики, куда человек вернулся, и «Назад»
 * уводил его обратно в заполнение поста. То же — форма шлоки, после
 * сохранения которой открывается страница шлоки обычным переходом.
 */

/** Сколько записей подряд можно пропустить — страховка от зацикливания. */
export const MAX_BACK_HOPS = 10;

/** Экраны заполнения материала: выбор режима и сами формы. */
export function isLibraryFormPath(pathname: string): boolean {
  return /^\/library\/add(?:\/|$)/.test(pathname);
}

/**
 * Пропустить ли запись, на которую привёл шаг назад.
 *
 * Форму — когда «Назад» нажали не из формы: из формы шаг назад к выбору
 * режима — ожидаемый, его не пропускаем. Ту же страницу, с которой нажали
 * «Назад», — всегда: после публикации история выглядит как «рубрика →
 * форма → рубрика», и без этого
 * «Назад» из рубрики, миновав форму, вернул бы в ту же рубрику — нажатие
 * выглядело бы так, будто кнопка не работает. Сравниваем путь без строки
 * запроса: смена фильтров в рубрике — та же страница, а не шаг, который
 * человек ждёт отменить кнопкой «Назад».
 */
export function shouldSkipOnBack(landed: string, origin: string): boolean {
  if (landed === origin) return true;
  return isLibraryFormPath(landed) && !isLibraryFormPath(origin);
}
