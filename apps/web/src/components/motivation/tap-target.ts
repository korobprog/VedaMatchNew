/**
 * Размер тап-цели в формах «Вдохновения».
 *
 * Замер на живой `/motivation/create` при ширине 360px: кнопки «🖼️ Из
 * галереи», «📁 Из файлов», «📋 Вставить из буфера», «Опубликовать», поля
 * «Автор» и «Источник» — 38px, `<select>` «Категория» — 39px, вкладки
 * «📖 По книгам» и «🔍 Поиск по словам» — 30px. Причина у всех одна:
 * `px-3 py-2 text-sm` даёт 20px строки + 16px паддингов + 2px рамки, и до
 * пальца эта высота не дотягивает. Мастер — единственное место портала, где
 * человек подряд жмёт десяток мелких кнопок с телефона, и промах здесь
 * стоит набранного текста.
 *
 * Приём взят тот, что в репозитории уже принят, а не новый: `min-h-11`
 * (Tailwind, `2.75rem` = 44px). Так сделаны чат
 * (`chat-composer.tsx`, `chat-requests-view.tsx`, `chat-room-menu.tsx`) и
 * меню админки, где у `admin-sidebar.tsx` рядом с классом стоит та же
 * причина: «палец, а не курсор». Минимум высоты, а не фиксированная
 * `h-11`: поле с длинной подписью или кнопка, у которой текст перенёсся на
 * вторую строку, обязаны вырасти, а не обрезать содержимое.
 *
 * Паддинги и цвета форм остаются на своих местах — модуль отвечает ровно за
 * размер тап-цели. Собирается он здесь, а не пишется в каждой форме: у
 * открыток (`picture-publish-form.tsx`), у роликов (`reel-wizard.tsx`) и у
 * выбора категории (`reel-category-select.tsx`) это две половины одного
 * мастера, человек переключается между ними одной кнопкой, и разъехаться
 * они не должны — ровно по той же причине, по какой рядом лежит
 * `field-label.ts`.
 *
 * Только утилиты поверх токенов `globals.css`: высота в модуле есть, цвета
 * нет. Фокус здесь не трогается — обводку даёт глобальный `*:focus-visible`,
 * и `outline: none` модуль не вносит.
 */

/** 44px: нижняя граница тап-цели, принятая в портале. */
const TAP_TARGET = "min-h-11";

/**
 * Поле ввода: `input`, `select`, `textarea`. Собственная высота у них
 * задаётся содержимым и `rows`, поэтому хватает одного минимума.
 */
export function tapFieldClass(extra?: string): string {
  return join(TAP_TARGET, extra);
}

/**
 * Кнопка или ссылка-кнопка. Кроме минимума нужна раскладка: у `<button>`
 * с `min-height` содержимое прижимается к верху заданных паддингов, и
 * подпись поехала бы вверх относительно соседей. `inline-flex` оставляет
 * кнопку по ширине содержимого — в рядах `flex flex-wrap gap-2`, где они и
 * стоят, растягивать её нельзя.
 */
export function tapButtonClass(extra?: string): string {
  return join(`inline-flex ${TAP_TARGET} items-center justify-center`, extra);
}

/** Свои классы дописываются после общих, пустая добавка не оставляет хвоста. */
function join(base: string, extra?: string): string {
  const tail = extra?.trim();
  return tail ? `${base} ${tail}` : base;
}
