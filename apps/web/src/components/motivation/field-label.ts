/**
 * Подпись поля в формах «Вдохновения» (VED-203).
 *
 * Жалоба дословно: графы «автор» и «источник» «сливаются с фоном». Формы
 * мастера лежат прямо на фоне страницы — под ними орбы и шумовой слой, а не
 * ровная заливка, — и подпись цветом `--vm-text-1` читалась как продолжение
 * пояснения под полем, набранного `--vm-text-2`. Подпись переведена на
 * `--vm-text-0`, самый контрастный текстовый токен, заданный в обеих темах,
 * и на `font-semibold`: заметной её делает разом и вес, и цвет, а пояснение
 * рядом остаётся тихим.
 *
 * Класс собирается здесь, а не пишется в каждой форме: у открыток
 * (`picture-publish-form.tsx`) и у роликов (`reel-wizard.tsx`) подписи
 * обязаны выглядеть одинаково — это две половины одного мастера, и человек
 * переключается между ними одной кнопкой.
 *
 * Только токены: `text-text-0` — утилита Tailwind поверх `--vm-text-0` из
 * `globals.css`. Хардкод `#RRGGBB` здесь запрещён — он пережил бы
 * переключение темы, — и тест это стережёт.
 */
const FIELD_LABEL_BASE = "block font-semibold text-text-0";

/**
 * Классы подписи поля. `extra` — то, что нужно этой конкретной подписи
 * (отступ, ширина колонки); пустая строка и пробелы не должны оставлять
 * хвост из двойных пробелов в `class`.
 */
export function fieldLabelClass(extra?: string): string {
  const tail = extra?.trim();
  return tail ? `${FIELD_LABEL_BASE} ${tail}` : FIELD_LABEL_BASE;
}
