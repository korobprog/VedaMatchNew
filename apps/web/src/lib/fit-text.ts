/**
 * Какой из вариантов подписи влезает в строку (VED-374, VED-391).
 *
 * Плитка панели горячих кнопок держит подпись в одну строку: вторая строка
 * в плитке с вертикальным центрированием поднимает значок. Ширина плитки
 * зависит от экрана, поэтому из лестницы вариантов «от полного к короткому»
 * берётся первый, чья ширина не больше доступной. Не влез ни один —
 * последний, самый короткий: его дорежет CSS многоточием.
 *
 * Решение отделено от измерения, чтобы тест не зависел от шрифтов браузера:
 * в плитке варианты — уже замеренные ширины невидимых мерок, в тесте —
 * строки и что угодно вместо шрифта.
 */

/**
 * Запас на округление: ширина мерки и ширина строки округляются до
 * дробных пикселей по-разному, и подпись, влезающая впритык, не должна
 * прыгать между вариантами.
 */
const SUBPIXEL = 0.5;

export function pickFittingOption<T>(
  options: readonly T[],
  width: number,
  measure: (option: T) => number,
): number {
  if (options.length === 0) return -1;
  const index = options.findIndex(
    (option) => measure(option) <= width + SUBPIXEL,
  );
  return index === -1 ? options.length - 1 : index;
}
