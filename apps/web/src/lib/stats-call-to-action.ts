/**
 * Подпись под числом участников в баннере. Обещает то, что за ссылкой, —
 * графики, города и этапы: «пусть нас будет больше» звучало лозунгом и не
 * говорило, куда человек попадёт.
 *
 * Имя приходит, только когда советник молчит: здоровается кто-то один, иначе
 * обращение звучит дважды на одном экране.
 */
export function statsCallToAction(greetName?: string): string {
  const name = greetName?.trim();
  return name
    ? `${name}, посмотрите, как мы растём`
    : "Посмотреть, как мы растём";
}
