/**
 * Разделы витрины «Работы».
 *
 * «Работа» — не один экран, а вход в набор инструментов: человек нажимает её в
 * портале и видит иконки того, что внутри. С точки зрения контракта это
 * по-прежнему ОДИН сервис (`work`) с одной папкой модуля и одним префиксом
 * маршрутов — как «Общение», внутри которого живёт справочник людей. Отдельный
 * сервис на каждую иконку означал бы отдельную запись каталога и отдельный
 * пункт в шапке, а иконок задумано несколько.
 *
 * Готовый раздел — ссылка, будущий — плашка «Скоро»: приглушённая ссылка ведёт
 * на пустую страницу, и человек возвращается ни с чем. Тот же приём, что у
 * ходовых сервисов на главной.
 */
export interface WorkSection {
  slug: string;
  name: string;
  hint: string;
  /** Одна строка о том, зачем сюда заходят. Показывается на широком экране. */
  about: string;
  /** Токен акцента из globals.css. Хардкод #RRGGBB не переживёт смену темы. */
  accent: "cyan" | "magenta" | "gold" | "violet" | "blue";
  /** Готовый раздел — ссылка; будущий — плашка «Скоро». */
  href?: string;
}

