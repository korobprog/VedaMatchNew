/**
 * Картинка для превью ссылки на афоризм в мессенджерах (VED-201, VED-357).
 *
 * В `og:image` когда-то стоял сам сторис-кадр: PNG 1080×1920 весом около 5 МБ.
 * Max такой разворачивает, остальные — нет. Поэтому превью отдаётся отдельным
 * адресом — уменьшенным JPEG, который гарантированно укладывается в предел.
 *
 * История заходов — чтобы не повторять ошибок.
 *
 * 1. PR #360: кадр 630×1120 (9:16) с `fit: 'cover'`, размеры объявлены в
 *    `og:image:width/height`. WhatsApp показывал его крупно, во всю ширину
 *    пузыря. Но `cover` у открытки не вертикальной формы срезал бока.
 * 2. PR #416: кадр стал повторять пропорции исходника, размеры из метатегов
 *    убрали — у каждого поста своя форма, а посчитать её страница не могла.
 * 3. PR #429: в превью идёт чистая иллюстрация, без впечатанной цитаты. Это
 *    правило **ломать нельзя** (`ogImageSource`). Кадр 900×1350, 230–265 КБ,
 *    размеры не объявлены — и WhatsApp то показывал превью крупно, то
 *    сворачивал в миниатюру сбоку.
 * 4. PR #463 решил, что виноваты вертикальные пропорции, и перешёл на
 *    альбомные 1200×630 с иллюстрацией посередине на размытой копии себя.
 *    Карточка стала крупной, но две трети её ширины заняли размытые поля —
 *    «уродство», по словам владельца. Вертикаль тут ни при чём: и кадр из
 *    п. 1, и кадр из п. 3 WhatsApp показывал крупно, вертикальными.
 *
 * Отсюда нынешнее устройство — параметры п. 1 без его обрезки: чистая
 * иллюстрация **в своих собственных пропорциях**, без полей и без
 * кадрирования, шириной `OG_PREVIEW_WIDTH` и весом заметно меньше 100 КБ.
 * Размер файла объявлен в метатегах: страница узнаёт размер исходника по его
 * заголовку (`motivation-og-probe.ts`) и считает кадр той же
 * `ogPreviewSize()`, что и маршрут `/m/[slug]/og`, — числа сходятся по
 * построению.
 *
 * Здесь только чистая часть: размер кадра, лестница качества и адрес. Само
 * перекодирование — в маршруте `/m/[slug]/og`.
 */

export const OG_IMAGE_TYPE = "image/jpeg";

/**
 * Ширина кадра — как у варианта, который WhatsApp показывал крупно (PR #360).
 * Телефон рисует превью примерно такой же ширины в физических точках, так что
 * больше — это лишний вес без видимой разницы.
 */
export const OG_PREVIEW_WIDTH = 630;

/**
 * Потолок высоты — те же 9:16 при ширине 630, что у варианта из PR #360.
 * Иллюстрация рилса (2:3, 630×945) до него не доходит. Выше упираются только
 * очень узкие открытки: у них кадр становится уже, а пропорции остаются свои.
 */
export const OG_PREVIEW_MAX_HEIGHT = 1120;

/**
 * Фон под прозрачными краями. У JPEG прозрачности нет, и без подложки они
 * стали бы чёрными пятнами непредсказуемой формы.
 */
export const OG_TRANSPARENT_FALLBACK = "#0A0614";

/**
 * Предел веса. Миниатюры в WhatsApp случались на файлах 230–265 КБ, крупно
 * он показывал и более лёгкие. Держимся заметно ниже 100 КБ: лёгкий файл
 * быстрее скачивает и бот, и телефон отправителя — WhatsApp собирает превью
 * именно на нём.
 */
export const OG_IMAGE_MAX_BYTES = 90_000;

export type OgEncoding = {
  quality: number;
};

/**
 * Попытки кодирования по порядку — только качество. Размер кадра не
 * трогаем: он объявлен в `og:image:width`/`og:image:height`, и файл обязан
 * ему соответствовать. На замерах пёстрая иллюстрация 630×945 укладывается
 * в предел к качеству 52–58, спокойная — уже на 64–72.
 */
export const OG_IMAGE_ATTEMPTS: readonly OgEncoding[] = [
  { quality: 80 },
  { quality: 72 },
  { quality: 64 },
  { quality: 58 },
  { quality: 52 },
  { quality: 46 },
  { quality: 40 },
];

export interface OgPreviewSize {
  width: number;
  height: number;
}

/**
 * Размер кадра превью по размеру исходника: пропорции исходника, ширина
 * `OG_PREVIEW_WIDTH`, высота не больше `OG_PREVIEW_MAX_HEIGHT`.
 *
 * Картинка в кадр не вписывается и не кадрируется — кадр **и есть** картинка,
 * поэтому полей и обрезки нет ни при какой форме. Мелкий исходник
 * растягивается до ширины кадра: превью размером с иконку мессенджеры
 * показывают значком сбоку вместо большой карточки.
 *
 * Ту же функцию зовут и страница (для метатегов), и маршрут картинки — так
 * объявленный размер совпадает с настоящим.
 */
export function ogPreviewSize(source: OgPreviewSize): OgPreviewSize {
  const srcWidth = Math.max(1, Math.round(source.width));
  const srcHeight = Math.max(1, Math.round(source.height));

  let width = OG_PREVIEW_WIDTH;
  let height = Math.round((width * srcHeight) / srcWidth);
  if (height > OG_PREVIEW_MAX_HEIGHT) {
    height = OG_PREVIEW_MAX_HEIGHT;
    width = Math.round((height * srcWidth) / srcHeight);
  }
  return { width: Math.max(1, width), height: Math.max(1, height) };
}

/**
 * Перебирает попытки, пока результат не уложится в предел.
 * `encode` — перекодировщик; в маршруте это sharp, в тесте — подделка.
 */
export async function encodeWithinLimit(
  encode: (attempt: OgEncoding) => Promise<Uint8Array>,
  maxBytes: number = OG_IMAGE_MAX_BYTES,
  attempts: readonly OgEncoding[] = OG_IMAGE_ATTEMPTS,
): Promise<{ bytes: Uint8Array; attempt: OgEncoding }> {
  if (attempts.length === 0) throw new Error("no encoding attempts");
  let last: { bytes: Uint8Array; attempt: OgEncoding } | null = null;
  for (const attempt of attempts) {
    const bytes = await encode(attempt);
    last = { bytes, attempt };
    if (bytes.byteLength <= maxBytes) return last;
  }
  return last!;
}

/**
 * Относительный адрес превью. Абсолютным его делает `metadataBase` корневого
 * layout — мессенджеры принимают только полный https-адрес.
 *
 * Адрес живёт под `/m/`, а этот префикс открыт гостю в proxy.ts: бот
 * мессенджера приходит без cookie, и иначе получил бы редирект на лендинг.
 * Маршрут параметр `v` не читает — он только делает адрес новым.
 */
export function ogImagePath(slug: string): string {
  return `/m/${encodeURIComponent(slug)}/og?v=${OG_LAYOUT_VERSION}`;
}

/**
 * Версия раскладки превью в адресе картинки. Мессенджеры и их прокси кэшируют
 * картинку по адресу, а маршрут отдаёт её с суточным кэшем: после смены
 * раскладки (#463 → #479) WhatsApp ещё сутки показывал старый кадр с полями,
 * хотя сервер уже отдавал новый (VED-357). Меняется раскладка — меняется
 * версия, и адрес для мессенджера становится новым.
 */
export const OG_LAYOUT_VERSION = "2";

/**
 * Из какого файла собирать превью — из `imageUrl`, самой иллюстрации.
 *
 * `storyImageUrl` сюда не годится и не берётся даже запасным вариантом: это
 * тот же фон, но с впечатанной цитатой и знаком. Пока брали его, WhatsApp
 * показывал текст дважды, а Telegram — ещё и обрубленным на полуслове, потому
 * что режет кадр 9:16 по своей рамке. Пустой `imageUrl` без картинки бывает
 * только у неопубликованного поста; отдать вместо превью кадр с обрезанным
 * текстом хуже, чем не отдать превью вовсе, — тогда мессенджер покажет
 * карточку из одного заголовка и описания.
 */
export function ogImageSource(post: {
  imageUrl?: string | null;
  /**
   * Объявлен, но не читается — намеренно. Пост приходит сюда целиком, и поле
   * в сигнатуре держит договор на виду: сторис-кадр рядом есть, и он всё
   * равно не берётся. Тест рядом проверяет ровно это.
   */
  storyImageUrl?: string | null;
}): string | null {
  return post.imageUrl || null;
}
