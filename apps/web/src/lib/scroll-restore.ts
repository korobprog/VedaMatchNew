/**
 * Возврат на то же место страницы после переключения окна (VED-325).
 *
 * Обещание «окно помнит, докуда прокручено» держалось одним кадром: портал
 * ставил `scrollTo` в первый же `requestAnimationFrame` после перехода. Для
 * страницы, у которой содержимое приходит запросом — список задач, лента,
 * каталог, — в этот момент высоты ещё нет, и браузер молча прижимает
 * прокрутку к тому максимуму, который есть, то есть к нулю.
 *
 * Поэтому не один кадр, а попытки до тех пор, пока страница не дорастёт до
 * нужной высоты, но с крайним сроком: бесконечное ожидание на странице,
 * которая стала короче (запись удалили, фильтр сузил список), — это дёрганье
 * под пальцем.
 *
 * Здесь только правило одной попытки. Кадры, слушатели и сам `scrollTo` —
 * в `components/quick/portal-windows-tracker.tsx`.
 */

/**
 * Сколько ждём высоту.
 *
 * Пять секунд — это медленная мобильная связь, на которой список задач
 * приезжает не сразу. Меньше не годится: по «страница перестала расти»
 * возврат срывался ещё до ответа сервера — между скелетом и данными высота
 * стоит на месте, и отличить «уже всё» от «ещё едет» изнутри страницы нечем.
 * Больше тоже не надо: через пять секунд человек читает сначала, и прыжок
 * вниз он воспримет как сбой, а не как заботу.
 */
export const SCROLL_RESTORE_DEADLINE_MS = 5000;

/**
 * Как часто пробуем. Не каждый кадр: `scrollHeight` заставляет браузер
 * пересчитать раскладку, и делать это шестьдесят раз в секунду ради
 * ожидания — заметная работа на телефоне. Десять раз в секунду человек не
 * отличит.
 */
export const SCROLL_RESTORE_POLL_MS = 100;

/**
 * Допуск в пикселях. Высота страницы редко сходится до пикселя: картинки
 * дорисовываются, шрифт подменяется, полоса плеера то есть, то нет.
 */
export const SCROLL_RESTORE_TOLERANCE_PX = 8;

export interface ScrollRestoreProbe {
  /** Куда хотим вернуться. */
  target: number;
  /** Докуда вообще можно прокрутить сейчас: высота страницы минус экран. */
  reach: number;
  /** Сколько прошло с начала попыток, мс. */
  elapsed: number;
  deadline?: number;
  tolerance?: number;
}

export interface ScrollRestoreStep {
  /** Куда прокрутить на этом шаге; `null` — трогать прокрутку не нужно. */
  top: number | null;
  /** Попытки окончены: либо добрались, либо ждать больше нечего. */
  done: boolean;
}

/** Докуда можно прокрутить страницу с такой высотой и таким экраном. */
export function scrollReach(
  documentHeight: number,
  viewportHeight: number,
): number {
  return Math.max(0, documentHeight - viewportHeight);
}

/**
 * Одна попытка вернуть прокрутку.
 *
 * Пока высоты не хватает, прокручиваем настолько, насколько получается, и
 * ждём дальше: так страница с подгрузкой по прокрутке успевает попросить
 * следующую порцию, а человек видит движение к своему месту, а не рывок в
 * конце.
 */
export function stepScrollRestore({
  target,
  reach,
  elapsed,
  deadline = SCROLL_RESTORE_DEADLINE_MS,
  tolerance = SCROLL_RESTORE_TOLERANCE_PX,
}: ScrollRestoreProbe): ScrollRestoreStep {
  // Возвращать наверх нечего: страница и так открывается сверху, а лишний
  // `scrollTo` отнимал бы у браузера его собственное восстановление.
  if (target <= 0) return { top: null, done: true };

  const top = Math.min(target, Math.max(0, reach));
  const reached = reach + tolerance >= target;
  return { top, done: reached || elapsed >= deadline };
}
