import type { NotificationMark } from "@vedamatch/shared";

/**
 * Как выглядит состояние задачи (VED-272, VED-312, VED-311).
 *
 * Портальный помощник, а не помощник сервиса: слово и цвет одного и того же
 * состояния читают двое — лента уведомлений и карточка в планировщике
 * «Работы». Пока у них были свои подписи, человек видел «Тестирование» в
 * колокольчике и «На доработку» на доске и не знал, какому ответу верить
 * (VED-320). Теперь вид один, а код состояния считает сервер — тоже в одном
 * месте.
 *
 * Слово на ярлыке — ровно название колонки доски, как его видит человек,
 * который её завёл: «В работе», «На тестирование», «На проверке»,
 * «Выполнено», «На доработку». Колонку «Тестерование» заказчик сам
 * переименовал в «На тестирование» и завёл «На проверке» (VED-487); слово на
 * ярлыке меняется только вслед за доской, не от себя.
 *
 * Знака рядом со словом нет: стрелку у «На доработку» заказчик попросил убрать
 * (VED-312). Приметы осталось две — слово и цвет, — и смысл несёт слово:
 * в чёрно-белой печати и дальтонику «Выполнено» остаётся «Выполнено».
 *
 * Цвета — только токены темы, каждый определён в обеих: `--vm-mark-*`
 * в `globals.css`, там же замеры контраста. Пара на состояние, а не один
 * цвет: тёмно-синее и тёмно-красное, которые просил заказчик, живут на его
 * светлой теме, а тёмная берёт осветлённый тон той же краски — иначе слово
 * не читается. Подложка у ярлыка не заливается цветом: заливка роняет
 * контраст подписи ниже AA.
 */

export interface TaskStatusMarkView {
  /** Слово на ярлыке — оно же то, что читает скринридер. */
  label: string;
  /**
   * Классы цвета: рамка и текст одним тоном. Фон берётся от карточки, своей
   * заливки у ярлыка нет — см. про контраст выше.
   */
  className: string;
}

/**
 * Ключ — `NotificationMark`, то есть четыре состояния задачи, «Комментарий»
 * (VED-298) и «Чужое» (VED-320). Карточка планировщика передаёт сюда только состояние
 * (`TaskStatusMark`), так что «Комментарий» на доске не появляется: это вид
 * новости в ленте, а не состояние задачи.
 */
const MARK_VIEWS: Record<NotificationMark, TaskStatusMarkView> = {
  in_progress: {
    label: "В работе",
    className: "border-mark-progress/60 text-mark-progress",
  },
  // «На тестирование» — так колонку переименовал заказчик (VED-487).
  testing: {
    label: "На тестирование",
    className: "border-mark-testing/60 text-mark-testing",
  },
  // «На проверке» (VED-487) — янтарный: остальные тона уже заняты.
  review: {
    label: "На проверке",
    className: "border-mark-review/60 text-mark-review",
  },
  done: {
    label: "Выполнено",
    className: "border-mark-done/60 text-mark-done",
  },
  rework: {
    label: "На доработку",
    className: "border-mark-rework/60 text-mark-rework",
  },
  /* Заказчик: «если уведомление о комментарии не имеет своего статуса, то
     добавь ей цветной статус Комментарий» (VED-298). Цвет свой, фиолетовый:
     четыре тона выше заняты, а спутать «Комментарий» с состоянием задачи
     значило бы прочитать его как пятую колонку. */
  comment: {
    label: "Комментарий",
    className: "border-mark-comment/60 text-mark-comment",
  },
  /* «Чужое» (VED-320): задачу составил и ведёт другой участник — вместо
     «Тестерования» и прочих у того, кому она не своя. Заказчик просил
     тёмно-синий; тёмно-синий у «Выполнено», поэтому здесь приглушённый
     стальной и пунктирная рамка — второе отличие, не цветом. */
  foreign: {
    label: "Чужое",
    className: "border-dashed border-mark-foreign/70 text-mark-foreign",
  },
};

/**
 * Вид ярлыка по коду. `null` — ярлыка нет: у уведомления не из «Работы»
 * состояния не бывает, колонка своей доски названа по-своему, а запись,
 * сделанная сборкой с другим набором, могла принести незнакомый код.
 */
export function taskStatusMarkView(
  mark: NotificationMark | null | undefined,
): TaskStatusMarkView | null {
  if (!mark) return null;
  return MARK_VIEWS[mark] ?? null;
}

/** Подпись для скринридера целиком: «Статус: Выполнено». */
export function taskStatusMarkLabel(view: TaskStatusMarkView): string {
  return `Статус: ${view.label}`;
}
