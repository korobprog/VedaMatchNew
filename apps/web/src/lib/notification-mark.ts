import type { NotificationMark } from "@vedamatch/shared";

/**
 * Как выглядит значок состояния в ленте уведомлений (VED-272, VED-312).
 *
 * Зачем он: доска «Работа» возвращает карточку в ленту на каждой смене
 * статуса, и одинаковые с виду уведомления приходится открывать заново, только
 * чтобы понять, что изменилось. API присылает код состояния, слова и цвета —
 * здесь: формулировки собирает клиент, а не издатель события.
 *
 * Слово на значке — ровно название колонки доски, как его видит человек,
 * который её завёл: «В работе», «Тестерование», «Выполнено», «На доработку».
 * «Тестерование» написано через «е» не по ошибке — так называется колонка
 * (сверено с доской), и переименовывать её от себя в значке значило бы
 * показывать человеку не то слово, на которое он нажимал.
 *
 * Знака рядом со словом нет: стрелку у «На доработку» заказчик попросил убрать
 * (VED-312). Приметы осталось две — слово и цвет, — и смысл несёт слово:
 * в чёрно-белой печати и дальтонику «Выполнено» остаётся «Выполнено».
 *
 * Цвета — только токены темы, каждый определён в обеих: `--vm-mark-*`
 * в `globals.css`, там же замеры контраста. Пара на состояние, а не один
 * цвет: тёмно-синее и тёмно-красное, которые просил заказчик, живут на его
 * светлой теме, а тёмная берёт осветлённый тон той же краски — иначе слово
 * не читается. Подложка у значка не заливается цветом: заливка роняет
 * контраст подписи ниже AA.
 */

export interface NotificationMarkView {
  /** Слово на значке — оно же то, что читает скринридер. */
  label: string;
  /**
   * Классы цвета: рамка и текст одним тоном. Фон берётся от карточки, своей
   * заливки у значка нет — см. про контраст выше.
   */
  className: string;
}

const MARK_VIEWS: Record<NotificationMark, NotificationMarkView> = {
  in_progress: {
    label: "В работе",
    className: "border-mark-progress/60 text-mark-progress",
  },
  testing: {
    label: "Тестерование",
    className: "border-mark-testing/60 text-mark-testing",
  },
  done: {
    label: "Выполнено",
    className: "border-mark-done/60 text-mark-done",
  },
  rework: {
    label: "На доработку",
    className: "border-mark-rework/60 text-mark-rework",
  },
};

/**
 * Вид значка по коду. `null` — значка нет: у уведомления не из «Работы»
 * состояния не бывает, а запись, сделанная сборкой с другим набором, могла
 * принести незнакомый код.
 */
export function notificationMarkView(
  mark: NotificationMark | null | undefined,
): NotificationMarkView | null {
  if (!mark) return null;
  return MARK_VIEWS[mark] ?? null;
}

/** Подпись для скринридера целиком: «Статус: Выполнено». */
export function notificationMarkLabel(view: NotificationMarkView): string {
  return `Статус: ${view.label}`;
}
