/**
 * Почему `<audio>` отказался играть — словами, которые человеку что-то
 * говорят. См. docs/music-service-plan.md.
 *
 * Отдельным модулем под тест: сам плеер тестами не покрыт (ему нужен живой
 * `HTMLMediaElement`), а разбор кода ошибки — чистая функция, и ошибиться в
 * ней значит показать человеку неверную причину. Тот же приём, что со
 * `sleep-timer.ts`.
 *
 * Коды — из HTML: 1 прервано человеком, 2 сеть, 3 декодирование, 4 источник
 * не поддерживается. Четвёртый приходит не только на чужой формат: любой
 * ответ, который браузер не считает пригодным звуком, — 404 от хранилища,
 * 401 от API, пустой файл — выглядит для него одинаково. Поэтому подпись у
 * него называет обе вероятные причины, а не гадает.
 */
export function mediaErrorText(error: MediaError | null): string {
  if (!error) return "Не удалось включить запись";

  switch (error.code) {
    case 1: // MEDIA_ERR_ABORTED
      // Человек сам переключил запись — это не отказ, и сообщать не о чем.
      return "";
    case 2: // MEDIA_ERR_NETWORK
      return "Оборвалась сеть. Попробуйте включить снова";
    case 3: // MEDIA_ERR_DECODE
      return "Файл повреждён — запись не читается";
    case 4: // MEDIA_ERR_SRC_NOT_SUPPORTED
      return "Файл не открывается: он не загрузился до конца или в неподдерживаемом формате";
    default:
      return "Не удалось включить запись";
  }
}

/**
 * Сколько ждать, прежде чем признать, что запись не идёт.
 *
 * Пятнадцать секунд: подписанная ссылка и первые килобайты укладываются в
 * секунду даже на слабом канале, а полминуты человек уже не ждёт — он жмёт
 * кнопку снова и обрывает ту самую загрузку, которую ждал.
 */
export const MUSIC_STALL_TIMEOUT_MS = 15_000;

/**
 * Что делать, когда ожидание затянулось.
 *
 * Отказ хранилища выглядит для браузера иначе, чем отказ: на 503 или 404
 * событие `error` приходит за доли секунды, а вот запрос, который приняли и
 * не ответили, не приходит никуда никогда. Элемент остаётся в загрузке
 * навсегда, и вертушка в кнопке — вместе с ним.
 *
 * Различаем два случая по тому, звучало ли уже:
 * — начало не пришло вовсе → это отказ, и об этом надо сказать;
 * — запись играла и упёрлась в пустой буфер → это провал связи посреди
 *   дороги. Звук вернётся сам, когда буфер наберётся, и обрывать его
 *   сообщением об ошибке значит убить то, что ещё живо.
 */
export function stalledVerdict(media: {
  readyState: number;
  currentTime: number;
}): "failed" | "buffering" {
  const started = media.currentTime > 0 || media.readyState >= 2;
  return started ? "buffering" : "failed";
}

/** Подпись, когда начало так и не пришло. */
export const MUSIC_STALL_TEXT =
  "Запись не отвечает: хранилище не отдало файл. Попробуйте ещё раз";

/**
 * Почему браузер отказался начать воспроизведение по `play()`.
 *
 * Это не то же самое, что отказ загрузки. `play()` возвращает промис, и его
 * отклонение — единственный след случившегося: события `error` у элемента
 * при этом нет, `MediaError` пустой, и `mediaErrorText` тут бесполезен.
 * Именно так выглядит запрет автозапуска: файл скачан, длительность
 * известна, а звука нет и сказать об этом некому.
 *
 * `AbortError` возвращает пустую строку намеренно: он приходит, когда
 * начатое воспроизведение прервал новый `load()` — то есть человек сам
 * переключил запись. Показывать ему ошибку не за что, ровно как и на
 * `MEDIA_ERR_ABORTED` выше.
 */
export function playRejectionText(error: unknown): string {
  const name =
    error && typeof error === "object" && "name" in error
      ? String((error as { name: unknown }).name)
      : "";

  switch (name) {
    case "AbortError":
      return "";
    case "NotAllowedError":
      // Автозапуск без жеста. Просить «нажмите ещё раз» — не отписка:
      // второе нажатие идёт уже из жеста и звук включает.
      return "Браузер не включил звук сам. Нажмите «Слушать» ещё раз";
    case "NotSupportedError":
      return "Файл не открывается: он не загрузился до конца или в неподдерживаемом формате";
    default:
      return "Не удалось включить запись";
  }
}
