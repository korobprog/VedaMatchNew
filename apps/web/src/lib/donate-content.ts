/** Получатель перевода, которому можно написать в личку (VED-12). */
export interface DonateRecipient {
  /** Имя так, как человек видит его в мессенджере портала. */
  name: string;
  /**
   * Портальный `User.id` — по нему строится ссылка `/chat/with/<id>`, и
   * страница чата сама заводит личный диалог, если его ещё нет.
   */
  userId: string;
}

