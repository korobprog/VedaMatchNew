/**
 * Содержимое раздела «Поддержать» — единственное место, где его правят.
 *
 * Здесь лежат три списка, каждый под свою карточку доски:
 * - `DONATE_PURPOSES` — цели перевода, которые человек подписывает в
 *   назначении платежа (VED-11);
 * - `DONATE_BANKS` — наши банки и реквизиты (VED-12);
 * - `DONATE_EXPENSES` — статьи трат за месяц (VED-62).
 *
 * Почему константой, а не таблицей в базе: реквизиты и расходы меняются
 * несколько раз в год, а не каждый день, и второй редактор для них (форма в
 * админке) уже есть — он правит короткие строки «СБП / карта / ссылка» (см.
 * `/admin/settings` и `components/donate-sheet.tsx`). Банковский счёт в ту
 * форму не укладывается: у него получатель, ИНН, БИК и корсчёт, и показывать
 * их надо вместе. Поэтому банковские реквизиты и смета живут здесь — в одном
 * файле, который правит разработчик вместе с деплоем.
 *
 * ВАЖНО: цифр в файле нет намеренно. `value: null` и `amountRub: null`
 * означают «ещё не сказали», и страница рисует на этом месте «уточняется», а
 * не выдуманное число. Придумать номер счёта или сумму нельзя: человек по
 * такому номеру отправит деньги в никуда.
 *
 * TODO(VED-12): вписать настоящие реквизиты в `DONATE_BANKS` — получатель,
 * счёт, БИК, корсчёт, ИНН/КПП по каждому банку. До этого блок показывает
 * честное «реквизиты уточняются».
 * TODO(VED-62): вписать настоящие суммы в `DONATE_EXPENSES` (рубли в месяц) и
 * обновить `DONATE_EXPENSES_PERIOD`. До этого блок показывает статьи без сумм.
 */

/** Одна строка реквизита. `value: null` — значение ещё не согласовано. */
export interface DonateRequisiteLine {
  /** Подпись строки: «Получатель», «Счёт», «БИК». */
  label: string;
  /** Значение или `null`, если его ещё не дали. */
  value: string | null;
}

