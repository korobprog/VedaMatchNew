/**
 * Содержимое раздела «Поддержать» — единственное место, где его правят.
 *
 * Здесь лежат три списка, каждый под свою карточку доски:
 * - `DONATE_PURPOSES` — цели перевода, которые человек подписывает в
 *   назначении платежа (VED-11);
 * - `DONATE_RECIPIENTS` — у кого спросить реквизиты, которых нет на странице
 *   (VED-12);
 * - `DONATE_EXPENSES` — статьи трат портала (VED-62).
 *
 * Реквизитов здесь нет и не будет: по VED-12 заказчик оставил на странице
 * только «Быстрый перевод» — имена, телефоны и карты получателей, которые
 * правятся формой в админке (`/admin/settings`, см.
 * `components/donate-sheet.tsx`). Каркас под банковский счёт с БИК, корсчётом
 * и ИНН он вычеркнул целиком, поэтому страница о нём больше не знает; всё
 * остальное человек спрашивает у получателей в личке — за это отвечает
 * `DONATE_RECIPIENTS`.
 *
 * ВАЖНО: цифр в файле нет намеренно. Сумм по статьям расходов заказчик
 * публиковать не стал — список отвечает на вопрос «за что портал платит», а
 * не «сколько». Выдуманные цифры здесь недопустимы: по ним человек считает
 * свой перевод.
 */

/**
 * Цель перевода (VED-11). Человек выбирает одну, страница собирает из неё
 * строку для поля «назначение платежа», а мы по выписке понимаем, за что
 * пришли деньги. Формулировки короткие: банки режут назначение по длине.
 */
export interface DonatePurpose {
  id: string;
  /** Что человек выбирает в списке. */
  label: string;
  /** Что это значит — одной строкой под списком. */
  hint: string;
  /**
   * Готовая формулировка для поля «назначение платежа» — целиком, а не
   * заготовка, к которой код приклеивает «Дар». Склейка ломается о падежи:
   * из «Благодарность разработчикам» получалось «Дар на благодарность
   * разработчикам». Как написано здесь — так и попадёт в выписку.
   */
  transfer: string;
}

