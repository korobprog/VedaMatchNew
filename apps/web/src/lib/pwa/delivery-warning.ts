import type { NotificationDeliveryStatusDto } from "@vedamatch/shared";
import type { PushSupport } from "./push-subscription";

/**
 * Правда человеку про его уведомления (VED-314).
 *
 * Раньше портал молчал: человек жал «включить», видел «Уведомления приходят и
 * на это устройство» и оставался в этой уверенности — а на сервере у него не
 * было ни одной точки доставки, и девять уведомлений за вечер прошли мимо. В
 * логах при этом стояло «пропущено: нет подписок», но логи человек не читает.
 *
 * Чистая функция: что показать — решает она, а карточка настроек только
 * рисует. Колокольчик работает и без пушей, поэтому предупреждение говорит про
 * устройство, а не про «уведомления не работают».
 */

export interface DeliveryWarning {
  title: string;
  hint: string;
}

const ALSO_BELL =
  "Список в колокольчике работает и без этого, но сам он не звонит.";

export function deliveryWarning(input: {
  /** Тумблер «Все уведомления». */
  enabled: boolean;
  /** Ответ сервера; `null` — ещё не загрузили или запрос не удался. */
  status: NotificationDeliveryStatusDto | null;
  /** Разрешение браузера на этой странице. */
  support: PushSupport;
}): DeliveryWarning | null {
  const { enabled, status, support } = input;
  // Не знаем — не пугаем: молчание сервера не повод обещать неприятности.
  if (!status) return null;
  // Выключил сам — про это уже сказано строкой ниже, второй раз не нужно.
  if (!enabled) return null;
  if (status.reachable) return null;

  const stale =
    status.stale > 0
      ? "Прежние подписки помечены мёртвыми: месяц без единого принятого пуша. "
      : "";

  return {
    title: "Уведомления включены, но доставлять их некуда",
    hint: stale + hintFor(support),
  };
}

function hintFor(support: PushSupport): string {
  switch (support) {
    case "granted":
      // Самый неприятный случай: разрешение есть, а подписки на сервере нет —
      // ключей VAPID не было в момент подписки, браузер сменил подписку молча
      // или запрос не дошёл.
      return `Разрешение браузер выдал, но подписка до сервера не дошла. Обновите страницу; если строка осталась — выключите и снова включите уведомления для сайта в настройках браузера. ${ALSO_BELL}`;
    case "default":
      return `Включите уведомления на это устройство кнопкой ниже — или войдите в приложение VedaMatch на телефоне. ${ALSO_BELL}`;
    case "denied":
      return `Этот браузер уведомления для сайта запретил — вернуть разрешение можно только в его настройках. Другой путь: приложение VedaMatch на телефоне. ${ALSO_BELL}`;
    default:
      return `Этот браузер не умеет присылать уведомления на устройство. Откройте портал в другом браузере или поставьте приложение VedaMatch. ${ALSO_BELL}`;
  }
}
