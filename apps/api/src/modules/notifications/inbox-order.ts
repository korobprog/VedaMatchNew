/**
 * Порядок ленты уведомлений (VED-153).
 *
 * Правило одно: непрочитанное впереди, а внутри каждой группы свежее сверху —
 * «чем ниже, тем старее». Раньше порядок задавался одним `orderBy` Prisma:
 *
 *     orderBy: [{ readAt: { sort: 'asc', nulls: 'first' } }, { createdAt: 'desc' }]
 *
 * Первая строка задумывалась только как «сначала непрочитанное» (`null`
 * первым), но она же сортирует и сами прочитанные — по времени прочтения и
 * по возрастанию. То есть наверху прочитанной части оказывалось то, что
 * открыли раньше всех, а самое свежее уезжало в самый низ. `createdAt: 'desc'`
 * при этом почти не работал: он разнимал только строки с совпадающей до
 * миллисекунды меткой `readAt` — такие даёт лишь «отметить все прочитанными».
 *
 * Выразить «сначала непрочитанное, потом по дате создания» одним `orderBy`
 * Prisma не умеет: это сортировка по выражению (`readAt IS NULL`), а не по
 * колонке. Поэтому выборка идёт по индексу `[userId, createdAt]`, а группы
 * расставляет эта чистая функция.
 */

/** Ровно те поля строки, от которых зависит порядок. */
export interface InboxOrderRow {
  createdAt: Date;
  /** `null` — ещё не прочитано. */
  readAt: Date | null;
}

/**
 * Сравнение двух уведомлений: меньше — выше в списке.
 *
 * Прочитанность важнее даты: человек приходит за новым, и свежее прочитанное
 * не должно перепрыгивать непрочитанное, до которого руки ещё не дошли.
 */
export function compareInboxRows(a: InboxOrderRow, b: InboxOrderRow): number {
  const unreadFirst = Number(a.readAt !== null) - Number(b.readAt !== null);
  if (unreadFirst !== 0) return unreadFirst;
  return b.createdAt.getTime() - a.createdAt.getTime();
}

/**
 * Лента в нужном порядке. Не трогает исходный массив: строки приходят из
 * Prisma, и сортировка на месте переставила бы чужой результат.
 */
export function sortInboxRows<T extends InboxOrderRow>(
  rows: readonly T[],
): T[] {
  return [...rows].sort(compareInboxRows);
}
