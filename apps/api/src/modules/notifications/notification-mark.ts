import {
  parseNotificationMark,
  parseTaskStatusMark,
  type NotificationMark,
} from '@vedamatch/shared';

/**
 * Значок уведомления в ленте (VED-272, VED-320, VED-298).
 *
 * Разбора названия колонки здесь нет — он живёт в «Работе»
 * (`work-task-status.ts`), и уведомления получают готовый код в событии.
 *
 * В строке уведомления значок хранится двумя колонками, и это намеренно:
 *
 * - `mark` — состояние задачи. Его переписывает `refreshWorkTaskMark` на
 *   каждом переезде карточки (VED-320), у всех уведомлений о задаче сразу, и
 *   ставит `null`, когда карточка уехала в колонку без состояния.
 * - `markFallback` — значок на этот случай, свой у вида новости. Пока он один:
 *   `comment` у уведомления о комментарии (VED-298: «если уведомление о
 *   комментарии не имеет своего статуса, добавь ей цветной статус
 *   Комментарий»). Переезд его не трогает — комментарий остаётся
 *   комментарием, куда бы ни уехала карточка.
 *
 * Одной колонкой не обойтись: переезд в колонку без состояния обнулил бы
 * `mark`, и понять, что строка была комментарием, стало бы не из чего.
 */
export function inboxMark(
  mark: string | null | undefined,
  markFallback: string | null | undefined,
): NotificationMark | null {
  // Состояние — первым: «что с задачей сейчас» важнее вида новости. Через
  // parse, а не as: в колонке строка, и запись, сделанная сборкой с другим
  // набором, не должна утекать клиенту неизвестным кодом.
  return parseTaskStatusMark(mark) ?? parseNotificationMark(markFallback);
}
