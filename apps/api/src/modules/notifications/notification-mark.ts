import type { NotificationMark } from '@vedamatch/shared';

/**
 * Значок состояния для уведомления (VED-272).
 *
 * Зачем он нужен: доска «Работа» возвращает карточку в ленту на каждой смене
 * статуса, и одинаковые с виду уведомления приходится открывать заново, чтобы
 * понять, что изменилось. Четыре самых частых состояния — «В работе»,
 * «Тестирование», «Выполнено», «На доработку» — получают заметную пометку, и
 * открывать ради них карточку больше не нужно.
 *
 * Почему разбором названия, а не признаком колонки: своего типа у колонки нет,
 * есть только имя (`WorkColumn.name`) и флаг `isDone`. Флаг сюда не годится
 * вдвойне — он живёт в таблицах «Работы», которые модуль уведомлений читать не
 * вправе, а в событие приходит ровно название колонки, как его написал человек.
 *
 * Незнакомое название — `null`, и уведомление остаётся без значка. Это норма,
 * а не потеря: у своей доски колонки называют по-своему, и подписать чужое
 * «Бэклог» одним из четырёх наших слов было бы хуже, чем не подписать вовсе.
 */

/** Нормализация названия колонки: регистр, ё и лишние пробелы не в счёт. */
function normalize(columnName: string): string {
  return columnName
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[«»"'`]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Названия колонок, которые считаем тем или иным состоянием.
 *
 * Синонимы — ровно те, что встречаются на досках портала; расширять список
 * догадками не нужно: незнакомое название честнее оставить без значка.
 */
const MARK_BY_COLUMN: ReadonlyArray<readonly [NotificationMark, string[]]> = [
  ['in_progress', ['в работе', 'в работу', 'работа', 'в процессе', 'делается']],
  [
    // «Тестерование» через «е» — не опечатка в списке, а название колонки на
    // доске портала, как его написал человек (сверено с доской, VED-312).
    // Без этого синонима самая частая колонка тестирования приходила сюда
    // незнакомой и уведомление оставалось вовсе без значка.
    'testing',
    [
      'тестирование',
      'тестерование',
      'на тестировании',
      'на тестеровании',
      'тест',
      'на проверке',
      'проверка',
    ],
  ],
  ['done', ['выполнено', 'готово', 'сделано', 'завершено', 'закрыто']],
  [
    'rework',
    ['на доработку', 'доработка', 'на доработке', 'вернули', 'возврат'],
  ],
];

/** Состояние по названию колонки; `null` — название не из известной четвёрки. */
export function resolveColumnMark(
  columnName: string | null | undefined,
): NotificationMark | null {
  if (!columnName) return null;
  const name = normalize(columnName);
  if (!name) return null;
  for (const [mark, names] of MARK_BY_COLUMN) {
    if (names.includes(name)) return mark;
  }
  return null;
}

/**
 * Обратная проверка для хранения: в базе значок лежит строкой, и строка из
 * старой записи может не знать нынешнего набора.
 */
export function parseNotificationMark(
  value: string | null | undefined,
): NotificationMark | null {
  switch (value) {
    case 'in_progress':
    case 'testing':
    case 'done':
    case 'rework':
      return value;
    default:
      return null;
  }
}
