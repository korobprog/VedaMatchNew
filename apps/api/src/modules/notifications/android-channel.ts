import type { NotificationCategory } from '@vedamatch/shared';

/**
 * В какую категорию уведомлений Android класть пуш (VED-361).
 *
 * До этой карточки канал был один — `messages`, и в него шло всё: и переписка,
 * и звонок. Человек, выключивший в системных настройках категорию
 * «Сообщения», переставал получать и вызовы, причём молча: сервер по-прежнему
 * числил телефон живой точкой доставки и честно отправлял пуш, а Android его
 * прятал. Каналов теперь два, и выключить их можно порознь.
 *
 * Идентификаторы обязаны совпадать со строками, которыми приложение эти
 * каналы создаёт (`apps/mobile/src/lib/push/device-registration.ts`): пуш в
 * несуществующий канал Android показывает на служебном
 * `fallback`-канале — без звука звонка и без настройки, которую человек
 * искал бы в списке категорий.
 *
 * Модуль чистый: строка на входе, строка на выходе. Канал — часть контракта
 * с приложением, и меняться он должен вместе с тестом, а не по ходу правки
 * отправителя.
 */

/** Канал «Сообщения»: переписка, заявки, новости — всё, кроме звонков. */
export const ANDROID_MESSAGES_CHANNEL_ID = 'messages';

/**
 * Канал «Звонки»: входящий, пропущенный, зов в групповой. Отдельный канал
 * нужен не только ради тумблера: у звонка своя важность и свой звук, а
 * пометить их у Android можно только на уровне канала.
 */
export const ANDROID_CALLS_CHANNEL_ID = 'calls';

export function androidChannelFor(category: NotificationCategory): string {
  return category === 'calls'
    ? ANDROID_CALLS_CHANNEL_ID
    : ANDROID_MESSAGES_CHANNEL_ID;
}
