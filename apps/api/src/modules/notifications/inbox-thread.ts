import type { NotificationMark } from '@vedamatch/shared';

/**
 * Ветки новостей в ленте (VED-320).
 *
 * Заказчик описал ленту как список задач, а не список событий: «задача
 * поднимается вверх по ленте уведомлений для всех остальных админов, но не для
 * него», и так на каждой смене статуса. До этого каждая смена статуса,
 * пережившая окно дозревания, клала человеку новую строку — пять переездов
 * одной карточки за день давали пять строк об одном и том же.
 *
 * Ветка — одна строка на человека и ключ (`NotificationItem.threadKey`,
 * уникален в паре с `userId`). Повторная новость в ветке переписывает строку и
 * поднимает её: свежая дата и снова непрочитана. Порядок ленты (VED-153,
 * `inbox-order.ts`) при этом не трогаем вовсе: он сортирует по `createdAt`, и
 * поднятая строка встаёт наверх по тому же правилу, что и новая.
 *
 * Со склейкой VED-298 ветка не спорит, а продолжает её дальше по времени.
 * Склейка работает ДО отправки: всё, что человек сделал с карточкой за три
 * минуты, уходит одной новостью. Ветка работает ПОСЛЕ: следующая новость о той
 * же карточке, за окном, ложится в ту же строку, а не рядом.
 */

/** Ключ ветки «смена статуса задачи». Адрес карточки уже однозначен. */
export function workStatusThreadKey(taskUrl: string): string {
  return `work-status:${taskUrl}`;
}

export interface InboxThreadNews {
  title: string;
  body: string;
  url: string;
  category: string;
  mark: NotificationMark | null;
}

/**
 * Что записать в уже лежащую строку ветки, когда пришла новая новость.
 *
 * Текст переписывается целиком: строка ветки — это «что с задачей сейчас», а
 * не лог. История переездов живёт в самой карточке (`WorkActivity`).
 */
export function threadRefreshData(news: InboxThreadNews, now: Date) {
  return {
    title: news.title,
    body: news.body,
    url: news.url,
    category: news.category,
    mark: news.mark,
    ...threadLiftData(now),
  };
}

/**
 * Подъём строки без новой новости — карточку только что передвинули, слова
 * о переезде доедут через окно дозревания.
 *
 * Непрочитанной строка становится намеренно: лента ставит непрочитанное выше
 * прочитанного, и поднятая, но прочитанная строка осталась бы под любым
 * непрочитанным, то есть не поднялась бы. Да и смысл подъёма — «посмотри, в
 * задаче что-то изменилось», а это и есть непрочитанное.
 */
export function threadLiftData(now: Date): { createdAt: Date; readAt: null } {
  return { createdAt: now, readAt: null };
}

/**
 * У кого поднимать строку. Пустые и повторы отбрасываются: из пустого `in`
 * Prisma строит запрос, который ничего не найдёт, — но ходить в базу незачем.
 */
export function liftRecipients(ids: readonly string[] | undefined): string[] {
  return [...new Set((ids ?? []).filter((id) => id.length > 0))];
}

/**
 * Две доставки в одну ветку могут столкнуться: воркер «Работы» отдаёт события
 * подряд, а доставка асинхронна. Проигравшая вставка упирается в уникальность
 * `[userId, threadKey]` — это не ошибка, а сигнал «строка уже есть, обнови её».
 */
export function isUniqueViolation(error: unknown): boolean {
  return (
    typeof error === 'object' &&
    error !== null &&
    (error as { code?: unknown }).code === 'P2002'
  );
}
