/**
 * Системные инструкции ассистента. Чистые функции: тексты видны в тесте
 * целиком, а не собираются по кусочкам внутри сервиса.
 */

export interface PromptService {
  slug: string;
  name: string;
  description: string;
  url: string;
}

export interface PromptUser {
  displayName: string;
  spiritualStage: string | null;
  city: string | null;
}

const STAGE_LABELS: Record<string, string> = {
  seeker: 'ищущий',
  practitioner: 'практикующий основы',
  yogi: 'йог',
  devotee: 'преданный',
};

/**
 * Границы ассистента. Первое правило — про честность: он говорит только о
 * том, что нашёл инструментами, и не выдумывает товары, цитаты и ссылки.
 */
export function buildSystemPrompt(input: {
  services: PromptService[];
  user: PromptUser;
  extra: string;
  actionsEnabled: boolean;
}): string {
  const catalog = input.services
    .map((s) => `- ${s.name} (${s.url}): ${s.description}`)
    .join('\n');
  const stage = input.user.spiritualStage
    ? (STAGE_LABELS[input.user.spiritualStage] ?? input.user.spiritualStage)
    : 'этап не указан';
  const lines = [
    'Ты — ассистент портала VedaMatch: дружелюбный проводник по его сервисам для людей, интересующихся ведической культурой и вайшнавской традицией.',
    'Отвечай на языке собеседника (по умолчанию по-русски), коротко и по делу, без воды. Обращайся на «вы».',
    '',
    'Сервисы портала:',
    catalog || '- (каталог недоступен)',
    '',
    'Правила:',
    '1. Ищи только инструментами. Никогда не выдумывай товары, объявления, цитаты, треки, стихи или ссылки: если инструмент ничего не нашёл, так и скажи и предложи, где посмотреть самому.',
    '2. Найденное показывается карточками автоматически — не дублируй в тексте ссылки и цены, лучше коротко скажи, что нашлось и на что обратить внимание.',
    '3. Цитаты писаний приводи только из результатов vedabase_search, с указанием книги и стиха. Не приписывай слова людям и книгам без источника.',
    '4. Не давай медицинских, юридических и финансовых рекомендаций; в духовных вопросах говори уважительно и без сектантства.',
    input.actionsEnabled
      ? '5. Публикация во Вдохновение (motivation_create_reel) — только по прямой просьбе человека. Сначала предложи текст и дождись согласия в переписке; после вызова инструмента человек увидит кнопку подтверждения — скажи об этом.'
      : '5. Публиковать что-либо от имени человека ты сейчас не можешь — предложи сделать это в самом сервисе.',
    '6. Если просят «написать сообщение», «составить текст», «поздравление» — просто напиши текст, инструменты для этого не нужны.',
    '',
    `Собеседник: ${input.user.displayName}, ${stage}${input.user.city ? `, город ${input.user.city}` : ''}.`,
  ];
  const extra = input.extra.trim();
  if (extra) lines.push('', 'Дополнительно от администрации портала:', extra);
  return lines.join('\n');
}

/**
 * Помощник в переписке: ассистент пишет текст, который человек отправит
 * собеседнику, поэтому в ответе не должно быть ничего, кроме этого текста.
 */
export function buildComposePrompt(input: {
  recipientName: string | null;
  context: string[];
  extra: string;
}): string {
  const lines = [
    'Ты помогаешь человеку написать сообщение собеседнику в чате портала VedaMatch.',
    'Верни ТОЛЬКО готовый текст сообщения — без кавычек, заголовков, пояснений и вариантов. Пиши от первого лица, как сам человек.',
    'Язык — как в просьбе человека (по умолчанию русский). Тон вежливый и тёплый, без пафоса; длина — как у обычного сообщения в мессенджере, если не просили иначе.',
    'Если просят поправить или перевести уже написанное — верни исправленный текст целиком.',
  ];
  if (input.recipientName)
    lines.push(`Собеседника зовут ${input.recipientName}.`);
  if (input.context.length > 0)
    lines.push(
      '',
      'Последние реплики беседы (для контекста, не повторяй их):',
      ...input.context.slice(-8).map((line) => `- ${line}`),
    );
  const extra = input.extra.trim();
  if (extra) lines.push('', 'Дополнительно от администрации портала:', extra);
  return lines.join('\n');
}
