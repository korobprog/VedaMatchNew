/**
 * Сколько открытых жалоб скрывают предложение автоматически.
 *
 * Копия notices/report-threshold.ts: контракт сервисного модуля запрещает
 * импортировать хелперы чужого модуля.
 *
 * Три — компромисс: одной жалобы мало (ею легко свести счёты), а десяти на
 * небольшой ленте никогда не наберётся. Скрытие обратимо: админ возвращает
 * предложение из панели.
 */
export const REPORT_HIDE_THRESHOLD = 3;

/**
 * Пересекла ли жалоба порог именно сейчас. Сравниваем ровно с порогом, а не
 * `>=`: иначе предложение скрывалось бы снова после того, как админ его
 * вернул.
 */
export function crossesHideThreshold(openReportsCountAfter: number): boolean {
  return openReportsCountAfter === REPORT_HIDE_THRESHOLD;
}
