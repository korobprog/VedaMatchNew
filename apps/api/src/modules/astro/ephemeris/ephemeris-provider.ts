/**
 * Слой эфемерид: чистая астрономия и ничего сверх неё.
 *
 * Провайдер возвращает ТРОПИЧЕСКИЕ видимые геоцентрические координаты на дату.
 * Аянамша, накшатры, даши и варги живут в ведическом слое поверх: это разные виды
 * знания, и шов между ними проходит здесь. Благодаря этому западная карта (тропик,
 * Плацидус, аспекты) переиспользует тот же провайдер без изменений.
 *
 * Реализация прячется за интерфейсом, чтобы замена движка не расползалась по коду.
 */

/** Девять грах джйотиша. Раху и Кету — средние узлы лунной орбиты, не тела. */
export type GrahaId =
  | 'sun'
  | 'moon'
  | 'mercury'
  | 'venus'
  | 'mars'
  | 'jupiter'
  | 'saturn'
  | 'rahu'
  | 'ketu';

export interface BodyPosition {
  body: GrahaId;
  /** Видимая геоцентрическая эклиптическая долгота, градусы [0, 360), тропическая. */
  longitude: number;
  /** Эклиптическая широта, градусы. */
  latitude: number;
  /** Градусов в сутки. Отрицательная — ретроградное движение. */
  speed: number;
}

export interface ChartAngles {
  /** Асцендент (лагна), тропическая долгота в градусах. */
  ascendant: number;
  /** Середина неба (MC), тропическая долгота в градусах. */
  midheaven: number;
  /** Истинный наклон эклиптики на дату, градусы. */
  obliquity: number;
  /** Местное истинное звёздное время, градусы. */
  localSiderealTime: number;
}

export interface EphemerisProvider {
  /**
   * Входит в fingerprint карты. Без этого после смены движка в кэше остались бы
   * карты, посчитанные другой математикой, и никто бы этого не заметил.
   */
  readonly version: string;

  /** Позиции всех девяти грах на момент времени. */
  positions(at: Date): BodyPosition[];

  /** Асцендент и MC. Широта/долгота места — градусы, восток и север положительны. */
  angles(at: Date, latitude: number, longitude: number): ChartAngles;
}
