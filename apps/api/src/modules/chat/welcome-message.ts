    'Важно: сайт пока в активной разработке. Многое уже работает, но ещё больше мы добавим и улучшим в ближайшее время, так что просьба не судить строго 😊',
    'Если вдруг изредка немного виснет, значит обновляем. Так с любыми сайтами.',
