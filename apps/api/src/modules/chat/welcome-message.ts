/**
 * Приветствие новому участнику в переписке (VED-20).
 *
 * В колокольчик приветствие приходило и раньше, но просили другого: чтобы
 * администратор видел его в истории переписки с новым человеком. Чужие личные
 * диалоги администратору не показываются — и правильно, — поэтому приветствие
 * приходит письмом от самой администрации: диалог получается её собственным.
 *
 * Текст живёт в «Общении», а не там, где издаётся событие о регистрации:
 * формулировку для человека собирает подписчик, издатель сообщает факт.
 */

/**
 * Письмо с личным обращением. Без имени — без обращения: «Здравствуйте, !»
 * хуже, чем просто «Добро пожаловать».
 */
export function welcomeMessage(name: string): string {
  const person = name.trim();
  const greeting = person
    ? `${person}, добро пожаловать в VedaMatch!`
    : 'Добро пожаловать в VedaMatch!';
  return [
    greeting,
    '',
    'Здесь восемь сервисов: знакомства, общение, практика, знания и рынок. ' +
      'Чтобы не теряться, начните с короткой настройки — она подскажет, что ' +
      'открыть первым; ссылка на неё пришла в колокольчик.',
    '',
    'Это личная переписка с администрацией портала: если что-то не находится ' +
      'или не работает, просто ответьте на это сообщение.',
  ].join('\n');
}
