/**
 * Где в бакете лежат файлы «Общения».
 *
 * Ключ объекта — часть защиты, а не деталь именования: проверка вложения
 * (`chat-validate.ts`) пускает только те адреса, ключ которых начинается с
 * разрешённого пути. Пока путей был один, он собирался строкой прямо в
 * проверке; с появлением моментов их два, и держать их в разных файлах
 * значит однажды разрешить лишнее.
 */

/** Папка беседы: сюда кладутся вложения её сообщений. */
export function conversationKeyPrefix(conversationId: string): string {
  return `chat/${conversationId}/`;
}

/**
 * Папка моментов человека. Не привязана к беседе: момент старше любой из них
 * и не принадлежит ни одной, а ответы на него живут сразу в нескольких.
 *
 * Совпасть с папкой беседы она не может: идентификатор беседы — uuid, и
 * `chat/moments/` им не бывает. Проверка на это есть в тесте — правило
 * держится на форме идентификатора, а не на удаче.
 */
export function momentKeyPrefix(authorId: string): string {
  return `chat/moments/${authorId}/`;
}
