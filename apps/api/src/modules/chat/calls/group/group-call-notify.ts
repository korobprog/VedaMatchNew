/**
 * Кого и когда будить уведомлением о групповом звонке — чистым модулем, без
 * Prisma и шины.
 *
 * Плашка «идёт звонок» внутри беседы (этап 1) видна только тому, кто в эту
 * беседу уже смотрит. Человек со свёрнутым приложением и закрытой вкладкой о
 * звонке не узнавал вовсе — это и чинится здесь.
 *
 * Правила тут отбирают, кого уведомление НЕ должно достать, и это важнее,
 * чем кого должно: ошибка в любую сторону — это либо молчание (ради чего всё
 * и затевалось), либо будильник на всю беседу. Держать такой отбор вперемешку
 * с запросами к базе нельзя — его надо проверять таблицей случаев.
 *
 * Тип уведомления свой (`chat.group-call-started`), а не `chat.call-incoming`:
 * см. докстрингу события в `@vedamatch/shared`.
 */

/**
 * Раньше этого срока одна комната не имеет права разбудить беседу второй раз.
 *
 * Без такого окна каждый новый участник рассылал бы уведомление всем
 * остальным: четверо в комнате — четыре волны по всей беседе. С окном
 * получается «сказали, что начали» и, если разговор идёт уже давно, редкое
 * напоминание тем, кто так и не пришёл.
 *
 * Десять минут — не настройка, а оценка: короче, и разговор на полчаса
 * успевает позвать одного и того же человека трижды; длиннее, и тот, кто
 * подключился к часовой встрече, второй волны уже не дождётся.
 */
export const GROUP_CALL_NOTIFY_COOLDOWN_MS = 10 * 60_000;

/**
 * Насколько «только что вышел» считается «знает о звонке». Человек, сам
 * нажавший «Выйти», не должен через секунду получить пуш «идёт звонок» от
 * того, кто вошёл следом: он уходил осознанно.
 */
export const GROUP_CALL_RECENT_LEAVE_MS = 5 * 60_000;

/** Что известно про одного участника беседы на момент рассылки. */
export interface NotifyCandidate {
  userId: string;
  /** Ушёл из беседы (`ChatMember.leftAt`) — он больше не участник. */
  leftConversation: boolean;
  /** До какого момента беседа заглушена (`mutedUntil`, ms); null — не глушена. */
  mutedUntil: number | null;
  /** Живой участник комнаты прямо сейчас — он и так в разговоре. */
  inRoom: boolean;
  /** Когда вышел из комнаты (ms); null — не входил или всё ещё внутри. */
  leftRoomAt: number | null;
  /** Смотрит эту беседу прямо сейчас — плашку «идёт звонок» он уже видит. */
  viewing: boolean;
}

/**
 * Кому уходит уведомление. Порядок сохраняется входной — рассылка
 * предсказуема, и в тесте не надо сортировать результат.
 *
 * Отсеиваются пятеро:
 * 1. ушедшие из беседы — они уже не её участники;
 * 2. заглушившие беседу — глушение и заводят ровно затем, чтобы она молчала;
 * 3. те, кто в комнате, — включая того, чей вход всё это и вызвал;
 * 4. только что вышедшие из комнаты — см. `GROUP_CALL_RECENT_LEAVE_MS`;
 * 5. смотрящие беседу — у них плашка «идёт звонок» уже на экране, и пуш
 *    поверх неё только дублирует.
 */
export function groupCallNotifyTargets(
  candidates: readonly NotifyCandidate[],
  now: number,
): string[] {
  return candidates
    .filter((candidate) => !candidate.leftConversation)
    .filter(
      (candidate) =>
        !(candidate.mutedUntil !== null && candidate.mutedUntil > now),
    )
    .filter((candidate) => !candidate.inRoom)
    .filter(
      (candidate) =>
        candidate.leftRoomAt === null ||
        now - candidate.leftRoomAt > GROUP_CALL_RECENT_LEAVE_MS,
    )
    .filter((candidate) => !candidate.viewing)
    .map((candidate) => candidate.userId);
}

/**
 * Имеет ли комната право разослать уведомление сейчас.
 *
 * `lastNotifiedAt` — отметка из `ChatGroupCall.notifiedAt`, а не счётчик в
 * памяти процесса: API работает не в одном экземпляре, и «мы уже слали»
 * обязано пережить перезапуск и быть общим для всех инстансов. Сама отметка
 * ставится условным `updateMany` по тому же порогу — кто первым её переписал,
 * тот и рассылает, остальные получают `count: 0` и молчат.
 */
export function mayNotifyRoom(
  lastNotifiedAt: number | null,
  now: number,
): boolean {
  if (lastNotifiedAt === null) return true;
  return now - lastNotifiedAt >= GROUP_CALL_NOTIFY_COOLDOWN_MS;
}

/** Момент, раньше которого прошлая рассылка уже не мешает новой. */
export function notifyCooldownThreshold(now: number): Date {
  return new Date(now - GROUP_CALL_NOTIFY_COOLDOWN_MS);
}
