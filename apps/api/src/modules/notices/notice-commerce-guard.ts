/**
 * Поиск признаков коммерции в тексте объявления.
 *
 * Доска некоммерческая структурно: денежных полей в модели нет вообще, и
 * продать что-то, не изменив схему, нельзя. Но текст свободный, и «массаж
 * 2000 ₽» в описание вписать можно — этим и занимается проверка.
 *
 * Она НЕ блокирует публикацию. Ложное срабатывание на «отдам даром, забрать
 * до 18:00» не должно молча съедать объявление, поэтому результат — только
 * пометка `needsReview` для очереди модератора и подсказка в форме.
 */

export interface CommerceSignals {
  score: number;
  /** Что именно сработало — модератору видно, за что зацепились. */
  hits: string[];
}

/**
 * Границы слова через юникодные свойства, а не `\b`: в JS граница слова
 * определена по ASCII, и вокруг кириллицы `\bпрайс\b` не совпадает ни с чем.
 * Та же ловушка, что в community-slug.ts.
 */
const LEFT = '(?<![\\p{L}\\p{N}])';
const RIGHT = '(?![\\p{L}\\p{N}])';

/**
 * Целое слово: «руб», но не «рубанок». Тело оборачивается в группу — иначе
 * альтернатива внутри разорвала бы границы: `а|б` дал бы `LEFT а` или
 * `б RIGHT`, а не то и другое сразу.
 */
const word = (body: string) => new RegExp(`${LEFT}(?:${body})${RIGHT}`, 'iu');
/** Начало слова: «скидк» ловит «скидка», «скидки», «скидочный». */
const stem = (body: string) => new RegExp(`${LEFT}${body}`, 'iu');

const AMOUNT = '\\d[\\d\\s.,]*';

/** Цена: число рядом с валютой, в любом порядке. */
const PRICE_PATTERNS: Array<[RegExp, string]> = [
  [
    new RegExp(`${AMOUNT}\\s*(₽|руб|р\\.|рублей|рубля)${RIGHT}`, 'iu'),
    'цена в рублях',
  ],
  [new RegExp(`(\\$|€|usd|eur)\\s*\\d`, 'iu'), 'цена в валюте'],
  [new RegExp(`${AMOUNT}\\s*(\\$|€|usd|eur)${RIGHT}`, 'iu'), 'цена в валюте'],
  [
    new RegExp(`${AMOUNT}\\s*(грн|тг|сум|тенге)${RIGHT}`, 'iu'),
    'цена в валюте',
  ],
  [
    new RegExp(
      `\\d{3,}\\s*(за|в)\\s*(час|сеанс|занятие|урок|месяц|штук)`,
      'iu',
    ),
    'ставка за услугу',
  ],
];

/** Слова, за которыми почти всегда стоит продажа или МЛМ. */
const WORD_PATTERNS: Array<[RegExp, string]> = [
  [word('прайс'), 'прайс'],
  [stem('скидк'), 'скидка'],
  [stem('предоплат'), 'предоплата'],
  [stem('рассрочк'), 'рассрочка'],
  [word('оптом|опт'), 'опт'],
  [new RegExp(`${LEFT}доставка\\s+платн`, 'iu'), 'платная доставка'],
  [stem('стоимость'), 'стоимость'],
  [new RegExp(`${LEFT}(по\\s+цене|цена\\s*[:—-])`, 'iu'), 'цена'],
  [
    new RegExp(`${LEFT}(заработок|доход\\s+от)${RIGHT}`, 'iu'),
    'обещание дохода',
  ],
  [stem('инвестиц'), 'инвестиции'],
  [
    // \p{L}*, а не \w*: «партнёрскую» кончается кириллицей, которую \w не знает.
    new RegExp(`${LEFT}партн[её]рск\\p{L}*\\s+программ`, 'iu'),
    'партнёрская программа',
  ],
  [new RegExp(`${LEFT}бизнес[-\\s]возможност`, 'iu'), 'бизнес-возможность'],
  [word('сетевой\\s+маркетинг|млм'), 'сетевой маркетинг'],
];

/**
 * Порог, с которого объявление попадает в очередь модератора.
 *
 * Единица — намеренно низкий порог: пометка ничего не ломает, а пропущенная
 * коммерция размывает границу с Рынком, ради которой сервис и заведён.
 */
export const REVIEW_THRESHOLD = 1;

export function detectCommerce(
  title: string | null | undefined,
  description: string | null | undefined,
): CommerceSignals {
  const text = `${title ?? ''}\n${description ?? ''}`;
  if (!text.trim()) return { score: 0, hits: [] };

  const hits: string[] = [];
  for (const [pattern, label] of [...PRICE_PATTERNS, ...WORD_PATTERNS]) {
    if (pattern.test(text) && !hits.includes(label)) hits.push(label);
  }
  return { score: hits.length, hits };
}

export function needsReview(signals: CommerceSignals): boolean {
  return signals.score >= REVIEW_THRESHOLD;
}
