/**
 * Сколько открытых жалоб скрывают объявление автоматически.
 *
 * Копия market/report-threshold.ts: контракт сервисного модуля запрещает
 * импортировать хелперы чужого модуля.
 *
 * Три — компромисс: одной жалобы мало (ею легко свести счёты), а десяти на
 * небольшой доске никогда не наберётся, и постмодерация превратится в её
 * отсутствие. Скрытие обратимо: админ возвращает объявление из панели.
 */
export const REPORT_HIDE_THRESHOLD = 3;

/**
 * Пересекла ли жалоба порог именно сейчас.
 *
 * Ключевое здесь — «именно сейчас»: проверка `count >= threshold` срабатывала
 * бы на каждой следующей жалобе, и объявление скрывалось бы снова после того,
 * как админ его вернул. Поэтому сравниваем ровно с порогом.
 */
export function crossesHideThreshold(openReportsCountAfter: number): boolean {
  return openReportsCountAfter === REPORT_HIDE_THRESHOLD;
}
