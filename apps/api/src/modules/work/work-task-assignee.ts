/**
 * Исполнитель задачи не пустует (VED-320).
 *
 * Заказчик: «Для каждой задачи исполнитель должен проставляться
 * автоматически, тот кто делает тот и исполнитель. Но если вдруг графа
 * пустует, проверь кто составил и пропиши». Поэтому пустой исполнитель —
 * при создании и при правке — становится составившим задачу. Это же
 * правило «исполнитель — тот, на ком ход»: завёл задачу — ход твой, пока не
 * передал другому. Задачу, заведённую агентом, получает агент — как и
 * договорено в CLAUDE.md.
 *
 * `null` остаётся, только если не известен и составивший (удалённый
 * аккаунт).
 */
export function resolveWorkAssignee(
  requested: string | null | undefined,
  createdById: string | null,
): string | null {
  return requested || createdById || null;
}
