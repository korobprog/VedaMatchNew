/**
 * Дозревание уведомлений о работе с карточкой.
 *
 * Переносы по доске — единственное действие в «Работе», которое человек
 * отменяет через минуту: положил в «Тестирование», вспомнил, что не дописал,
 * вернул назад. Пуш, ушедший по клику, к этому моменту уже лежит у троих в
 * шторке и врёт. Поэтому движение не уведомляет сразу: запись ложится в
 * очередь, а через окно воркер смотрит, где карточка оказалась на самом деле.
 *
 * Отсюда же следует, что в очереди хранится только колонка, ОТКУДА уехали:
 * «куда» на момент отправки читается из задачи, а не из записи. Иначе серия
 * переносов родила бы серию уведомлений с промежуточными колонками.
 *
 * Через ту же очередь с VED-298 идут и комментарии. Причина — жалоба заказчика
 * на «дубликаты»: настоящих дублей в базе почти нет, а вот одно действие
 * человека рождало два уведомления — «новый комментарий» сразу и «переехала в
 * такую-то колонку» через окно. Комментировать карточку и тут же переносить её
 * — обычный рабочий жест, и получателю прилетало дважды об одном. Внутри окна
 * ещё ничего не отправлено, поэтому склейка тут бесплатна: решение принимается
 * один раз на отправке, по всему, что накопилось.
 */

/**
 * Сколько ждём перед отправкой; оно же — окно склейки.
 *
 * Три минуты — время «ой, не туда», и ровно тот же отрезок, внутри которого
 * комментарий и перенос считаются одним действием. Совпадение не случайное:
 * склеить можно только то, что ещё не отправлено, а отправляется всё на
 * границе этого окна. Окно шире потребовало бы править уже лежащее у человека
 * в ленте, окно уже — оставило бы внутри задержки два уведомления вместо
 * одного, то есть не вылечило бы жалобу.
 */
export const WORK_NOTICE_DELAY_MS = 3 * 60_000;

/**
 * Через сколько взятая в работу запись считается брошенной и возвращается в
 * очередь. Воркер мог умереть между claim и отправкой — см. восстановление
 * зависших задач у мотивации.
 */
export const WORK_NOTICE_CLAIM_TIMEOUT_MS = 5 * 60_000;

export type WorkNoticeColumn = {
  id: string;
  name: string;
  isDone: boolean;
};

/** Что накопилось по задаче за окно от одного человека для одного получателя. */
export type WorkNoticeWindow = {
  /**
   * Колонка на момент первого движения в окне; `null` — движения не было
   * вовсе (комментарий без переноса) либо колонку снесли вместе с доской и
   * сказать «откуда» уже нечего.
   */
  from: WorkNoticeColumn | null;
  /** Где карточка лежит на момент отправки. */
  to: WorkNoticeColumn;
  /** Текст последнего комментария в окне; `null` — комментария не было. */
  commentExcerpt: string | null;
  /** Сколько комментариев легло в окно: «ещё 2» собирает подписчик. */
  commentCount: number;
};

export type WorkNoticeOutcome =
  /** Новости нет: карточка вернулась туда, откуда уехала, и слова не сказано. */
  | { kind: 'skip' }
  /** Сделанное отправили на доработку — новость для того, кто делал. */
  | {
      kind: 'returned';
      columnName: string;
      commentExcerpt: string | null;
      commentCount: number;
    }
  /** Обычный переезд между колонками. */
  | {
      kind: 'status';
      fromColumnName: string;
      toColumnName: string;
      commentExcerpt: string | null;
      commentCount: number;
    }
  /** Только разговор: карточка осталась на месте, но человек что-то сказал. */
  | { kind: 'commented'; commentExcerpt: string; commentCount: number };

/**
 * Что сообщать по итогам окна.
 *
 * Возврат из «готово» отделён от прочих переездов намеренно: у него другой
 * адресат по смыслу («твою работу вернули») и другие слова, и он был отдельным
 * событием портала до появления этой очереди.
 *
 * Смена колонки побеждает комментарий, а не наоборот: «задача переехала, ваша
 * очередь проверять» несёт больше смысла, чем «есть новый комментарий», — так
 * и просил заказчик. Сам текст комментария при этом не теряется, он едет
 * вместе с переездом, и формулировку из двух частей собирает подписчик.
 *
 * Комментарий без переноса уведомление шлёт по-прежнему: через комментарии
 * карточек идёт вся переписка с заказчиком — вопросы, уточнения, отчёты. Выключи
 * их, и вопрос к человеку до него не дойдёт. Просили убрать дубли, а не оглохнуть.
 */
export function resolveWorkNotice(window: WorkNoticeWindow): WorkNoticeOutcome {
  const excerpt = window.commentExcerpt?.trim() ? window.commentExcerpt : null;
  // Счётчик страхуем от рассинхрона с текстом: запись могла прийти из старой
  // строки очереди, где счётчика ещё не было.
  const commentCount = excerpt ? Math.max(1, window.commentCount) : 0;
  const moved = window.from !== null && window.from.id !== window.to.id;

  if (!moved) {
    return excerpt
      ? { kind: 'commented', commentExcerpt: excerpt, commentCount }
      : { kind: 'skip' };
  }

  const from = window.from as WorkNoticeColumn;
  if (from.isDone && !window.to.isDone) {
    return {
      kind: 'returned',
      columnName: window.to.name,
      commentExcerpt: excerpt,
      commentCount,
    };
  }
  return {
    kind: 'status',
    fromColumnName: from.name,
    toColumnName: window.to.name,
    commentExcerpt: excerpt,
    commentCount,
  };
}

/**
 * Момент отправки для записи, попавшей в очередь.
 *
 * Существующей записи срок НЕ продлевается: иначе человек, весь день таскающий
 * одну карточку, не получит уведомление никогда. Окно считается от первого
 * движения — задержка ограничена сверху, сколько бы переносов и комментариев
 * ни случилось.
 */
export function resolveNotifyAt(
  existingNotifyAt: Date | null,
  now: Date,
): Date {
  return existingNotifyAt ?? new Date(now.getTime() + WORK_NOTICE_DELAY_MS);
}
