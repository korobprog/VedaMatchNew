import type { TaskStatusMark } from '@vedamatch/shared';

/**
 * Название колонки доски — в код состояния задачи (VED-311, VED-320).
 *
 * Живёт в «Работе», а не в «Уведомлениях», хотя раньше было наоборот. Причина
 * — жалоба VED-320: в ленте у карточки стояло «Тестирование», а в планировщике
 * та же карточка показывала «На доработку». Разбор названия был у подписчика, и
 * два клиента отвечали на один вопрос каждый по-своему. Колонки — наши, знать,
 * какая из них значит «тестирование», может только «Работа», поэтому код
 * состояния теперь считаем мы: и для ярлыка на карточке, и в событие для
 * ленты. Подписчик получает готовый код и собирает по нему слово и цвет —
 * контракт («издатель сообщает факт, формулировку собирает подписчик») от этого
 * не страдает: код состояния — это факт, а не формулировка.
 *
 * Почему разбором названия, а не признаком колонки: своего типа у колонки нет,
 * есть только имя (`WorkColumn.name`) и флаг `isDone`. Флага мало — он не
 * отличает «Тестирование» от «На доработку», а именно их и просили различать.
 *
 * Незнакомое название — `null`, и ярлыка нет. Это норма, а не потеря: у своей
 * доски колонки называют по-своему, и подписать чужое «Бэклог» одним из
 * четырёх наших слов было бы хуже, чем не подписать вовсе.
 */

/** Нормализация названия колонки: регистр, ё и лишние пробелы не в счёт. */
function normalize(columnName: string): string {
  return columnName
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[«»"'`]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Названия колонок, которые считаем тем или иным состоянием.
 *
 * Синонимы — ровно те, что встречаются на досках портала; расширять список
 * догадками не нужно: незнакомое название честнее оставить без ярлыка.
 */
const MARK_BY_COLUMN: ReadonlyArray<readonly [TaskStatusMark, string[]]> = [
  // «Работа» без предлога — не статус, а раздел: на доске портала так
  // называется колонка задач сервиса «Работа» (VED-430). Пока слово стояло
  // здесь, карточки раздела «РАБОТА» носили ярлык «В работе», а раздел
  // считался статусом и не отделялся от них.
  ['in_progress', ['в работе', 'в работу', 'в процессе', 'делается']],
  [
    // «Тестерование» через «е» — не опечатка в списке, а название колонки на
    // доске портала, как его написал человек (сверено с доской, VED-312).
    // Без этого синонима самая частая колонка тестирования приходила сюда
    // незнакомой и карточка оставалась вовсе без ярлыка.
    'testing',
    [
      'тестирование',
      'тестерование',
      'на тестировании',
      'на тестеровании',
      'тест',
      'на проверке',
      'проверка',
    ],
  ],
  ['done', ['выполнено', 'готово', 'сделано', 'завершено', 'закрыто']],
  [
    'rework',
    ['на доработку', 'доработка', 'на доработке', 'вернули', 'возврат'],
  ],
];

/** Состояние по названию колонки; `null` — название не из известной четвёрки. */
export function resolveTaskStatusMark(
  columnName: string | null | undefined,
): TaskStatusMark | null {
  if (!columnName) return null;
  const name = normalize(columnName);
  if (!name) return null;
  for (const [mark, names] of MARK_BY_COLUMN) {
    if (names.includes(name)) return mark;
  }
  return null;
}

/** Колонка так, как её видит разбор состояния: имя и флаг «завершающая». */
export interface WorkColumnMeaning {
  name: string;
  isDone: boolean;
}

/**
 * Колонка сделанной работы — «Выполнено», «Готово» — по флагу И по имени
 * (VED-406).
 *
 * Одного флага мало: на доске портала им отмечены и тематические колонки —
 * «РАЗНОЕ.», «МУЗЫКА», «ОБРАЗОВАНИЕ» (прод, 24.09). Новые карточки заказчик
 * заводит прямо в них, и ИИ-агент, взявший такую карточку в «Тестерование»,
 * порождал «Задачу вернули», хотя ничего не возвращал: с точки зрения флага
 * карточка выехала из «готового». Возврат — это выезд из колонки, которая и
 * называется сделанной.
 */
export function isFinishedColumn(column: WorkColumnMeaning): boolean {
  return column.isDone && resolveTaskStatusMark(column.name) === 'done';
}

/**
 * Закрывает ли въезд в колонку задачу для того, кто её туда положил
 * (VED-406): флаг «завершающая» или имя сделанного. Шире, чем
 * `isFinishedColumn`, намеренно: здесь цена ошибки — погасить двигавшему его
 * же уведомления о задаче, которую он только что сам убрал с глаз, а цена
 * пропуска — жалоба «почему мне висят уведомления со статусом Выполнено».
 */
export function closesTask(column: WorkColumnMeaning): boolean {
  return column.isDone || resolveTaskStatusMark(column.name) === 'done';
}

/**
 * Колонка статуса или колонка раздела (VED-430).
 *
 * Заказчик: «нужно отделить разделы задач и разделы их статусов». Раздел —
 * о чём задача («РАБОТА», «МУЗЫКА»), статус — в каком она состоянии
 * («Тестерование», «Выполнено»). Своего признака у колонки нет, поэтому
 * граница — тот же разбор названия, что даёт ярлык: колонка, чьё имя
 * читается одним из четырёх статусов, — колонка статуса, остальные — разделы.
 * Незнакомое имя («ПАУЗА», «Бэклог») — раздел: ошибиться в эту сторону
 * безопаснее, раздел ничего не закрывает и уведомлений не рождает.
 */
export function isStatusColumn(columnName: string | null | undefined): boolean {
  return resolveTaskStatusMark(columnName) !== null;
}
