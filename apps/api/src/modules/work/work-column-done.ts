/**
 * Признак «завершающая» у колонки — не украшение, а смысл: задача, попавшая
 * в такую колонку, закрывается, а вынутая из неё открывается обратно (см.
 * moveTask). Признак можно переключить и у колонки, в которой уже лежат
 * карточки, — например, когда своё «Выполнено» завели вручную, а закрывать
 * задачи оно не умело.
 *
 * Тогда карточки внутри должны догнать колонку: иначе доска говорит «здесь
 * выполненное», а отчёты и «Мой день» считают эти задачи открытыми.
 */

/** Что сделать с карточками колонки. `null` — ничего, признак не менялся. */
export type ColumnDoneChange = { completedAt: Date | null } | null;

export function columnDoneChange(
  current: boolean,
  requested: boolean | undefined,
  now: Date,
): ColumnDoneChange {
  if (requested === undefined || requested === current) return null;
  // Включили — закрываем незакрытые; выключили — открываем все. Уже
  // проставленную дату не переписываем: карточка закрыта тогда, когда её
  // закрыли, а не когда колонку переименовали в «Готово».
  return { completedAt: requested ? now : null };
}
