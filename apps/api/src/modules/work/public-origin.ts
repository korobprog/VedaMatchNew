/**
 * Публичный адрес портала для ссылок, которые уходят человеку.
 *
 * Приглашение в рабочую среду собиралось из переменной `WEB_URL`, которой нет
 * ни в compose, ни в панели: её не читает больше никто. На проде ссылка
 * поэтому всегда получалась `http://localhost:3000/work/join/<токен>` — и
 * позвать по ней было невозможно.
 *
 * Правильное имя у портала одно — `WEB_ORIGIN`: его читают вход, награды и
 * CORS. Значение при этом бывает списком через запятую, потому что доменов у
 * портала несколько (`main.ts` разбирает его именно так). В ссылку годится
 * только первый: остальные — зеркала и поддомены.
 */

/**
 * Первый адрес из настройки или `null`, если настройки нет. Хвостовые слэши
 * убираются: иначе ссылка выходит с двойным — `https://сайт//work/join/…`.
 */
export function publicOrigin(raw: string | null | undefined): string | null {
  if (typeof raw !== 'string') return null;
  const first = raw
    .split(',')
    .map((origin) => origin.trim())
    .filter(Boolean)[0];
  if (!first) return null;
  return first.replace(/\/+$/, '');
}
