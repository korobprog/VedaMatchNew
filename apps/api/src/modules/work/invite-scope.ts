/**
 * Кого показывать в списке «кого позвать» в рабочую среду.
 *
 * По умолчанию — только знакомых из портального графа: «Работа» не место, где
 * ищут незнакомых, и обычный владелец среды не должен перебирать портал.
 *
 * У портального администратора задача другая. Он собирает команду и зовёт
 * людей, которые ему лично не открывались, — а через ссылку это выходит
 * длиннее и ненадёжнее. Новых сведений он при этом не получает: весь список
 * участников ему и так виден в админке.
 *
 * Портал открывается только по запросу и только осмысленному: пустой ввод или
 * одна буква вернули бы почти весь список людей, а это выдача, а не поиск.
 */

/** Минимум букв, при котором поиск по порталу перестаёт быть перечислением. */
export const PORTAL_SEARCH_MIN = 2;

export type InviteScope = 'known' | 'portal';

export function inviteScope(
  portalAdmin: boolean,
  search: string | null | undefined,
): InviteScope {
  if (!portalAdmin) return 'known';
  return (search?.trim().length ?? 0) >= PORTAL_SEARCH_MIN ? 'portal' : 'known';
}
