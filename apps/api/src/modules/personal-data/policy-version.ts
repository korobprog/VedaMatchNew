/**
 * Версия текста политики конфиденциальности, действующая прямо сейчас.
 *
 * **Поднимать при каждой правке `/legal/privacy`.** Без версии согласие
 * недоказуемо: запись «человек согласился» без указания, с чем именно, не
 * говорит ни о чём — текст с тех пор мог смениться десять раз.
 *
 * Формат — дата правки. Она читается человеком и сама собой упорядочивается.
 */
export const POLICY_VERSION = '2026-09-05';

/**
 * Виды согласий. Значения совпадают с энумом `ConsentKind` московской схемы:
 * дублировать энум в две схемы значит поддерживать их синхронно.
 *
 * `cross_border` заведён, но **при регистрации не записывается**: политика
 * пока не сообщает ни места хранения, ни того, что копия уезжает за рубеж.
 * Записать согласие на то, о чём человеку не сказали, хуже, чем не записать
 * ничего. Снимается это правкой текста политики, а не кода — см. блокирующие
 * пункты в плане российского контура.
 */
export const CONSENT_KINDS = ['processing', 'cross_border'] as const;

export type ConsentKind = (typeof CONSENT_KINDS)[number];

export type ConsentGrant = {
  kind: ConsentKind;
  policyVersion: string;
  grantedIp?: string | null;
};

/**
 * Согласия, которые человек фактически даёт, проходя экран входа.
 *
 * Экран говорит «Продолжая, вы принимаете условия использования и политику
 * конфиденциальности» — это согласие на обработку. Ничего сверх сказанного
 * сюда попадать не должно.
 */
export function consentsAtRegistration(grantedIp?: string | null): ConsentGrant[] {
  return [{ kind: 'processing', policyVersion: POLICY_VERSION, grantedIp }];
}
