/**
 * Что из каталога — не Медиатека, а аудиокниги (VED-237, VED-297).
 *
 * Просили одно: «отображение всех аудиокниг должно находиться внутри этой
 * кнопки». Значит, запись, которая относится к аудиокнигам, в общем
 * каталоге не показывается ни в витрине, ни в поиске, ни в счётчиках. К
 * аудиокнигам запись относится по одному из двух признаков:
 *
 * 1. Она глава книги (`MusicAudiobookChapter`) — главный признак с VED-297,
 *    когда книга стала самостоятельной единицей.
 * 2. Её исполнитель отмечен чтецом (`MusicArtist.isAudiobook`, схема PR
 *    #417). Отметка осталась, чтобы новая запись чтеца, ещё не разложенная
 *    по книгам, не выскочила посреди киртанов — редакция видит такие записи
 *    в админке списком «не в книге».
 *
 * Отдельным модулем и под тестом, потому что тут ровно одна ошибка стоит
 * дорого и не видна глазами: запись **без исполнителя**. В Prisma условие
 * по вложенной связи (`artist: { isAudiobook: false }`) не совпадает, когда
 * связи нет вовсе, — и полторы сотни записей прода, у которых исполнитель
 * не проставлен, молча исчезли бы из каталога. Поэтому «не чтец» — это
 * «исполнитель не отмечен ИЛИ исполнителя нет».
 */

/** Условие для `where` Prisma: записи обычного каталога. */
export interface MusicCatalogOnlyCondition {
  AND: [
    { OR: [{ artistId: null }, { artist: { isAudiobook: false } }] },
    { audiobookChapter: { is: null } },
  ];
}

/**
 * Условие «запись из Медиатеки, а не из аудиокниг» — для элемента массива
 * `AND` в любой выдаче каталога.
 */
export function catalogOnlyCondition(): MusicCatalogOnlyCondition {
  return {
    AND: [
      { OR: [{ artistId: null }, { artist: { isAudiobook: false } }] },
      { audiobookChapter: { is: null } },
    ],
  };
}

/**
 * То же для выборки исполнителей витрины: карточки чтецов в Медиатеке не
 * нужны. Здесь исполнитель есть всегда, поэтому обходимся плоским полем.
 */
export function catalogArtistCondition(): { isAudiobook: false } {
  return { isAudiobook: false };
}
