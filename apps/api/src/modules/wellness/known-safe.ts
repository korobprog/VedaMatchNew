const LETTER = /[\p{L}\p{N}]/u;

/** Целое слово — та же проверка, что в `ingredient-match.ts`. */
function containsWord(haystack: string, needle: string): boolean {
  if (!needle) return false;
  let from = 0;
  for (;;) {
    const at = haystack.indexOf(needle, from);
    if (at < 0) return false;
    const before = at === 0 ? '' : haystack[at - 1];
    const afterAt = at + needle.length;
    const after = afterAt >= haystack.length ? '' : haystack[afterAt];
    if (!LETTER.test(before || ' ') && !LETTER.test(after || ' ')) return true;
    from = at + 1;
  }
}

/** Длинные вперёд: «подсолнечное масло» точнее голого «масло». */
const PREPARED = [...KNOWN_SAFE].sort((a, b) => b.length - a.length);

export function isKnownSafe(normalizedText: string): boolean {
  return PREPARED.some((safe) => containsWord(normalizedText, safe));
}

/**
 * Убирает из списка непонятого то, что на самом деле понятно и безвредно.
 * Работает по токенам, а не по строкам `unrecognized`: там лежит `raw` —
 * кусок этикетки как напечатан, а сравнивать надо приведённый `text`.
 */
export function dropKnownSafe(
  tokens: readonly WellnessCompositionToken[],
  unrecognized: readonly string[],
): string[] {
  const safeRaw = new Set(
    tokens.filter((token) => isKnownSafe(token.text)).map((token) => token.raw),
  );
  return unrecognized.filter((raw) => !safeRaw.has(raw));
}

