/**
 * Слово-заголовок состава на упаковке (VED-335, второй заход).
 *
 * Зачем проверка вообще. Снимок этикетки — единственный путь, которым в базу
 * попадает состав «со слов участника». Без проверки туда уходит что угодно:
 * снятый наугад бок пачки, пищевая ценность, штрихкод крупным планом, кусок
 * рекламного текста. Модель на таком снимке послушно вернёт хоть что-нибудь —
 * и это «что-нибудь» потом ответит вердиктом другому человеку у полки.
 *
 * Поэтому правило простое и проверяемое: на снимке должно быть напечатано
 * слово-заголовок состава. Нет слова — снимок не принимаем и говорим, почему.
 *
 * ПОЧЕМУ ИМЕННО СПИСОК СЛОВ, А НЕ «ПОХОЖЕ НА СОСТАВ». Судить «похоже» нечем:
 * перечисление через запятую — это и состав, и пищевая ценность, и список
 * наград на коробке. Слово-заголовок печатают по закону (ТР ТС 022/2011
 * требует называть ингредиенты списком с заголовком), и его наличие —
 * единственный признак, который можно проверить, не гадая.
 *
 * ЧТО ВХОДИТ В СПИСОК.
 * - «состав» во всех падежах — основная форма на российской упаковке;
 * - «ингредиенты» и «ingredients» — импорт и двуязычные этикетки;
 * - «склад» — украинская упаковка, её на полках СНГ много, и отказывать
 *   человеку с такой пачкой было бы обидной мелочью. Русское значение слова
 *   («склад» как помещение) на этикетке продукта не встречается, а проверяем
 *   мы не произвольный текст, а то, что модель уже вернула как состав;
 * - «састаў» — белорусская упаковка, по той же причине.
 *
 * Список — данные, пополняется строкой.
 */

/** Основы слов, по которым узнаём заголовок. Падежи добираются окончанием. */
const COMPOSITION_STEMS = [
  'состав',
  'ингредиент',
  'ingredient',
  'склад',
  'састаў',
  'саста',
];

/** Приводим к сравнимому виду: строчные, без «ё», без лишних пробелов. */
function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();
}

const LETTER = /\p{L}/u;

/**
 * Слово начинается с основы. Проверяем именно начало слова, а не вхождение
 * подстроки: иначе «состав» находится внутри «несоставной», а «склад» —
 * внутри «складской».
 */
function startsWordWith(text: string, stem: string): boolean {
  let from = 0;
  for (;;) {
    const at = text.indexOf(stem, from);
    if (at < 0) return false;
    const before = at === 0 ? '' : text[at - 1];
    if (!LETTER.test(before || ' ')) return true;
    from = at + 1;
  }
}

export function hasCompositionWord(text: string): boolean {
  if (!text) return false;
  const normalized = normalize(text);
  return COMPOSITION_STEMS.some((stem) => startsWordWith(normalized, stem));
}

/**
 * Убирает заголовок из начала строки — в базу кладётся сам состав, без
 * «Состав:». Только в начале: слово «состав» посреди строки (бывает в
 * оговорках вроде «состав может меняться») трогать нельзя.
 */
export function stripCompositionWord(text: string): string {
  // Кавычки снимаются ПЕРВЫМИ: модель любит обрамлять ответ целиком, и
  // «Состав: вода» с кавычкой перед словом иначе не узнаётся как заголовок.
  return text
    .replace(/^["'«»]+|["'«»]+$/g, '')
    .trim()
    .replace(
      /^(состав(?:\s+продукта)?|ингредиенты|ingredients|склад|састаў)\s*[:.\-–—]?\s*/i,
      '',
    )
    .replace(/^["'«»]+|["'«»]+$/g, '')
    .trim();
}

/**
 * Что сказать человеку, когда слова на снимке не нашлось. Формулировка живёт
 * рядом с правилом: объяснение «почему не приняли» — часть самого правила, а
 * не украшение экрана.
 */
export const NO_COMPOSITION_WORD_MESSAGE =
  'Не вижу на снимке слова «Состав» — сфотографируйте ту часть упаковки, где написан состав.';
