/**
 * Отказ провайдера по содержанию кадра.
 *
 * Отличается от прочих сбоев тем же, чем «кончились деньги»: повтор с тем же
 * кадром даст ровно тот же ответ, и каждая попытка платная. Поэтому такой код
 * нельзя показывать автору как «не получилось, попробуйте ещё раз» и нельзя
 * повторять автоматически.
 *
 * Провайдер отвечает 422 и кладёт в `detail[0].type` строку
 * `content_policy_violation`. На живой проверке так была отвергнута
 * иллюстрация с Кришной и Арджуной — классическая индийская живопись
 * регулярно ловится подобными фильтрами.
 */

export const CONTENT_POLICY_CODE = 'content_policy_violation';

/** Отвергнут ли кадр проверкой содержания у провайдера. */
export function isContentPolicyCode(code: string | null | undefined): boolean {
  return Boolean(code?.toLowerCase().includes(CONTENT_POLICY_CODE));
}

/**
 * Что сказать автору. Важно не обещать успех при повторе и подсказать
 * единственное действие, которое может помочь, — сменить картинку.
 */
export function videoRejectionMessage(
  code: string | null | undefined,
): string | null {
  if (!isContentPolicyCode(code)) return null;
  return 'Провайдер видео отклонил этот кадр: его проверка содержания сочла картинку неподходящей. Повтор с тем же кадром результата не даст — попробуйте пересобрать рилс с другой иллюстрацией.';
}
