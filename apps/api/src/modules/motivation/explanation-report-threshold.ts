/**
 * Сколько жалоб прячут пояснение под цитатой.
 *
 * Копия notices/report-threshold.ts: контракт сервисного модуля запрещает
 * импортировать хелперы чужого модуля.
 *
 * Три — тот же компромисс, что и в Объявлениях: одной жалобы мало (ею легко
 * свести счёты с автором трактовки), а десяти на небольшой ленте никогда не
 * наберётся. Жалоба одна на человека, поэтому три — это три разных читателя,
 * а не три нажатия одного.
 */
export const EXPLANATION_HIDE_THRESHOLD = 3;

/**
 * Пересекла ли жалоба порог именно сейчас. Сравниваем ровно с порогом, а не
 * `>=`: иначе пояснение пряталось бы снова после того, как админ его вернул.
 */
export function crossesExplanationThreshold(reportsAfter: number): boolean {
  return reportsAfter === EXPLANATION_HIDE_THRESHOLD;
}
