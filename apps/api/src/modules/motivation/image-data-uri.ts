/**
 * Кадр как data-URI для fal.
 *
 * Провайдер принимает Base64 data-URI везде, где ждёт ссылку на файл, и
 * декодирует сам. Нам это нужно не ради удобства: заливка в хранилище fal
 * (`v3b.fal.media`, 87.249.129.66) с боевого сервера не работает — соединение
 * встаёт на объёме больше ~20 КБ и обрывается по таймауту, а обратное
 * скачивание нашего S3 провайдер не осиливает вовсе. При этом API-сеть fal
 * (`queue.fal.run`, 35.224.27.103) здорова: 300 КБ уходят за 1,15 с.
 *
 * Отдавая картинку прямо в теле задачи, мы целиком обходим сломанный хост.
 */
export function buildImageDataUri(
  bytes: Buffer,
  contentType = 'image/jpeg',
): string {
  return `data:${contentType};base64,${bytes.toString('base64')}`;
}

/**
 * Во что превратится вес кадра после Base64.
 *
 * Кодирование раздувает данные на треть, и считать это стоит заранее: тело
 * задачи уходит одним запросом, и его размер — единственное, что отделяет нас
 * от повторения истории с таймаутом.
 */
export function encodedSizeBytes(rawBytes: number): number {
  return Math.ceil(rawBytes / 3) * 4;
}
