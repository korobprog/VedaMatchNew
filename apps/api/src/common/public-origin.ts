/**
 * Публичный адрес портала для ссылок и редиректов, которые видит человек.
 *
 * `WEB_ORIGIN` называется как один адрес, но хранит список через запятую:
 * `main.ts` разбирает его для CORS, потому что доменов у портала несколько —
 * `.ru`, `.com`, зеркала и поддомены. В ссылку годится только первый,
 * остальные обязаны остаться в CORS и никуда больше не попадать.
 *
 * Хелпер живёт в `common`, а не внутри модуля: значение читают вход, награды
 * и приглашения — три разных сервиса, и разъехавшаяся трактовка уже ломала
 * прод. 12 сентября 2026 в переменную добавили домены `.com`, после чего
 * возврат из Google уводил браузер на `https://vedamatch.ru,https://vedamatch.com,...`
 * — адрес с запятыми, который не открывается.
 */

/**
 * Первый адрес из настройки или `null`, если настройки нет. Хвостовые слэши
 * убираются: иначе ссылка выходит с двойным — `https://сайт//work/join/…`.
 */
export function publicOrigin(raw: string | null | undefined): string | null {
  if (typeof raw !== 'string') return null;
  const first = raw
    .split(',')
    .map((origin) => origin.trim())
    .filter(Boolean)[0];
  if (!first) return null;
  return first.replace(/\/+$/, '');
}
