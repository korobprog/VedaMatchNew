-- Публичная витрина Знакомств: страница сервиса открыта гостям и поисковикам,
-- поэтому попадание на неё требует отдельного согласия. Настройка privacy.photo
-- со значением "everyone" его не заменяет: она открывает фото участникам
-- портала, а не всему интернету, и никто не соглашался быть лицом в рекламе.
--
-- Значение по умолчанию — false: молчание согласием не считается, витрина
-- пустует, пока люди не отметят её сами.
ALTER TABLE "UnionProfile"
ADD COLUMN "showcaseOptIn" BOOLEAN NOT NULL DEFAULT false,
ADD COLUMN "showcaseBlockedAt" TIMESTAMP(3);

-- Витрина выбирает согласившихся из всех анкет портала — без индекса это
-- полный проход по таблице на каждый визит гостя.
CREATE INDEX "UnionProfile_showcaseOptIn_idx" ON "UnionProfile"("showcaseOptIn");
