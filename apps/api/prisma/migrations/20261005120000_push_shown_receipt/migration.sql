-- VED-327: подтверждение показа уведомления от service worker.
--
-- После VED-314 портал знает, что служба доставки браузера ПРИНЯЛА пуш
-- (`lastSuccessAt`), но не что человек его увидел: браузер, который не
-- открывали месяц, принимает пуш так же, как живой. Теперь service worker
-- после `showNotification` сам сообщает «показано» (`POST
-- /notifications/shown`), и отметка ложится сюда.
--
-- Хранится только факт показа и id последнего подтверждённого пуша (для
-- идемпотентности). Открыл ли человек уведомление и когда — не хранится.
--
-- Колонки аддитивные, NULL у существующих строк означает «подтверждений ещё
-- не было», бэкофилл не нужен. Написано руками — по той же причине, что
-- `20260922120000_push_delivery_health`.

-- AlterTable
ALTER TABLE "PushSubscription" ADD COLUMN "lastShownAt" TIMESTAMP(3);
ALTER TABLE "PushSubscription" ADD COLUMN "lastShownPushId" TEXT;
