-- VED-361: у звонков свой выключатель, независимый от сообщений.
--
-- Значение по умолчанию `true` и для новых строк, и для существующих: человек,
-- который ничего не настраивал, звонки получал и раньше — под категорией
-- «Сообщения». Выключить их он теперь может отдельно, а вот включить то, что
-- он не выключал, миграция ему не должна.
ALTER TABLE "NotificationPreference"
  ADD COLUMN "calls" BOOLEAN NOT NULL DEFAULT true;
