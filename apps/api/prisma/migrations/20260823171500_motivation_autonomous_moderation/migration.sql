-- Рилс участника публикуется по вердикту ИИ-модератора, без одобрения
-- администратора: текст уже разбирает модель, второй проверяющий на том же
-- тексте — лишний этап. Админ остаётся оператором: он видит очередь из того,
-- в чём модель не уверена, и может в любой момент вернуть режим в настройках.

-- AlterTable
ALTER TABLE "MotivationSettings"
ALTER COLUMN "aiModerationMode" SET DEFAULT 'autonomous';

-- Уже заведённую настройку default не догоняет. «Подсказывает» — прежнее
-- умолчание, его и переводим. Явное «выключено» не трогаем: это осознанный
-- выбор редакции, а не унаследованное значение.
UPDATE "MotivationSettings"
SET "aiModerationMode" = 'autonomous'
WHERE "aiModerationMode" = 'assist';
