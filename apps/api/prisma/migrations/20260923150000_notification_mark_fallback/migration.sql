-- Значок «Комментарий» у уведомления о комментарии к задаче (VED-298): когда
-- у задачи нет состояния (карточка лежит не в «В работе», «Тестерование»,
-- «Выполнено» или «На доработку»), лента показывает его вместо пустоты.
-- Колонка отдельная от "mark": переезд карточки переписывает "mark" у всех
-- уведомлений о задаче, и в одной колонке «это был комментарий» стёрлось бы.
ALTER TABLE "NotificationItem" ADD COLUMN "markFallback" TEXT;

-- Уже лежащие уведомления о комментарии получают значок сразу, иначе он
-- появился бы только у новых. Узнаём их по заголовку — других примет у строки
-- нет: «VED-1: новый комментарий» и «VED-1: 3 комментария» (несколько реплик
-- за окно дозревания, VED-298). Смена статуса, возврат и поручение сюда не
-- попадают: у них другие заголовки.
UPDATE "NotificationItem"
SET "markFallback" = 'comment'
WHERE "category" = 'work'
  AND "url" LIKE '/work/planner/%'
  AND (
    "title" ~ '^[A-Za-z0-9]+-[0-9]+: новый комментарий$'
    OR "title" ~ '^[A-Za-z0-9]+-[0-9]+: [0-9]+ комментари(й|я|ев)$'
  );
