-- Индекс для чистки удалённых сообщений (ChatRetentionService).
--
-- Воркер каждые пятнадцать минут отбирает сообщения с deletedAt раньше
-- границы хранения и сортирует по нему же. Без индекса это чтение всей
-- таблицы сообщений — самой большой в сервисе — четыре раза в час.
CREATE INDEX "ChatMessage_deletedAt_idx" ON "ChatMessage"("deletedAt");
