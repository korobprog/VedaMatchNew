// Логика выбора чанков для `<link rel="modulepreload">` — вынесена из
// `patch-web-preloads.mjs`, чтобы покрыть тестом без обращения к файловой
// системе (CLAUDE.md, раздел «Тесты»).

/**
 * Базовые имена маршрутов, чьи чанки нужны для первого экрана независимо от
 * того, гость пользователь или уже вошёл: оба layout'а маршрутизатора (веб —
 * `_layout.web.tsx`, `(tabs)/_layout.tsx`) и экран входа с его собеседником
 * `auth.tsx` (переход после внешнего OAuth). Metro называет чанк
 * `<базовое имя файла-маршрута>-<хеш>.js`.
 */
export const CRITICAL_ROUTE_BASENAMES = ['_layout', 'login', 'auth'];

/**
 * Из списка имён JS-чанков веб-экспорта выбирает те, что стоит догружать
 * `modulepreload` параллельно с основным бандлом (веха 6 «Скорость»,
 * gan-harness/spec.md): при включённых `asyncRoutes` маршрутизатор узнаёт про
 * эти файлы только в рантайме, динамическим `import()`, и без предзагрузки
 * запрашивает их только после того, как выполнится весь предыдущий JS — на
 * медленной сети это лишний оборот сети на каждый файл ради экрана, который
 * нужен в 100% случаев.
 *
 * Совпадение — по префиксу `<базовое_имя>-`: в дереве `src/app/**` нет двух
 * файлов-маршрутов с общим префиксом имени (`login.tsx`/`auth.tsx`/оба
 * `_layout.tsx`) — при появлении такого файла в будущем (например,
 * `login-required.tsx`) его чанк попадёт в предзагрузку заодно, это не баг:
 * лишние несколько КБ дешевле лишнего оборота сети для нужного файла.
 */
export function selectPreloadChunks(fileNames) {
  return fileNames
    .filter((name) => name.endsWith('.js'))
    .filter((name) => CRITICAL_ROUTE_BASENAMES.some((base) => name.startsWith(`${base}-`)))
    .sort();
}

/**
 * Корневой layout маршрутизатора существует в двух файлах —
 * `_layout.native.tsx` и `_layout.web.tsx` (см. комментарий в первом: почему
 * не безымянный `_layout.tsx`). Metro всё равно выпускает чанк для ОБОИХ —
 * `require.context` матчит файл по имени независимо от специфичности для
 * платформы, специфичность выбирает только то, какой из них экспо-роутер
 * реально когда-нибудь потребует в рантайме (`getFileMeta` в
 * `expo-router/build/getRoutesCore.js`, `specificity < 0` → чанк ни разу не
 * запрашивается). Чанк `_layout.native.tsx` в веб-сборке не нужен вовсе —
 * греть его предзагрузкой значит просто отбирать полосу у нужных файлов
 * (та же причина, что у отказа от предзагрузки шрифтов в `public/index.html`).
 *
 * Различаем по содержимому, не по имени (имя — случайный хеш): только у
 * `_layout.native.tsx` есть шесть начертаний из `@expo-google-fonts/*`
 * (`useFonts`). Ищем строку пути пакета, а не имя идентификатора вроде
 * `SplashScreen` — минификатор переименовывает локальные привязки, но путь
 * пакета в вызове `require('@expo-google-fonts/...')` остаётся текстовой
 * строкой и не минифицируется.
 */
export function isDeadNativeLayoutChunk(content) {
  return content.includes('expo-google-fonts');
}
