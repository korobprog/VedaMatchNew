/**
 * Правда про доставку уведомлений на ЭТОТ телефон (VED-329).
 *
 * Тот же разговор, что портал уже завёл на сайте (VED-314,
 * `apps/web/src/lib/pwa/delivery-warning.ts`): человек жал «включить», видел
 * бодрую строку и оставался в уверенности, что всё работает, — а точек
 * доставки у него не было ни одной, и вечер уведомлений прошёл мимо. Жалоба
 * 21.09 повторилась в приложении, потому что здесь раздел молчал вовсе.
 *
 * Логика правила с сайта, копия — своя: по контракту сервисного модуля
 * приложение не тянет чужой файл, а держит свою копию рядом со своим кодом.
 * Отличие от веба одно и важное: там точка доставки — подписка браузера,
 * здесь — токен FCM, и приложение шлёт его при КАЖДОМ запуске
 * (`push-bridge.tsx`), а регистрация токена снимает серверную пометку
 * «мёртвая» (`saveDevice` → `seenByClient()`). Поэтому «сервер считает точку
 * мёртвой» в приложении почти всегда означает «токен до сервера не дошёл», и
 * текст зовёт повторить регистрацию, а не пугает.
 *
 * Модуль чистый: ни сети, ни Firebase, ни React. Тексты держим здесь же —
 * правило и формулировка это одно решение, и проверять их надо вместе.
 */

import type { NotificationDeliveryStatusDto } from '@vedamatch/shared';
import type { NotificationChannelsState } from './notification-channel';
import type { PushRegistration } from './push-registration';

/** Различимые исходы раздела. */
export type DeliverySectionKind =
  /** Ответа сервера ещё нет, ошибки тоже: первый заход. */
  | 'checking'
  /** Доставка работает. */
  | 'ok'
  /** Android запретил приложению показывать уведомления. */
  | 'no-permission'
  /** Разрешение есть, но выключены ОБЕ категории — и «Сообщения», и «Звонки». */
  | 'channels-off'
  /** Выключена только категория «Сообщения»: звонки при этом звонят. */
  | 'messages-channel-off'
  /** Выключена только категория «Звонки»: сообщения при этом приходят. */
  | 'calls-channel-off'
  /** Сборка без ключей Firebase: получать пуши нечем. */
  | 'no-token'
  /** Разрешение есть, а живой точки доставки у сервера нет. */
  | 'unreachable'
  /** Другие устройства уведомления получают, а этот телефон — нет. */
  | 'not-this-phone'
  /** Сервер не ответил: не знаем — не пугаем. */
  | 'unknown';

/** Что делает кнопка раздела. */
export type DeliverySectionAction =
  | 'none'
  /** Открыть системные настройки уведомлений приложения. */
  | 'settings'
  /** Открыть настройки самой категории «Сообщения». */
  | 'messages-channel-settings'
  /** Открыть настройки самой категории «Звонки». */
  | 'calls-channel-settings'
  /** Зарегистрировать телефон заново и перечитать состояние. */
  | 'retry'
  /** Просто перечитать состояние у сервера. */
  | 'recheck';

export interface DeliverySectionState {
  kind: DeliverySectionKind;
  title: string;
  /** Объяснение человеческим языком: что происходит и что с этим делать. */
  hint: string;
  action: DeliverySectionAction;
  /** Подпись кнопки; `null`, когда кнопки нет. */
  actionLabel: string | null;
  /** Тон плашки: спокойный, тревожный или нейтральный. */
  tone: 'ok' | 'warn' | 'muted';
}

export interface DeliverySectionInput {
  /** Чем кончилась регистрация токена в этом запуске. */
  registration: PushRegistration;
  /**
   * Важность категорий «Сообщения» и «Звонки» у системы. Разрешение
   * приложения её не покрывает: человек может оставить разрешение и выключить
   * категорию — тогда Android не покажет ничего (VED-329, раунд 001, дефект
   * 1). Категорий две (VED-361), и выключены они бывают порознь: раздел
   * обязан говорить, что именно замолчало, а что продолжает работать.
   */
  channels: NotificationChannelsState;
  /** Ответ `GET /notifications/delivery-status`; `null` — ещё не знаем. */
  status: NotificationDeliveryStatusDto | null;
  /** Последний запрос статуса не удался (сеть, 5xx). */
  statusFailed: boolean;
}

/**
 * Колокольчик и переписка работают и без пушей — это нужно говорить в каждом
 * плохом исходе, иначе человек решит, что сломано приложение целиком.
 */
const ALSO_IN_APP =
  'Сообщения и звонки внутри VedaMatch работают и без пушей — телефон просто не сообщит о них, пока приложение закрыто.';

export function describeDeviceDelivery(input: DeliverySectionInput): DeliverySectionState {
  const { registration, channels, status, statusFailed } = input;

  // Разрешение — первым делом и до всякого сервера: причина очевидна, а
  // действие ровно одно. Сервер в этот момент может показывать живые точки
  // (другой телефон, браузер), но человеку важно про телефон в его руке.
  if (registration === 'no-permission') {
    return {
      kind: 'no-permission',
      title: 'Уведомления запрещены в настройках телефона',
      hint: `Android не разрешил VedaMatch показывать уведомления, поэтому ни сообщения, ни звонки телефон не покажет. Откройте настройки уведомлений VedaMatch и включите их. ${ALSO_IN_APP}`,
      action: 'settings',
      actionLabel: 'Открыть настройки уведомлений',
      tone: 'warn',
    };
  }

  // Разрешение приложения выдано, а категорию выключили вручную. Найдено на
  // живом телефоне (раунд 001, снимок `ved329-06`): сервер при этом числит
  // телефон живой точкой и доставляет, а Android молча всё прячет — самый
  // обидный вид вранья, ради которого раздел и заведён.
  //
  // Категорий две, и молчать они могут порознь (VED-361). Сказать «уведомления
  // выключены», когда выключены только сообщения, — то же враньё наоборот:
  // человек решит, что и звонок до него не дойдёт, хотя дойдёт.
  const channelOff = describeChannelsOff(channels);
  if (channelOff) return channelOff;

  // Сборка без `google-services.json`: разрешение выдано, а ключей FCM нет —
  // `getToken()` падает, и посылать на сервер нечего. Кнопка «повторить» тут
  // бесполезна: другой сборкой файл не появится.
  if (registration === 'no-token') {
    return {
      kind: 'no-token',
      title: 'Эта сборка приложения не умеет получать уведомления',
      hint: `В ней нет ключей службы доставки Firebase, поэтому телефону некуда присылать пуши. Поставьте VedaMatch из RuStore или с сайта vedamatch.ru/app — в тех сборках уведомления есть. Ещё один путь: уведомления в Telegram, раздел ниже. ${ALSO_IN_APP}`,
      action: 'none',
      actionLabel: null,
      tone: 'warn',
    };
  }

  if (!status) {
    // Молчание сервера — не повод обещать неприятности: то же правило, что на
    // сайте. Говорим честно «не знаем» и даём перепроверить.
    if (statusFailed) {
      return {
        kind: 'unknown',
        title: 'Не удалось проверить доставку',
        hint: 'Сервер не ответил на запрос о состоянии уведомлений. Похоже, нет связи — проверьте её и попробуйте ещё раз.',
        action: 'recheck',
        actionLabel: 'Проверить снова',
        tone: 'muted',
      };
    }
    return {
      kind: 'checking',
      title: 'Проверяем доставку…',
      hint: 'Спрашиваем сервер, дойдут ли уведомления до этого телефона.',
      action: 'none',
      actionLabel: null,
      tone: 'muted',
    };
  }

  // `status.app` — это «сколько живых телефонов у АККАУНТА», а не «жив ли
  // этот» (сервер считает `groupBy` по `userId`, без привязки к токену
  // спрашивающего). Поэтому провалившаяся регистрация важнее любого счётчика:
  // иначе второй телефон человека (или строка, оставшаяся от переустановки)
  // оправдывал бы обещание, которое к телефону в руках отношения не имеет
  // (раунд 001, дефект 2).
  if (registration === 'failed') {
    const elsewhere = status.app > 0 || status.reachable;
    return {
      kind: elsewhere ? 'not-this-phone' : 'unreachable',
      title: elsewhere
        ? 'Этот телефон уведомления не получит'
        : 'Уведомления включены, но доставлять их некуда',
      hint: `${unreachableReason('failed')}${otherPoints(status)}Нажмите «Зарегистрировать заново» — телефон отправит ключ доставки ещё раз. ${ALSO_IN_APP}`,
      action: 'retry',
      actionLabel: 'Зарегистрировать заново',
      tone: 'warn',
    };
  }

  if (status.app > 0) {
    return {
      kind: 'ok',
      title: 'Уведомления доходят до телефона',
      hint:
        registration === 'registered'
          ? 'Этот телефон зарегистрирован точкой доставки: сообщения и звонки придут, даже когда VedaMatch закрыт.'
          : 'Сервер видит телефон с приложением VedaMatch и доставляет уведомления на него.',
      action: 'none',
      actionLabel: null,
      tone: 'ok',
    };
  }

  return {
    kind: 'unreachable',
    title: 'Уведомления включены, но доставлять их некуда',
    hint: `${unreachableReason(registration)}${otherPoints(status)}Нажмите «Зарегистрировать заново» — телефон отправит ключ доставки ещё раз. ${ALSO_IN_APP}`,
    action: 'retry',
    actionLabel: 'Зарегистрировать заново',
    tone: 'warn',
  };
}

/**
 * Выключенные категории. Три разных ответа вместо одного: выключены обе,
 * только сообщения, только звонки. Тон одинаково тревожный — молчит то, чего
 * человек ждал, — а вот что именно молчит и что при этом работает, сказано
 * прямо (VED-361, пункт «честные тексты»).
 *
 * `unknown` тревогой не считается: канала может ещё не быть (первый запуск
 * до регистрации), и обвинять в этом человека не за что.
 */
function describeChannelsOff(
  channels: NotificationChannelsState,
): DeliverySectionState | null {
  const messagesOff = channels.messages === 'off';
  const callsOff = channels.calls === 'off';

  if (messagesOff && callsOff) {
    return {
      kind: 'channels-off',
      title: 'Категории «Сообщения» и «Звонки» выключены',
      hint: `Само приложение уведомления показывать может, но обе его категории в настройках телефона выключили — а сервер шлёт именно в них, так что вы не увидите ни сообщений, ни звонков. Включите категории «Сообщения» и «Звонки» в настройках уведомлений VedaMatch. ${ALSO_IN_APP}`,
      // Экран уведомлений приложения показывает обе категории списком: туда
      // и ведём, чтобы не гонять человека по двум экранам подряд.
      action: 'settings',
      actionLabel: 'Открыть настройки уведомлений',
      tone: 'warn',
    };
  }

  if (messagesOff) {
    return {
      kind: 'messages-channel-off',
      title: 'Категория «Сообщения» выключена',
      hint: `Сообщения телефон показывать не будет: их категорию в настройках выключили. Звонки при этом продолжат звонить — у них своя категория, и она включена. Чтобы вернуть сообщения, включите категорию «Сообщения» в настройках уведомлений VedaMatch. ${ALSO_IN_APP}`,
      action: 'messages-channel-settings',
      actionLabel: 'Открыть категорию «Сообщения»',
      tone: 'warn',
    };
  }

  if (callsOff) {
    return {
      kind: 'calls-channel-off',
      title: 'Категория «Звонки» выключена',
      hint: `О входящем звонке телефон молчит: категорию «Звонки» в настройках выключили. Сообщения при этом приходят — у них своя категория, и она включена. Чтобы снова слышать вызовы, включите категорию «Звонки» в настройках уведомлений VedaMatch. ${ALSO_IN_APP}`,
      action: 'calls-channel-settings',
      actionLabel: 'Открыть категорию «Звонки»',
      tone: 'warn',
    };
  }

  return null;
}

function unreachableReason(registration: PushRegistration): string {
  switch (registration) {
    case 'failed':
      // Самый частый честный случай: токен получен, но POST не прошёл.
      return 'Телефон получил ключ доставки, но отправить его на сервер не вышло — похоже, в тот момент не было связи. ';
    case 'registered':
      // Ключ ушёл, а сервер его ещё не числит: либо состояние прочитано до
      // записи, либо запись не дожила. Регистрация снимает пометку «мёртвая»,
      // поэтому повтор здесь действительно лечит.
      return 'Телефон отправил ключ доставки, но сервер пока не числит его живой точкой. ';
    default:
      return 'Сервер не числит этот телефон точкой доставки: ключ доставки до него не дошёл. ';
  }
}

/** Куда уведомления всё-таки идут: иначе «некуда» звучит страшнее правды. */
function otherPoints(status: NotificationDeliveryStatusDto): string {
  const places: string[] = [];
  // `app` считает ВСЕ живые телефоны аккаунта. Сюда попадаем только когда этот
  // телефон точкой не стал, значит счётчик говорит о других устройствах.
  if (status.app > 0) places.push('на другие ваши устройства');
  if (status.web > 0) places.push('в браузер');
  if (status.telegram > 0) places.push('в Telegram');
  const elsewhere =
    places.length > 0
      ? `Уведомления приходят ${places.join(' и ')}, но не на этот телефон. `
      : '';
  const stale =
    status.stale > 0
      ? 'Прежние подписки браузера сервер пометил мёртвыми: месяц без единого принятого пуша. '
      : '';
  return elsewhere + stale;
}

/**
 * Как часто спрашивать сервер. Раздел открывают и закрывают по нескольку раз
 * за сеанс, и каждый заход в запрос превращать незачем: состояние доставки
 * меняется не чаще, чем человек успевает дойти до настроек и обратно.
 */
export const DELIVERY_FRESH_MS = 60_000;

/** Почему хотим обновиться. */
export type DeliveryRefreshReason =
  /** Экран открылся или вернулся в фокус. */
  | 'focus'
  /** Приложение вернулось на передний план само по себе. */
  | 'foreground'
  /** Человек нажал кнопку или вернулся из системных настроек. */
  | 'manual';

/**
 * Обновляться ли сейчас. Чистая часть правила «не дёргать сервер на каждый
 * заход»: по нажатию и по возвращению из настроек — всегда (иначе человек
 * включит уведомления и увидит прежнюю ругань), в остальных случаях — если
 * прошлый ответ успел устареть.
 */
export function shouldRefreshDelivery(params: {
  reason: DeliveryRefreshReason;
  /** Момент последнего УСПЕШНОГО ответа; `null` — ответа ещё не было. */
  checkedAt: number | null;
  now: number;
}): boolean {
  if (params.reason === 'manual') return true;
  if (params.checkedAt === null) return true;
  return params.now - params.checkedAt >= DELIVERY_FRESH_MS;
}
