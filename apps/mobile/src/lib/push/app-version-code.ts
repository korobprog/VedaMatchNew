/**
 * versionCode установленной сборки для регистрации токена на сервере.
 *
 * Сервер по нему решает, звать ли телефон со сборкой с сайта обновиться:
 * пуш «Доступна новая версия» уходит только тем, чья версия меньше вышедшей.
 * Номер берётся из конфига сборки (`app.config.ts` → `android.versionCode`,
 * в CI — база плюс номер запуска). Всё непохожее на номер — `undefined`:
 * поле не отправляется, и сервер считает версию неизвестной, а не нулевой.
 *
 * Своя копия разбора, а не импорт из самообновления: модуль регистрации
 * попадает и в магазинную сборку, где кода самообновления нет вовсе.
 */
export function installedVersionCode(raw: unknown): number | undefined {
  if (typeof raw !== 'number' || !Number.isInteger(raw) || raw <= 0) return undefined;
  return raw;
}
