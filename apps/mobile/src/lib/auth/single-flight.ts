/**
 * Одно выполнение на всех, кто пришёл, пока оно идёт.
 *
 * Нужен для обновления токенов: refresh-токен одноразовый, сервер ротирует
 * его и повторное предъявление считает кражей — отзывает все сессии человека.
 * Если поток чата и обычный запрос одновременно получили 401 после сна
 * телефона, второй refresh с тем же токеном выкидывал человека из аккаунта.
 */
export function singleFlight<T>(run: () => Promise<T>): () => Promise<T> {
  let inFlight: Promise<T> | null = null;
  return () => {
    inFlight ??= run().finally(() => {
      inFlight = null;
    });
    return inFlight;
  };
}
