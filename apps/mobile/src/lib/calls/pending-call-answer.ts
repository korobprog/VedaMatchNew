/**
 * «Отложенный ответ» на нативное событие `answer` (VED-221,
 * `gan-harness/feedback/feedback-001.md`, блокирующий п.2).
 *
 * Нажатие «Ответить» на уведомлении/блокировке при свёрнутом, но не
 * убитом, приложении (`CallActionReceiver.kt`) шлёт JS-событие `answer`
 * синхронно — раньше, чем поток событий (`chat-stream.tsx`) переоткроется
 * после возврата в активное состояние и `reconcile()`
 * (`call-provider.tsx`) успеет узнать сам звонок через
 * `GET /chat/calls/active`. Раньше обработчик `answer` требовал точного
 * совпадения `phase === 'incoming'` в момент события — почти всегда
 * промахивался и терял нажатие безвозвратно, человеку приходилось нажимать
 * «Ответить» второй раз уже внутри приложения.
 *
 * Модуль запоминает `callId`, для которого ответ уже решён, до тех пор,
 * пока звонок с этим `callId` не появится в состоянии — тогда его можно
 * принять самим, без участия человека. Чистая структура данных: сеть и
 * `accept()` — снаружи, в `call-provider.tsx`.
 */
export class PendingCallAnswer {
  private callId: string | null = null;

  /** Есть нативное «ответить» для `callId`, звонка в состоянии ещё нет —
   *  запомнить. Повторный вызов с тем же `callId` (например, оба пути,
   *  `getLaunchCall()` и JS-событие `answer`, сработали для одного и того
   *  же звонка) не создаёт второй отложенный ответ — очередь одна. */
  request(callId: string): void {
    this.callId = callId;
  }

  /** Звонок с этим `callId` появился в состоянии (`call.ringing` из потока
   *  или `restore` из `reconcile()`) — если он совпадает с запомненным,
   *  потребить (один раз: второй вызов с тем же `callId` уже вернёт
   *  `false`, отложенный ответ нельзя применить дважды) и сказать «да,
   *  прими его сейчас, без второго нажатия». */
  consume(callId: string): boolean {
    if (this.callId !== callId) return false;
    this.callId = null;
    return true;
  }

  /** Есть ли вообще отложенный ответ — решает, нужно ли сразу дёргать
   *  `GET /chat/calls/active`, не дожидаясь обычного ресинка потока
   *  (перехода `AppState` → `active`). */
  hasPending(): boolean {
    return this.callId !== null;
  }

  clear(): void {
    this.callId = null;
  }
}
