import type { AppStateStatus } from 'react-native';
import type { CallPhase } from './call-machine';

/**
 * Что делать с `call.ringing` из общего потока (VED-358).
 *
 * Живая поломка 22.09: человеку звонили, в браузере окно «Принять»
 * появилось, а в приложении — нет. Причина не в самом звонке: обработчик
 * потока в `call-provider.tsx` на телефоне с погашенным экраном поднимал
 * нативный экран вызова и на этом ЗАКАНЧИВАЛ обработку события — `dispatch`
 * до машины состояний не доходил вовсе. Полноэкранный intent сразу после
 * этого выводит приложение на передний план, и человек видит приложение,
 * которое про звонок не знает: ни баннера, ни кнопки «Принять». Вернуть
 * входящий мог только случайный пересинк потока с `GET /chat/calls/active`
 * — а его не бывает, пока поток не рвался (телефон просто лежал с
 * погашенным экраном, процесс жив, SSE открыт).
 *
 * Отсюда правило: машина состояний узнаёт о звонке ВСЕГДА. Нативный экран —
 * это способ ДОЗВОНИТЬСЯ до человека мимо приложения, а не замена знанию
 * приложения о звонке. Поэтому вариантов ровно два, и «только нативный,
 * мимо машины» среди них нет.
 *
 * Чем нативный путь не дублирует внутренний баннер: рингтон внутри
 * приложения отдельно гейтится по `AppState` в самом провайдере, так что
 * «баннер смонтирован, но экран погашен» не звенит и не держит wake lock —
 * ровно то, ради чего решение `decideIncomingCallPresentation` и вводилось
 * (VED-222, BUG D).
 */
export interface RingingRouting {
  /** Поднять нативный экран: Telecom `Connection` + полноэкранный intent. */
  showNative: boolean;
  /**
   * Отдать событие машине состояний (`reduceCall`). Решение живёт здесь, а
   * не в провайдере, именно потому, что поломка была в нём: провайдер
   * выходил из обработчика раньше `dispatch`. Теперь провайдер —
   * безусловный исполнитель, а правило закрыто тестом.
   */
  trackInMachine: boolean;
}

export interface RingingRoutingInput {
  /** `Platform.OS`. Нативный модуль звонков есть только на Android. */
  platform: string;
  /** `AppState.currentState` в момент события. */
  appState: AppStateStatus;
  /** Фаза звонков прямо сейчас: поверх идущего разговора нативный экран не
   *  поднимаем — второй звонок сервер и так отвергнет как «занято». */
  phase: CallPhase;
  /** Звонят нам (мы `callee`), а не это наш же исходящий с другого
   *  устройства (VED-346). */
  isCallee: boolean;
}

export function routeRingingEvent(input: RingingRoutingInput): RingingRouting {
  const showNative =
    input.platform === 'android' &&
    input.isCallee &&
    input.phase === 'idle' &&
    input.appState !== 'active';
  // `trackInMachine` — всегда. Это не забывчивость, а само правило:
  // приложение обязано знать о звонке, который ему звонит, независимо от
  // того, каким способом об этом узнал человек.
  return { showNative, trackInMachine: true };
}
