/**
 * Что именно выключает каждый тумблер — словами (VED-361, пункт «честные
 * тексты»).
 *
 * Разделив звонки и сообщения, легко получить настройку, из которой непонятно,
 * что останется работать. Человек выключает «Сообщения» и не знает, замолчит
 * ли телефон совсем; выключает «Звонки» — и думает, что заодно потерял
 * переписку. Поэтому подпись каждого тумблера прямо называет и то, что
 * пропадёт, и то, что останется.
 *
 * Модуль чистый и лежит отдельно от разметки: формулировка — это решение, и
 * проверяется она тестом, а не взглядом на экран.
 */

export type NotificationSwitchKey = 'chat' | 'calls';

export interface NotificationSwitchCopy {
  key: NotificationSwitchKey;
  /** Подпись тумблера. */
  label: string;
  /** Подпись для скринридера: одного слова «Сообщения» ему мало. */
  accessibilityLabel: string;
  /** Что происходит при текущем положении тумблера. */
  note: string;
}

export function notificationSwitchCopy(params: {
  chat: boolean;
  calls: boolean;
}): NotificationSwitchCopy[] {
  return [
    {
      key: 'chat',
      label: 'Сообщения',
      accessibilityLabel: 'Уведомления о сообщениях',
      note: params.chat
        ? 'Телефон сообщит о новых сообщениях. Выключите — перестанут приходить сообщения, звонки продолжат звонить.'
        : 'Сообщения телефон не показывает. Звонки при этом звонят — у них свой выключатель ниже.',
    },
    {
      key: 'calls',
      label: 'Звонки',
      accessibilityLabel: 'Уведомления о звонках',
      note: params.calls
        ? 'Телефон зазвонит о входящем, даже если беседа без звука. Выключите — перестанут звонить звонки, сообщения продолжат приходить.'
        : 'О входящем звонке телефон молчит. Сообщения при этом приходят — у них свой выключатель выше.',
    },
  ];
}

/**
 * Строка над тумблерами. Отдельно от них, потому что говорит про другое: про
 * общий выключатель портала, который сильнее обоих.
 */
export function notificationSwitchesHint(enabled: boolean): string {
  return enabled
    ? 'Сообщения и звонки выключаются порознь: заглушить переписку и при этом слышать вызовы — нормально.'
    : 'Все уведомления выключены на сайте — пока так, не придёт ни сообщение, ни звонок. Тумблеры ниже сохранены и заработают, когда включите уведомления снова.';
}
