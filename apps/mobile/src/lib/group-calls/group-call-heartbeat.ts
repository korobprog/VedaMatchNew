/**
 * «Я ещё здесь» глазами клиента.
 *
 * Сервер убирает участника, от которого не было подтверждения дольше
 * `GROUP_CALL_PARTICIPANT_TTL_MS` (`apps/api/.../group/group-call-room.ts`), —
 * у остальных он просто исчезает из списка. Обратная сторона того же правила
 * нужна и здесь: если подтверждения не уходят (телефон в офлайне, портал
 * недоступен), то нас в комнате уже нет, сколько бы соединений ни оставалось
 * открытыми. Экран в этот момент показывает разговор и таймер — и врёт:
 * остальные нас не слышат, а мы говорим в пустоту.
 *
 * Провайдер до этого молча глотал ошибку heartbeat'а (`.catch(() =>
 * undefined)`), и заметить выпадение было нечем. Перенесено из веб-части
 * (VED-293, этап 2, `apps/web/.../group/group-call-heartbeat.ts`) — там это
 * появилось первым.
 *
 * Числа не независимые: тайм-аут — это ровно три пропущенных подтверждения,
 * и держать их согласованными — задача этого модуля, а не двух случайных
 * констант в разных файлах.
 */

/** Как часто подтверждаем присутствие. */
export const GROUP_CALL_HEARTBEAT_MS = 15_000;

/** Сколько сервер ждёт подтверждения, прежде чем убрать участника. */
export const GROUP_CALL_TTL_MS = 45_000;

/**
 * Сколько подряд неудачных подтверждений означают, что сервер нас уже убрал.
 * Короткая просадка сети (лифт, Wi-Fi → LTE) сюда не попадает: она
 * укладывается в один-два пропуска.
 */
export const HEARTBEAT_FAILURES_BEFORE_LOST = Math.ceil(
  GROUP_CALL_TTL_MS / GROUP_CALL_HEARTBEAT_MS,
);

export function heartbeatLost(consecutiveFailures: number): boolean {
  return consecutiveFailures >= HEARTBEAT_FAILURES_BEFORE_LOST;
}

/** Что показать, когда подтверждения перестали доходить. */
export const HEARTBEAT_LOST_MESSAGE =
  'Связь с порталом пропала — вас вывели из звонка';

/**
 * Не чаще этого — между двумя подтверждениями (VED-360).
 *
 * Подтверждение теперь шлют два источника: JS-таймер (пока приложение на
 * экране) и тик нативной службы (`GroupCallKeepAliveService`, идёт всегда —
 * JS-таймеры Android останавливает вместе с `Activity`). На переднем плане
 * оба тикают раз в 15 с, и без этого порога запросов было бы вдвое больше.
 * Порог заметно меньше шага: тик и таймер плывут, и пропустить законный
 * тик из-за дрожи в секунду нельзя.
 */
export const HEARTBEAT_MIN_GAP_MS = 10_000;

/**
 * Пора ли подтверждать присутствие. `lastAt` — когда ушло прошлое
 * подтверждение (`null` — ещё не уходило). `force` — возврат приложения
 * на экран: после паузы, о которой мы не знаем, сколько она длилась,
 * подтверждаем сразу.
 */
export function heartbeatDue(
  lastAt: number | null,
  now: number,
  force = false,
): boolean {
  if (force || lastAt === null) return true;
  return now - lastAt >= HEARTBEAT_MIN_GAP_MS;
}
