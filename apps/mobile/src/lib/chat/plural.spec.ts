import { withPlural } from './plural';

describe('withPlural', () => {
  it('склоняет по последним цифрам, включая 11–14', () => {
    const f = (n: number) => withPlural(n, 'участник', 'участника', 'участников');
    expect([1, 2, 5, 11, 12, 21, 22, 25, 101, 111].map(f)).toEqual([
      '1 участник',
      '2 участника',
      '5 участников',
      '11 участников',
      '12 участников',
      '21 участник',
      '22 участника',
      '25 участников',
      '101 участник',
      '111 участников',
    ]);
  });
});
