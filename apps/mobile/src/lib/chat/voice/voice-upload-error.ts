/**
 * Сообщение об ошибке отправки голосового — человеку всегда по-русски,
 * независимо от причины. Техническая причина (может быть текстом стороннего
 * fetch на английском, например «Unsupported FormDataPart implementation»,
 * VED-286, feedback-002 п.1) уходит в `console.warn` рядом с вызовом, не
 * сюда — эта функция намеренно не принимает исходную ошибку, чтобы её
 * нельзя было случайно подставить в текст для пользователя.
 */
export function describeVoiceUploadError(): string {
  return 'Не удалось отправить голосовое';
}
