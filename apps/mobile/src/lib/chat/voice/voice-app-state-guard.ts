import type { AppStateStatus } from 'react-native';

/**
 * Уход приложения в фон во время записи/воспроизведения голосового
 * (VED-286, feedback-001 п.2, уточнение в feedback-002 п.4).
 *
 * ВАЖНО: этот JS-обработчик — не единственный актёр. `AudioModule.kt`
 * (`node_modules/expo-audio/android/.../AudioModule.kt`,
 * `OnActivityEntersBackground`) САМ ставит все активные рекордеры на паузу
 * (`recorder.pauseRecording()`) и все играющие плееры на паузу при уходе
 * Activity в фон, если `allowsBackgroundRecording`/`shouldPlayInBackground`
 * не включены (в этом проекте оба выключены осознанно) — независимо от
 * того, подписан ли кто-то в JS на `AppState` вообще. Он же на возврате в
 * приложение (`OnActivityEntersForeground`) сам вызывает `recorder.record()`
 * для рекордеров, оставшихся на паузе. На практике порядок такой: нативный
 * `pause` срабатывает первым (та же Activity-колбэк, что видит и
 * `AppState`), JS ниже лишь дожимает «пауза → полная отмена» — `stop()`
 * после нативного `pause()` валиден для `MediaRecorder`, крэша это не даёт
 * (проверено по `AudioRecorder.kt`, поведение — переход состояний, а не
 * гонка данных). Но у него остаётся смысл сам по себе: без него нативная
 * пауза при возврате в приложение САМА возобновила бы запись
 * (`recorder.record()` выше), и человек продолжил бы писать голосовое,
 * ничего не подозревая о том, что часть его пропала, пока телефон был
 * свёрнут — JS-обработчик ниже вместо этого честно останавливает и
 * отменяет всю запись целиком.
 *
 * Запись: Android режет доступ к микрофону из фона без foreground-службы
 * записи, которой у нас нет — заводить постоянно висящее уведомление ради
 * голосовых сообщений (в отличие от звонков, `CallForegroundService`)
 * несоразмерно. Решение — как для входящего звонка (`voice-call-guard.ts`):
 * запись останавливается и НЕ отправляется, а не «отправить то, что успели
 * записать» и не «оставить черновик». Черновик голосового больше нигде в
 * приложении не существует как понятие — заводить его только ради этого
 * случая усложняет модель без выигрыша. Человек не должен решить, что
 * голосовое ушло само по себе, поэтому по возврату в приложение
 * (`voice-recorder-control.tsx`) показывается короткое «Запись остановлена».
 *
 * Воспроизведение — просто пауза, не потеря позиции: вернувшись, можно
 * продолжить с того же места (`voice-message-player.tsx`); нативная пауза
 * плеера (см. выше) целится в то же самое и не противоречит JS-обработчику.
 *
 * Срабатывает только на `background`, не на `inactive` — на Android
 * `inactive` практически не возникает (в основном многозадачность iOS), а
 * трактовать его как уход в фон означало бы обрывать запись на любое
 * мимолётное системное всплытие поверх приложения.
 */
export function shouldCancelRecordingForAppState(state: AppStateStatus): boolean {
  return state === 'background';
}

export function shouldPausePlaybackForAppState(state: AppStateStatus): boolean {
  return state === 'background';
}
