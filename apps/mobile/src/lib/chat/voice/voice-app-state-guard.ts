import type { AppStateStatus } from 'react-native';

/**
 * Уход приложения в фон во время записи/воспроизведения голосового
 * (VED-286, feedback-001 п.2).
 *
 * Запись: Android режет доступ к микрофону из фона без foreground-службы
 * записи, которой у нас нет — заводить постоянно висящее уведомление ради
 * голосовых сообщений (в отличие от звонков, `CallForegroundService`)
 * несоразмерно. Решение — как для входящего звонка (`voice-call-guard.ts`):
 * запись останавливается и НЕ отправляется, а не «отправить то, что успели
 * записать» и не «оставить черновик». Черновик голосового больше нигде в
 * приложении не существует как понятие — заводить его только ради этого
 * случая усложняет модель без выигрыша. Человек не должен решить, что
 * голосовое ушло само по себе, поэтому по возврату в приложение
 * (`voice-recorder-control.tsx`) показывается короткое «Запись остановлена».
 *
 * Воспроизведение — просто пауза, не потеря позиции: вернувшись, можно
 * продолжить с того же места (`voice-message-player.tsx`).
 *
 * Срабатывает только на `background`, не на `inactive` — на Android
 * `inactive` практически не возникает (в основном многозадачность iOS), а
 * трактовать его как уход в фон означало бы обрывать запись на любое
 * мимолётное системное всплытие поверх приложения.
 */
export function shouldCancelRecordingForAppState(state: AppStateStatus): boolean {
  return state === 'background';
}

export function shouldPausePlaybackForAppState(state: AppStateStatus): boolean {
  return state === 'background';
}
