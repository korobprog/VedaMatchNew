/**
 * Что запрещено, пока идёт запись голосового (VED-286, feedback-003,
 * блокирующий п.2).
 *
 * Меню сообщения (`app/chat/[id].tsx: openMenu`) — единственный путь к
 * `editing !== null` (пункт «Изменить», `startEdit`). Композер уже не даёт
 * `canSubmit` вытолкнуть `VoiceRecorderControl` во время записи
 * (`(canSubmit && !voiceRecording) || editing`, feedback-002), но условие
 * `|| editing` — независимый второй триггер того же размонтирования, и он
 * этой защитой не покрыт: войти в правку можно и без `canSubmit`. Как
 * только `editing` становится не `null`, композер рендерит кнопку
 * «Сохранить» вместо `VoiceRecorderControl`, а размонтирование во время
 * активной записи — путь БЕЗ навигационного `blur`, то есть
 * `useFocusEffect` (основная защита, `voice-recorder-control.tsx`) здесь
 * не сработает и обрыв записи попадёт в задокументированно ненадёжную
 * вторую линию (обычный `useEffect`-cleanup, зависящий от порядка хуков).
 *
 * Проще и надёжнее — не открывать меню сообщения вовсе, пока запись
 * активна: реакция/ответ/копирование/удаление подождут несколько секунд до
 * конца записи, а не рискуют кладом записи ради них.
 */
export function canOpenMessageMenuWhileRecording(voiceRecording: boolean): boolean {
  return !voiceRecording;
}
