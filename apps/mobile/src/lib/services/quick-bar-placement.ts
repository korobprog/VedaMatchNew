/**
 * Где стоит панель быстрого доступа (VED-385), а где её нет — и почему.
 *
 * Правило одно и структурное: панель монтируется в раскладке вкладок
 * `app/(tabs)/_layout.tsx` и видна на всех пяти вкладках. Всё, что
 * открывается ПОВЕРХ вкладок, — маршруты корневого стека
 * (`components/root-shell-stack.tsx`), и панели там нет не потому, что её
 * прячут по списку, а потому, что её там не монтируют. Новый полноэкранный
 * экран, добавленный в корневой стек, получает «без панели» сам, без правки
 * этого файла.
 *
 * Почему так. Вкладки — место, где выбирают, куда пойти: панель там и нужна.
 * Экран поверх вкладок — место, где человек уже что-то делает: пишет, говорит,
 * наводит камеру. Там каждый пиксель сверху занят делом (шапка собеседника,
 * видео, видоискатель), и полоса ярлыков, уводящих из текущего дела, мешала бы.
 *
 * Список ниже — не механизм, а документ и сторож: `quick-bar-placement.spec.ts`
 * проверяет, что эти экраны действительно объявлены в корневом стеке, а не
 * во вкладках, и что панель не смонтирована нигде, кроме раскладки вкладок.
 */

