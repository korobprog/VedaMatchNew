/**
 * Верхний отступ экрана вкладки. Когда панель видна, она сама занимает
 * вырез и строку состояния (`paddingTop: insets.top` у панели), и экран под
 * ней отступ под вырез повторять не должен — иначе между панелью и
 * заголовком вкладки встаёт пустая полоса высотой с вырез.
 */
export function screenTopInset(safeTop: number, barVisible: boolean): number {
  return barVisible ? 0 : safeTop;
}
