/**
 * Средства раздела «Здоровье» (VED-335, третий заход).
 *
 * «Здоровье» — раздел, а сканер — одно из его средств, а не сам раздел. До
 * этого карточка сервиса открывала сканер напрямую, и второму средству места
 * в приложении не было вовсе: его пришлось бы вешать кнопкой внутри сканера,
 * то есть внутри чужого экрана.
 *
 * Список — данные. Добавить третье средство значит дописать строку, а не
 * править разметку экрана: ровно это и проверяет спека рядом.
 *
 * На сайте раздел уже устроен так же (`apps/web/src/app/(portal)/wellness/page.tsx`
 * — плитки «Проверить продукт», «Мои ограничения», «История», «Корзина»,
 * «Рецепты»), и здесь повторяется не весь его список, а только то, что
 * приложение умеет само. Врать плиткой, которая ничего не открывает, нельзя.
 */

/** Значок рисуется экраном; имена намеренно свои, а не из чужой библиотеки. */
export type WellnessToolIcon = 'scan' | 'history';

export interface WellnessTool {
  key: string;
  title: string;
  /** Одна строка: зачем это средство. Без неё ярлык — загадка. */
  text: string;
  /** Маршрут приложения. Проверяется спекой: он обязан начинаться с `/`. */
  route: string;
  icon: WellnessToolIcon;
}

