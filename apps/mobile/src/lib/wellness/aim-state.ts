/**
 * Рамка прицеливания сканера: три состояния, подсказки и помощь, когда код
 * упорно не читается (VED-335).
 *
 * Рамка — не индикатор итога, а живая подсказка во время наведения: она
 * показывает, куда класть штрихкод, и меняется по ходу чтения. Цвет при этом
 * помощник, а не носитель смысла: зелёное и красное различают не все, поэтому
 * у каждого состояния есть заголовок и совет, и ровно они читаются
 * скринридером. Убрать из экрана цвет — сканером всё равно можно
 * пользоваться; убрать слова — нельзя.
 *
 * ЧТО КАМЕРА НА САМОМ ДЕЛЕ СООБЩАЕТ. `expo-camera` не умеет сказать «вижу
 * штрихкод, но не могу разобрать»: событие `onBarcodeScanned` приходит только
 * на удачное декодирование. Поэтому жёлтая привязана к тому единственному
 * признаку неуверенного чтения, который у нас есть на самом деле, — код
 * декодирован, но не сошёлся с контрольной цифрой (смазано, блик, половина
 * полосок срезана). Это честный «вижу, но не прочитал»: выдумывать
 * промежуточное состояние из ничего значило бы показывать человеку жёлтую по
 * таймеру и врать ею.
 *
 * Модуль чистый и без React: правила рамки должны проверяться тестом, а не
 * глазами в магазине.
 */

/** Красная — кода нет, жёлтая — виден, но не прочитан, зелёная — прочитан. */
export type AimState = 'searching' | 'unstable' | 'read';

/** Имя токена темы, а не цвет: значение берётся из палитры экраном. */
export type AimTone = 'danger' | 'warning' | 'success';

/** Что сканер делает с уже прочитанным кодом. */
export type LookupPhase = 'idle' | 'pending' | 'done';

export interface AimInput {
  /**
   * Когда камера в последний раз ДЕКОДИРОВАЛА что-то, что кодом не оказалось:
   * не сошлась контрольная цифра или формат не про еду. `null` — ни разу.
   */
  sawAt: number | null;
  now: number;
  lookup: LookupPhase;
}

/**
 * Сколько держим жёлтую после неудачной попытки.
 *
 * Без задержки рамка мигает красным на каждом кадре, где распознавание не
 * сработало, — а рука с телефоном дрожит всегда. Мигание в такт дрожанию
 * читается как поломка, а не как подсказка.
 */
export const AIM_HOLD_MS = 900;

export function aimState({ sawAt, now, lookup }: AimInput): AimState {
  // Код прочитан и принят — зелёная, что бы ни показывала камера сейчас:
  // человек уже отводит телефон и ждёт ответа.
  if (lookup !== 'idle') return 'read';
  if (sawAt === null) return 'searching';
  return now - sawAt <= AIM_HOLD_MS ? 'unstable' : 'searching';
}

export interface AimCopy {
  tone: AimTone;
  /** Короткое слово состояния — рядом с рамкой, тем же цветом. */
  title: string;
  /** Что делать руками. Состояние без совета человеку бесполезно. */
  hint: string;
  /**
   * Одной строкой для скринридера: он читает область целиком, а не две
   * подписи по отдельности.
   */
  accessibilityLabel: string;
}

const COPY: Record<AimState, AimCopy> = {
  searching: {
    tone: 'danger',
    title: 'Наведите на штрихкод',
    hint: 'Поместите полоски внутрь рамки, держите телефон в 10–15 см.',
    accessibilityLabel:
      'Штрихкод не виден. Поместите полоски внутрь рамки, держите телефон в 10–15 сантиметрах.',
  },
  unstable: {
    tone: 'warning',
    title: 'Держите ровнее',
    hint: 'Код виден, но читается не целиком. Поднесите ближе и не наклоняйте.',
    accessibilityLabel:
      'Код виден, но читается не целиком. Поднесите телефон ближе и не наклоняйте его.',
  },
  read: {
    tone: 'success',
    title: 'Готово, ищем товар',
    hint: 'Код прочитан — можно убрать телефон.',
    accessibilityLabel: 'Код прочитан. Ищем товар, телефон можно убрать.',
  },
};

export function describeAim(state: AimState): AimCopy {
  return COPY[state];
}

/** Все три состояния разом — для теста и для экрана справки. */
export const AIM_STATES: readonly AimState[] = ['searching', 'unstable', 'read'];

/**
 * Через сколько сканер сам начинает помогать, не дожидаясь, пока человек
 * догадается. Восемь секунд — это уже «стою и вожу телефоном», а не «навожу».
 */
export const HELP_AFTER_MS = 8_000;

/**
 * Через сколько сканер сам открывает ручной ввод. Тринадцать секунд подряд
 * без результата обычно значат, что код стёрт, заклеен ценником или запотел, —
 * и камера его не прочитает никогда, сколько ни целься.
 */
export const MANUAL_AFTER_MS = 13_000;

/**
 * Сколько игнорируем ТОТ ЖЕ код после возврата с экрана ответа.
 *
 * Найдено живой проверкой на A51: человек нажимает «Проверить ещё продукт»,
 * упаковка всё ещё в кадре — и сканер мгновенно уносит его обратно на тот же
 * ответ. До кнопок «Ввести код вручную» и «Последние проверки» дотянуться
 * нельзя вовсе: экран отскакивает раньше, чем палец доходит.
 *
 * Пауза короткая и снимается сама: за две с половиной секунды телефон
 * успевают отвести, а перепроверить тот же продукт человеку никто не мешает —
 * достаточно подержать код в кадре чуть дольше.
 */
export const SAME_CODE_COOLDOWN_MS = 2_500;

/**
 * Принимать ли прочитанный код. ДРУГОЙ код принимается сразу: взяли вторую
 * пачку — ответ должен прийти немедленно, а не через паузу.
 */
export function shouldAcceptBarcode({
  barcode,
  lastBarcode,
  lastHandedAt,
  now,
}: {
  barcode: string;
  /** Последний код, с которым уже уходили на экран ответа. */
  lastBarcode: string | null;
  lastHandedAt: number | null;
  now: number;
}): boolean {
  if (lastBarcode === null || lastHandedAt === null) return true;
  if (barcode !== lastBarcode) return true;
  return now - lastHandedAt > SAME_CODE_COOLDOWN_MS;
}

export interface ScanHelp {
  /** Советы по порядку — что попробовать. Пусто, пока помогать рано. */
  hints: string[];
  /** Раскрыть ручной ввод самим, не дожидаясь нажатия. */
  offerManual: boolean;
}

/**
 * Советы при долгой неудаче. Порядок не случайный: сначала бесплатное и
 * мгновенное (фонарик), потом действие руками, и только потом признание, что
 * камера тут не поможет.
 */
const HINTS = [
  'Включите фонарик — на блестящей упаковке это чаще всего и мешает.',
  'Протрите упаковку и расправьте плёнку: смятые полоски не читаются.',
  'Приблизьте: мелкий код должен занять рамку целиком.',
  'Код стёрт или заклеен ценником — наберите цифры под полосками вручную.',
];

export function scanHelp({
  startedAt,
  now,
  lookup,
}: {
  /** Когда началась текущая попытка: вход на экран или возврат с ответа. */
  startedAt: number;
  now: number;
  lookup: LookupPhase;
}): ScanHelp {
  // Код уже прочитан — помогать не с чем, советы только отвлекают.
  if (lookup !== 'idle') return { hints: [], offerManual: false };
  const elapsed = now - startedAt;
  if (elapsed < HELP_AFTER_MS) return { hints: [], offerManual: false };
  const offerManual = elapsed >= MANUAL_AFTER_MS;
  // Последний совет — про ручной ввод; он появляется вместе с самим полем,
  // а не раньше: советовать то, чего на экране ещё нет, — издевательство.
  return {
    hints: offerManual ? HINTS : HINTS.slice(0, -1),
    offerManual,
  };
}
