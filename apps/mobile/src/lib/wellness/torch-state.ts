/**
 * Фонарик сканера: когда он действительно горит и что об этом написано
 * (VED-335, третий заход).
 *
 * Пользователь сообщил «фонарик не работает». На A51 он работает: в логе
 * CameraX видно `TorchControl#setTorchAsync: torch mode = TorchMode(value=1)`
 * и `ANDROID_FLASH_MODE(2)`, светодиод загорается. Не работало другое — то,
 * как это выглядело:
 *
 * 1. **Кнопка уезжала из-под пальца.** Подпись менялась с «Фонарик» на
 *    «Фонарик выкл.», кнопка становилась шире, и соседняя уезжала влево на
 *    десятки пикселей. Человек целился в «Приблизить», попадал в фонарик и
 *    наоборот — со стороны это ровно «кнопка не слушается». Поймано замером
 *    границ через `uiautomator`: `[529,149][753,206]` до и после переключения
 *    границы разные.
 * 2. **Состояние было видно только тонкой рамкой.** В магазине при свете
 *    светодиод глазом почти не заметен, а обводка — не ответ на вопрос
 *    «включилось или нет».
 * 3. **Фонарик гас после каждой проверки.** Экран гасил его при уходе на
 *    ответ и не возвращал обратно: человек в тёмном углу магазина включал
 *    его заново на каждый продукт.
 *
 * Отсюда правила ниже. Они чистые, чтобы проверяться тестом, а не памятью.
 */

export interface TorchInput {
  /** Чего хочет человек: он нажал кнопку. Живёт, пока открыт сканер. */
  wanted: boolean;
  /** Экран сканера сейчас на виду. Уход на ответ — это `false`. */
  focused: boolean;
}

/**
 * Горит ли светодиод. Желание человека и фактическое горение разведены
 * намеренно: пока он читает ответ, жечь светодиод незачем, но и забывать
 * его выбор нельзя — вернувшись, он ждёт, что фонарик всё ещё включён.
 */
export function torchEnabled({ wanted, focused }: TorchInput): boolean {
  return wanted && focused;
}

export interface ToggleCopy {
  /** Подпись на кнопке. НЕ меняется вместе с состоянием — см. причину выше. */
  label: string;
  /** Что читает скринридер: здесь состояние называется словами. */
  accessibilityLabel: string;
}

export function torchCopy(wanted: boolean): ToggleCopy {
  return {
    label: 'Фонарик',
    accessibilityLabel: wanted
      ? 'Фонарик включён. Нажмите, чтобы выключить'
      : 'Фонарик выключен. Нажмите, чтобы включить',
  };
}

/**
 * Приближение. Подпись меняется, но её ширина — нет: «Зум 1×», «Зум 2×»,
 * «Зум 3×» одинаковой длины, и соседняя кнопка с места не двигается.
 */
export function zoomCopy(step: number, total: number): ToggleCopy {
  return {
    label: `Зум ${step + 1}×`,
    accessibilityLabel: `Приближение ${step + 1} из ${total}. Нажмите, чтобы увеличить`,
  };
}
