/**
 * Что умеет сборка канала (VED-207).
 *
 * Одна кодовая база даёт два разных продукта: файл с сайта (`site`) и
 * приложение витрины (`store`, RuStore и Google Play). Разница между ними —
 * не набор разбросанных по экранам `if (channel === 'site')`, а эта таблица:
 * каждая возможность объявлена один раз и на оба канала сразу, и именно её
 * читают экраны, хук самообновления и `app.config.ts`.
 *
 * Почему таблица, а не флаги в `AppVariant`: флаг `selfUpdate` в варианте
 * (как было до VED-207) отвечал ровно на один вопрос и не оставлял места
 * следующим — оплате (VED-209), ссылкам на платные разделы сайта (VED-216),
 * предложению скачать APK. Каждая новая пара «канал × функция» иначе
 * превращается в ещё одно поле варианта и ещё одну проверку в экране.
 *
 * Почему только канал, а не контур: правила магазинов одинаковы для ru и com
 * (`docs/mobile-app-store-links.md`) — у RuStore и Google Play различается
 * платёжный механизм, а не то, что приложению вообще разрешено показывать.
 * Инвариант «контур на возможности не влияет» закреплён тестом, чтобы
 * контурная правка не протащила платный экран в магазинную сборку.
 *
 * Модуль чистый: его читают и `app.config.ts` в Node во время сборки, и
 * рантайм через `appCapabilities()` (`app-variant.ts`), и тесты.
 */

import type { AppVariant, Channel } from './variant';

export interface AppCapabilities {
  /**
   * Секция «Проверить обновление» и установка APK системным установщиком
   * (VED-176). На `store` её нет вовсе: обновления раздаёт витрина, а
   * REQUEST_INSTALL_PACKAGES Google Play требует отдельно обосновывать.
   */
  selfUpdate: boolean;
  /**
   * Точки входа в оплату и подписку внутри приложения — экран тарифа, кнопка
   * «Оплатить», цены (VED-209, оплата на сервере — VED-208). Правило платежей
   * обоих магазинов: цифровую подписку нельзя продавать мимо витрины
   * (`docs/mobile-app-store-links.md`, Apple 3.1.1/3.1.3, Google Play
   * Payments), а для продавца с российским счётом Google Play Billing закрыт
   * с 26.12.2024 — поэтому монетизация живёт только в файле с сайта.
   */
  inAppPayments: boolean;
  /**
   * Ссылки и призывы, ведущие в платные разделы сайта (тариф, оплата,
   * продление). Отдельно от `inAppPayments`: своего платёжного экрана может
   * не быть, а ссылка «оплатить на сайте» — такое же нарушение правила
   * платежей, как встроенная касса (Apple 3.1.3, Google Play).
   */
  paidWebLinks: boolean;
  /**
   * Предложение скачать APK с сайта («полная версия», «скачайте с
   * vedamatch.ru»). В магазинной сборке это ещё и Spam/Minimum Functionality:
   * приложение не должно уводить пользователя ставить себя мимо витрины.
   */
  apkDownloadPrompt: boolean;
  /**
   * Открытие бесплатных разделов сайта в системном браузере — каталог
   * «Сервисы», заглушки вкладок, общины. Разрешено на обоих каналах: ссылки
   * на бесплатные разделы правилами не запрещены
   * (`docs/mobile-app-store-links.md`, «Главный вывод»). Возможность заведена
   * не ради текущей разницы, а чтобы эта строка была осознанным решением, а
   * не умолчанием: если ревью VED-216 потребует убрать часть ссылок, гасится
   * она здесь, а не в пяти экранах.
   */
  siteServiceLinks: boolean;
}

/** Порядок таблицы в README и в сообщениях тестов. */
export const CAPABILITY_KEYS = [
  'selfUpdate',
  'inAppPayments',
  'paidWebLinks',
  'apkDownloadPrompt',
  'siteServiceLinks',
] as const satisfies readonly (keyof AppCapabilities)[];

// Человеческие имена возможностей живут не здесь, а в `store-safety.ts`
// (`CAPABILITY_LABELS`): этот модуль попадает в бандл обеих сборок, а имена
// нужны только сообщениям проверок — и состоят ровно из тех слов, которые
// проверка ищет в бандле витрины.

/**
 * Единственное место, где написано «что можно каналу». Обе строки заданы
 * целиком, без `...site` и точечных переопределений: разницу между сборками
 * должно быть видно глазом в одном экране, а не вычислять её в уме.
 */
const BY_CHANNEL: Record<Channel, AppCapabilities> = {
  site: {
    selfUpdate: true,
    inAppPayments: true,
    paidWebLinks: true,
    apkDownloadPrompt: true,
    siteServiceLinks: true,
  },
  store: {
    selfUpdate: false,
    inAppPayments: false,
    paidWebLinks: false,
    apkDownloadPrompt: false,
    siteServiceLinks: true,
  },
};

/**
 * Возможности сборки. Копия, а не ссылка на строку таблицы: вызывающий код
 * не должен уметь испортить таблицу всем остальным (та же причина, что у
 * `pushProviders` в `variant.ts`).
 *
 * Канал приходит из `extra.variant`, то есть из данных сборки, а не из
 * литерала — незнакомое значение тут возможно (например, сборка старой
 * версией конфига), и лучше упасть с внятным текстом, чем молча выдать
 * пустой набор возможностей.
 */
export function capabilitiesFor(variant: Pick<AppVariant, 'channel'>): AppCapabilities {
  const row = BY_CHANNEL[variant.channel];
  if (!row) {
    throw new Error(`Канал "${variant.channel}" не описан в таблице возможностей capabilities.ts`);
  }
  return { ...row };
}
