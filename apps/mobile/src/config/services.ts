/**
 * Хелпер склейки ссылок на сайт (VED-174).
 *
 * Раньше здесь был статический список `SERVICE_LINKS` из шести сервисов
 * латиницей, а в итерации 1 — резервный `FALLBACK_SERVICES` на случай
 * первой ошибки загрузки. Оба варианта убраны (раунд оценки 007, дефект 2):
 * спека прямо запрещает переписывать названия и описания текстом второй
 * раз, а резерв уже на первом прогоне расходился с продом (у половины
 * сервисов не совпали описания, часть сервисов в резерве не было вовсе,
 * `music` на проде называется «Медиатека», а не «Музыка», как в старом
 * резерве). Единственный источник каталога — `GET /services`
 * (`lib/services/services-api.ts`); при ошибке загрузки экран показывает
 * обычное состояние «ошибка + Повторить», как на вкладке «Общины».
 */

/** Склейка без двойного слэша: origin из варианта сборки уже без хвоста. */
export function serviceUrl(webOrigin: string, path: string): string {
  return `${webOrigin.replace(/\/+$/, '')}/${path.replace(/^\/+/, '')}`;
}
