/**
 * Вырезание комментариев из исходника — для проверок сборки витрины
 * (VED-207).
 *
 * Зачем: проверки ищут в коде запрещённые витринами строки и ветвления по
 * каналу. Комментарий — не код: в релизный бандл он не попадает (минификатор
 * их снимает), зато в нём как раз и написано, ЧТО запрещено и почему. Без
 * этого шага правило ругается на собственную документацию, а значит его
 * быстро отключат.
 *
 * Разбор намеренно примитивный — посимвольный автомат, знающий строки,
 * шаблонные литералы и экранирование. Регулярные литералы отдельным
 * состоянием не разбираются: `/` в коде считается началом комментария только
 * если за ним сразу идёт `/` или `*`, а в наших регулярках слэш внутри
 * экранирован (`/\/+$/`). Полноценный парсер здесь не нужен: цена ошибки —
 * лишняя или недостающая находка в проверке, а не сломанная сборка.
 *
 * Переводы строк сохраняются, содержимое комментариев заменяется пробелами:
 * номера строк в сообщении об ошибке должны совпадать с файлом.
 */

type State = 'code' | 'line' | 'block' | "'" | '"' | '`';

export function stripComments(source: string): string {
  let state: State = 'code';
  let out = '';

  for (let i = 0; i < source.length; i += 1) {
    const char = source[i];
    const next = source[i + 1];

    if (state === 'code') {
      if (char === '/' && next === '/') {
        state = 'line';
        out += '  ';
        i += 1;
      } else if (char === '/' && next === '*') {
        state = 'block';
        out += '  ';
        i += 1;
      } else {
        if (char === "'" || char === '"' || char === '`') state = char;
        out += char;
      }
      continue;
    }

    if (state === 'line') {
      if (char === '\n') {
        state = 'code';
        out += char;
      } else {
        out += ' ';
      }
      continue;
    }

    if (state === 'block') {
      if (char === '*' && next === '/') {
        state = 'code';
        out += '  ';
        i += 1;
      } else {
        out += char === '\n' ? '\n' : ' ';
      }
      continue;
    }

    // Внутри строки: экранированный символ пропускаем целиком, чтобы `\'` не
    // закрывал строку, а `\\` не экранировал следующую кавычку.
    if (char === '\\' && next !== undefined) {
      out += char + next;
      i += 1;
      continue;
    }
    if (char === state) state = 'code';
    out += char;
  }

  return out;
}
