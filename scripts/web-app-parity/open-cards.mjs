#!/usr/bin/env node
// Карточки доски, среди которых `dedupe-existing-card.mjs` ищет дубль
// (VED-215). Вынесено из `run.mjs` отдельным модулем в раунде 003
// (Н-нов-4) по правилу CLAUDE.md: «Чистая логика выносится в отдельный
// модуль и покрывается тестом, даже когда обёртка вокруг неё не
// тестируется» — до этого функция жила прямо в раннере и не тестировалась
// юнитом вовсе, хотя несёт главное новое поведение раунда 002 (Н4: дедуп
// по всей доске, не только по колонке создания).

/**
 * Карточки, среди которых ищем дубль. Раунд 001, Н4: искать нужно по всей
 * доске, не только в колонке создания («VedaMath-Native») — карточку
 * могли перетащить в «В работе»/«На доработку», пока её не закрыли, и
 * следующий PR по тому же сервису обязан увидеть её там же, а не завести
 * вторую. Закрытые колонки (`isDone`, «Выполнено») исключены осознанно:
 * закрытая карточка не дубль, а прошлая задача, новый PR должен завести
 * новую.
 *
 * @param {{columns?: {isDone?: boolean; tasks?: {id: string; title: string}[]}[]} | null | undefined} board
 *   ответ `GET /work/boards/:id` (`WorkBoardDto` — `packages/shared/src/work.ts`).
 * @returns {{id: string; title: string}[]} карточки всех неархивных, но не
 *   закрытых колонок, в порядке колонок доски.
 */
export function openCardsAcrossBoard(board) {
  return (board?.columns ?? [])
    .filter((column) => !column?.isDone)
    .flatMap((column) => column?.tasks ?? []);
}
