/**
 * Уборка лишних пустых строк в длинном тексте (VED-372).
 *
 * Портальная чистая функция, не сервисная: ею пользуются форма поста в
 * блог-ленте и форма статьи/катхи в «Образовании», а завтра — любое поле, куда
 * вставляют текст из мессенджера, заметок или PDF. Ни одного эндпоинта она не
 * знает, ни одной сервисной модели не касается, поэтому живёт здесь, а не
 * внутри какого-то сервиса: иначе второй сервис был бы вынужден либо
 * импортировать чужой модуль, либо копировать логику.
 *
 * Сколько строк оставлять и какими словами сообщить итог, решает сервис: у
 * каждого свой предел на сервере и свой язык интерфейса.
 *
 * Вставленный текст приносит пустые строки не только в виде `\n\n`, но и
 * строками из пробелов и табуляций: для регулярного выражения `\n{3,}` это
 * не пустая строка, для человека — дыра в тексте. Поэтому пустой здесь
 * считается строка без видимых знаков.
 */

export interface BlankLinesResult {
  /** Текст после уборки. */
  text: string;
  /** Сколько пустых строк убрано — это показывается человеку. */
  removed: number;
}

/**
 * Убрать лишние пустые строки, оставив между абзацами не больше `keep`.
 *
 * Строки с содержимым не меняются вовсе: уборка занимается пустотой, а не
 * словами. Оставленная пустая строка становится действительно пустой —
 * пробелы и табуляции в ней не видны, но мешают следующей уборке и
 * серверному схлопыванию.
 *
 * Пустые строки в начале и в конце убираются всегда: сверху и снизу
 * абзацев, между которыми надо оставить воздух, нет.
 *
 * `keep` больше фактического числа пустых строк ничего не добавляет: это
 * «убрать лишние», а не «расставить отступы». Отрицательный, дробный или
 * нечисловой `keep` понимается как ближайшее допустимое целое, не меньше 0.
 */
export function collapseBlankLines(value: string, keep = 0): BlankLinesResult {
  const limit = Number.isFinite(keep) ? Math.max(0, Math.trunc(keep)) : 0;
  const normalized = value.replace(/\r\n?/g, '\n');
  const lines = normalized.split('\n');

  const out: string[] = [];
  let pending = 0;
  let seenContent = false;

  for (const line of lines) {
    if (line.trim() === '') {
      pending += 1;
      continue;
    }
    if (seenContent) {
      // До первой строки с содержимым пустота не разделяет ничего, поэтому
      // оставлять её незачем — как и в самом конце текста.
      for (let index = 0; index < Math.min(pending, limit); index += 1) {
        out.push('');
      }
    }
    pending = 0;
    seenContent = true;
    out.push(line);
  }

  const text = out.join('\n');
  // Считаем по числу строк: убираем мы только строки, а оставленную пустую
  // всего лишь очищаем от пробелов — это не «убрано». Текст, который уборка
  // не изменила, не убрал ничего, и пустой текст в том числе.
  return { text, removed: text === normalized ? 0 : lines.length - out.length };
}
