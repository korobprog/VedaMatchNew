/**
 * Состояние задачи одним кодом — портальное понятие, а не сервисное (VED-311,
 * VED-320).
 *
 * Живёт здесь, а не в `work.ts` и не в `notifications.ts`, потому что читают
 * его двое и с разных сторон: доска «Работа» подписывает им карточку в
 * планировщике, лента уведомлений — новость об этой же карточке. Пока тип
 * назывался `NotificationMark` и лежал у уведомлений, «Работе» пришлось бы
 * импортировать чужой тип, а это контракт сервисного модуля запрещает.
 *
 * Коды, а не русские слова: подписи и цвета собирает клиент — это правило
 * всего портала. Один код — один вид, и именно поэтому расхождение «в ленте
 * Тестирование, а на карточке На доработку» вылечено не двумя правками
 * подписей, а тем, что источник кода теперь один.
 *
 * Список закрытый и короткий намеренно: это четыре состояния, которые назвал
 * заказчик, а не справочник колонок доски. Колонку человек называет как хочет,
 * незнакомое название остаётся без ярлыка — так честнее, чем подписать чужой
 * «Бэклог» одним из наших четырёх слов.
 */
export type TaskStatusMark =
  /** «В работе» — за карточку взялись. */
  | 'in_progress'
  /** «На тестирование» — сделанное просят проверить. */
  | 'testing'
  /** «На проверке» — сделанное смотрит проверяющий (VED-487). */
  | 'review'
  /** «Выполнено» — карточка закрыта. */
  | 'done'
  /** «На доработку» — сделанное вернули. */
  | 'rework';

/**
 * Строка из базы или из чужой сборки — в код состояния. `null` — значения нет
 * либо оно не из нынешней четвёрки.
 *
 * Нужна на обоих концах: в `NotificationItem.mark` состояние лежит строкой, а
 * не энумом (набор меняется вместе с клиентами), и запись, сделанную сборкой с
 * другим набором, нельзя отдавать клиенту неизвестным кодом.
 */
export function parseTaskStatusMark(
  value: string | null | undefined,
): TaskStatusMark | null {
  switch (value) {
    case 'in_progress':
    case 'testing':
    case 'review':
    case 'done':
    case 'rework':
      return value;
    default:
      return null;
  }
}
